#!/usr/bin/env python3
"""Operationalization and executable-blueprint extension for research design v4.

The authoritative facts remain in ``research_design.json``.  This module adds
stable OPR/STEP identities and validates the complete claim-to-action path; it
does not persist a compiled protocol or create another workflow stage.
"""

from __future__ import annotations

import json
import importlib.util
import re
import sys
from copy import deepcopy
from pathlib import Path, PurePosixPath
from typing import Any, Iterable, Mapping


SCHEMA_VERSION = "cnki-research-design/v4"
SCHEMA_ASSET_PATH = (
    Path(__file__).resolve().parent.parent
    / "references"
    / "schemas"
    / "cnki-research-design-v4.schema.json"
)
OPERATION_SCHEMA_VERSION = "method-operation/v1"
EMPIRICAL_ROOT = Path(__file__).resolve().parents[2] / "empirical-research"
ADAPTER_REGISTRY_PATH = EMPIRICAL_ROOT / "references" / "method-adapter-registry.json"
RESEARCHER_DISPATCH_PATH = EMPIRICAL_ROOT / "scripts" / "researcher_dispatch.py"
OPERATIONALIZATION_VIEW_REL = Path("operationalization_matrix.md")
PROTOCOL_VIEW_REL = Path("execution_protocol.md")
GENERATED_MARKER = "<!-- generated by research_design.py from research_design.json; do not edit -->"

OPR_ID = re.compile(r"^OPR-[A-Z0-9][A-Z0-9_-]*$")
STEP_ID = re.compile(r"^STEP-[A-Z0-9][A-Z0-9_-]*$")
FAILURE_CODE = re.compile(r"^([A-Z][A-Z0-9_]*)\.([A-Z0-9][A-Z0-9_.-]*)$")
CLAIM_ROUTE = re.compile(r"^(?:retain|narrow|withdraw):([A-Za-z0-9_-]+)$")
FIXED_ROUTES = {
    "retry",
    "replace-implementation",
    "reopen:acquisition",
    "reopen:research",
    "reopen:design",
    "human-review",
}


class V4ContractError(ValueError):
    pass


_RESEARCHER_DISPATCH_MODULE: Any | None = None


def researcher_dispatch_module() -> Any:
    global _RESEARCHER_DISPATCH_MODULE
    if _RESEARCHER_DISPATCH_MODULE is not None:
        return _RESEARCHER_DISPATCH_MODULE
    if not RESEARCHER_DISPATCH_PATH.is_file():
        raise V4ContractError(f"Researcher dispatch compiler is missing: {RESEARCHER_DISPATCH_PATH}")
    module_name = "_avereth_design_researcher_dispatch"
    spec = importlib.util.spec_from_file_location(module_name, RESEARCHER_DISPATCH_PATH)
    if spec is None or spec.loader is None:
        raise V4ContractError("Could not load the researcher dispatch compiler")
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    try:
        spec.loader.exec_module(module)
    except Exception as exc:
        sys.modules.pop(module_name, None)
        raise V4ContractError(f"Could not load the researcher dispatch compiler: {exc}") from exc
    _RESEARCHER_DISPATCH_MODULE = module
    return module


def _text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value.strip()
    if isinstance(value, (dict, list, tuple)):
        return json.dumps(value, ensure_ascii=False, sort_keys=True)
    return str(value).strip()


def _substantive(value: Any) -> bool:
    text = _text(value).casefold()
    return bool(text) and not text.startswith("needs-review") and text not in {
        "todo",
        "tbd",
        "unknown",
        "待确认",
        "待核实",
    }


def _add(result: Any, code: str, severity: str, message: str, path: str) -> None:
    result.add(code, severity, message, path)


def _load_json(path: Path) -> Mapping[str, Any]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, json.JSONDecodeError) as exc:
        raise V4ContractError(f"Could not read JSON asset {path}: {exc}") from exc
    if not isinstance(payload, Mapping):
        raise V4ContractError(f"JSON asset must contain an object: {path}")
    return payload


def load_adapter_registry() -> Mapping[str, Any]:
    registry = _load_json(ADAPTER_REGISTRY_PATH)
    if _text(registry.get("schema_version")) != "cnki-method-adapter-registry/v3":
        raise V4ContractError(
            "Research design v4 requires cnki-method-adapter-registry/v3"
        )
    if not isinstance(registry.get("families"), Mapping):
        raise V4ContractError("Method-adapter registry has no families")
    return registry


def _asset_path(raw: Any) -> Path:
    token = _text(raw)
    if not token:
        raise V4ContractError("Operation profile asset is not registered")
    path = Path(token)
    if path.is_absolute() or ".." in path.parts:
        raise V4ContractError(f"Unsafe operation profile asset path: {token}")
    resolved = (EMPIRICAL_ROOT / path).resolve()
    try:
        resolved.relative_to(EMPIRICAL_ROOT.resolve())
    except ValueError as exc:
        raise V4ContractError(f"Operation profile escapes empirical-research: {token}") from exc
    return resolved


def operation_profile(
    family: str,
    registry: Mapping[str, Any] | None = None,
) -> Mapping[str, Any]:
    active = registry or load_adapter_registry()
    if _text(active.get("schema_version")) != "cnki-method-adapter-registry/v3":
        raise V4ContractError(
            "Operation profiles require cnki-method-adapter-registry/v3"
        )
    families = active.get("families") if isinstance(active.get("families"), Mapping) else {}
    specification = families.get(family)
    if not isinstance(specification, Mapping):
        raise V4ContractError(f"Unknown method family {family!r}")
    path = _asset_path(specification.get("operation_profile_asset"))
    profile = _load_json(path)
    if _text(profile.get("schema_version")) != OPERATION_SCHEMA_VERSION:
        raise V4ContractError(f"Operation profile for {family!r} is not {OPERATION_SCHEMA_VERSION}")
    if _text(profile.get("family")) != family:
        raise V4ContractError(f"Operation profile family mismatch for {family!r}")
    return profile


def failure_taxonomy(
    registry: Mapping[str, Any] | None = None,
) -> Mapping[str, Any]:
    active = registry or load_adapter_registry()
    if _text(active.get("schema_version")) != "cnki-method-adapter-registry/v3":
        raise V4ContractError(
            "Failure taxonomy requires cnki-method-adapter-registry/v3"
        )
    raw = active.get("failure_taxonomy_asset") or "references/schemas/failure-taxonomy-v1.json"
    payload = _load_json(_asset_path(raw))
    if _text(payload.get("schema_version")) != "failure-taxonomy/v1":
        raise V4ContractError("Failure taxonomy is not failure-taxonomy/v1")
    if not isinstance(payload.get("namespaces"), Mapping):
        raise V4ContractError("Failure taxonomy has no namespaces")
    return payload


def project_to_v3(payload: Mapping[str, Any]) -> dict[str, Any]:
    projected = deepcopy(dict(payload))
    projected["schema_version"] = "cnki-research-design/v3"
    projected.pop("operationalizations", None)
    projected.pop("execution_blueprint", None)
    return projected


def cross_artifact_projection(payload: Mapping[str, Any], v2: Any, v3: Any) -> Mapping[str, Any]:
    return v3.cross_artifact_projection(project_to_v3(payload), v2)


def _ids(values: Any) -> set[str]:
    if not isinstance(values, list):
        return set()
    return {_text(value).upper() for value in values if _text(value)}


def _require_text(result: Any, value: Any, path: str, *, code: str) -> None:
    if not _substantive(value):
        _add(result, code, "ERROR", "A substantive value is required", path)


def _validate_refs(
    result: Any,
    values: Any,
    known: set[str],
    path: str,
    *,
    required: bool = False,
) -> set[str]:
    if not isinstance(values, list):
        _add(result, "RD.OPR.FIELD_INVALID", "ERROR", "Reference field must be an array", path)
        return set()
    found = _ids(values)
    if required and not found:
        _add(result, "RD.OPR.REF_MISSING", "ERROR", "At least one reference is required", path)
    unknown = sorted(found - known)
    if unknown:
        _add(result, "RD.OPR.REF_UNRESOLVED", "ERROR", f"Unknown references: {', '.join(unknown)}", path)
    return found


def _safe_relative(raw: Any) -> bool:
    token = _text(raw).replace("\\", "/")
    if not token or token.startswith("/") or re.match(r"^[A-Za-z]:", token):
        return False
    path = PurePosixPath(token)
    return ".." not in path.parts and "." not in path.parts


def _valid_route(route: str, claims: set[str]) -> bool:
    if route in FIXED_ROUTES:
        return True
    match = CLAIM_ROUTE.fullmatch(route)
    return bool(match and match.group(1).upper() in claims)


def _validate_failure_routes(
    result: Any,
    routes: Any,
    *,
    claims: set[str],
    namespaces: set[str],
    path: str,
) -> None:
    if not isinstance(routes, list) or not routes:
        _add(result, "RD.PROTOCOL.FAILURE_ROUTE_MISSING", "ERROR", "At least one typed failure route is required", path)
        return
    for index, item in enumerate(routes):
        item_path = f"{path}[{index}]"
        if not isinstance(item, Mapping):
            _add(result, "RD.PROTOCOL.FAILURE_ROUTE_INVALID", "ERROR", "Failure route must be an object", item_path)
            continue
        code = _text(item.get("code"))
        match = FAILURE_CODE.fullmatch(code)
        if not match or match.group(1) not in namespaces:
            _add(result, "RD.PROTOCOL.FAILURE_CODE_UNKNOWN", "ERROR", f"Unknown failure code namespace: {code!r}", f"{item_path}.code")
        route = _text(item.get("route"))
        if not _valid_route(route, claims):
            _add(result, "RD.PROTOCOL.FAILURE_ROUTE_INVALID", "ERROR", f"Unsupported failure route: {route!r}", f"{item_path}.route")


def _graph_ancestors(step_id: str, dependencies: Mapping[str, set[str]]) -> set[str]:
    found: set[str] = set()
    pending = list(dependencies.get(step_id, set()))
    while pending:
        current = pending.pop()
        if current in found:
            continue
        found.add(current)
        pending.extend(dependencies.get(current, set()))
    return found


def _validate_graph(
    result: Any,
    step_ids: set[str],
    dependencies: Mapping[str, set[str]],
) -> None:
    for step_id, required in dependencies.items():
        unknown = sorted(required - step_ids)
        if unknown:
            _add(result, "RD.PROTOCOL.PRECONDITION_UNKNOWN", "ERROR", f"Unknown prerequisite steps: {', '.join(unknown)}", f"execution_blueprint.steps[{step_id}].preconditions")
    visiting: set[str] = set()
    visited: set[str] = set()

    def visit(node: str) -> bool:
        if node in visiting:
            return True
        if node in visited:
            return False
        visiting.add(node)
        for parent in dependencies.get(node, set()):
            if parent in step_ids and visit(parent):
                return True
        visiting.remove(node)
        visited.add(node)
        return False

    for step_id in sorted(step_ids):
        if visit(step_id):
            _add(result, "RD.PROTOCOL.CYCLE", "ERROR", "Execution blueprint contains a dependency cycle", "execution_blueprint.steps")
            break


def validate_payload(
    base: Path,
    payload: Mapping[str, Any],
    *,
    stage: str,
    result: Any,
    v2: Any,
    v3: Any,
) -> dict[str, set[str]]:
    """Validate v4 by composing the frozen v3 contract with protocol checks."""

    if _text(payload.get("schema_version")) != SCHEMA_VERSION:
        _add(result, "RD.SCHEMA.UNSUPPORTED", "ERROR", f"Expected {SCHEMA_VERSION}", "schema_version")
        return {"all": set()}
    identifiers = v3.validate_payload(
        base,
        project_to_v3(payload),
        stage=stage,
        result=result,
        v2=v2,
    )
    questions = set(identifiers.get("research_questions", set()))
    concepts = set(identifiers.get("concepts", set()))
    claims = set(identifiers.get("claims", set()))
    evidence = set(identifiers.get("evidence", set()))
    designs = set(identifiers.get("method_routes", set()))
    material_plan = payload.get("material_plan") if isinstance(payload.get("material_plan"), Mapping) else {}
    materials = {
        _text(item.get("material_id") or item.get("id")).upper()
        for item in material_plan.get("material_refs") or []
        if isinstance(item, Mapping) and _text(item.get("material_id") or item.get("id"))
    }
    claim_types = {
        _text(item.get("id")).upper(): _text(item.get("type"))
        for item in payload.get("claims") or []
        if isinstance(item, Mapping) and _text(item.get("id"))
    }
    routes = {
        _text(item.get("id")).upper(): item
        for item in payload.get("method_routes") or []
        if isinstance(item, Mapping) and _text(item.get("id"))
    }
    empirical_designs = {
        design_id
        for design_id, route in routes.items()
        if bool(route.get("empirical"))
    }
    empirical_claims = {
        _text(claim_id).upper()
        for design_id in empirical_designs
        for claim_id in routes[design_id].get("claim_ids") or []
        if _text(claim_id)
    }
    try:
        registry = load_adapter_registry()
        taxonomy = failure_taxonomy(registry)
    except V4ContractError as exc:
        _add(result, "RD.PROTOCOL.REGISTRY_INVALID", "ERROR", str(exc), "execution_blueprint")
        return identifiers
    namespaces = set(taxonomy.get("namespaces") or {})

    operationalizations = payload.get("operationalizations")
    if not isinstance(operationalizations, list) or not operationalizations:
        _add(result, "RD.OPR.MISSING", "ERROR", "Every v4 design needs operationalizations", "operationalizations")
        operationalizations = []
    opr_ids: set[str] = set()
    opr_claims: dict[str, set[str]] = {}
    opr_materials: dict[str, set[str]] = {}
    opr_evidence: dict[str, set[str]] = {}
    covered_claims: set[str] = set()
    for index, item in enumerate(operationalizations):
        prefix = f"operationalizations[{index}]"
        if not isinstance(item, Mapping):
            _add(result, "RD.OPR.FIELD_INVALID", "ERROR", "Operationalization must be an object", prefix)
            continue
        identifier = _text(item.get("id")).upper()
        if not OPR_ID.fullmatch(identifier):
            _add(result, "RD.OPR.ID_INVALID", "ERROR", f"Invalid OPR identity: {identifier!r}", f"{prefix}.id")
            continue
        if identifier in opr_ids or identifier in identifiers.get("all", set()):
            _add(result, "RD.ID.DUPLICATE", "ERROR", f"Duplicate global ID {identifier!r}", f"{prefix}.id")
        opr_ids.add(identifier)
        qrefs = _validate_refs(result, item.get("question_ids"), questions, f"{prefix}.question_ids", required=True)
        crefs = _validate_refs(result, item.get("claim_ids"), claims, f"{prefix}.claim_ids", required=True)
        _ = qrefs
        concept = _text(item.get("concept_id")).upper()
        if concept not in concepts:
            _add(result, "RD.OPR.CONCEPT_UNRESOLVED", "ERROR", f"Unknown concept {concept!r}", f"{prefix}.concept_id")
        mrefs = _validate_refs(result, item.get("material_ids"), materials, f"{prefix}.material_ids") if materials else _ids(item.get("material_ids"))
        erefs = _validate_refs(result, item.get("evidence_ids"), evidence, f"{prefix}.evidence_ids")
        if crefs & empirical_claims and not mrefs:
            _add(
                result,
                "RD.OPR.EMPIRICAL_MATERIAL_MISSING",
                "ERROR",
                "Empirical operationalization must bind at least one Material ID",
                f"{prefix}.material_ids",
            )
        if not (mrefs or erefs):
            _add(result, "RD.OPR.MATERIAL_PATH_MISSING", "ERROR", "Operationalization must bind material or evidence identities", prefix)
        for field in ("dimension", "observable", "unit_of_analysis", "extraction_rule", "transformation_rule"):
            _require_text(result, item.get(field), f"{prefix}.{field}", code="RD.OPR.FIELD_MISSING")
        recognition = item.get("recognition_or_measurement_rule")
        if not isinstance(recognition, Mapping):
            _add(result, "RD.OPR.RULE_MISSING", "ERROR", "Recognition or measurement rule must be an object", f"{prefix}.recognition_or_measurement_rule")
        else:
            _require_text(result, recognition.get("type"), f"{prefix}.recognition_or_measurement_rule.type", code="RD.OPR.RULE_MISSING")
            _require_text(result, recognition.get("rule"), f"{prefix}.recognition_or_measurement_rule.rule", code="RD.OPR.RULE_MISSING")
        checks = item.get("quality_checks")
        if not isinstance(checks, list) or not checks or not all(_substantive(value) for value in checks):
            _add(result, "RD.OPR.QUALITY_CHECK_MISSING", "ERROR", "Operationalization needs substantive quality checks", f"{prefix}.quality_checks")
        for field_name in ("decision_rule", "failure_consequence"):
            value = item.get(field_name)
            required = ("support", "contradict", "inconclusive") if field_name == "decision_rule" else ("contradict", "inconclusive")
            if not isinstance(value, Mapping) or any(not _substantive(value.get(key)) for key in required):
                _add(result, "RD.OPR.DECISION_RULE_MISSING", "ERROR", f"{field_name} is incomplete", f"{prefix}.{field_name}")
        expected_type = _text(item.get("expected_result_type"))
        linked_types = {claim_types.get(claim_id, "") for claim_id in crefs}
        if not expected_type or expected_type not in linked_types:
            _add(result, "RD.OPR.RESULT_TYPE_DRIFT", "ERROR", "Expected result type must match a linked claim type", f"{prefix}.expected_result_type")
        opr_claims[identifier] = crefs
        opr_materials[identifier] = mrefs
        opr_evidence[identifier] = erefs
        covered_claims.update(crefs)
    missing_claims = sorted(claims - covered_claims)
    if missing_claims:
        _add(result, "RD.OPR.CLAIM_UNCOVERED", "ERROR", f"Active claims lack operationalization: {', '.join(missing_claims)}", "operationalizations")

    blueprint = payload.get("execution_blueprint")
    if not isinstance(blueprint, Mapping):
        _add(result, "RD.PROTOCOL.MISSING", "ERROR", "execution_blueprint is required", "execution_blueprint")
        return identifiers
    if _text(blueprint.get("schema_version")) != OPERATION_SCHEMA_VERSION:
        _add(result, "RD.PROTOCOL.SCHEMA_INVALID", "ERROR", f"execution_blueprint must use {OPERATION_SCHEMA_VERSION}", "execution_blueprint.schema_version")
    steps = blueprint.get("steps")
    if not isinstance(steps, list) or not steps:
        _add(result, "RD.PROTOCOL.STEP_MISSING", "ERROR", "Execution blueprint needs typed steps", "execution_blueprint.steps")
        return identifiers
    step_ids: set[str] = set()
    dependencies: dict[str, set[str]] = {}
    step_records: dict[str, Mapping[str, Any]] = {}
    operations_by_design: dict[str, set[str]] = {design: set() for design in designs}
    roles_by_design: dict[str, set[str]] = {design: set() for design in designs}
    mvmr_by_design: dict[str, set[str]] = {design: set() for design in designs}
    steps_by_opr: dict[str, set[str]] = {identifier: set() for identifier in opr_ids}
    for index, step in enumerate(steps):
        prefix = f"execution_blueprint.steps[{index}]"
        if not isinstance(step, Mapping):
            _add(result, "RD.PROTOCOL.STEP_INVALID", "ERROR", "Step must be an object", prefix)
            continue
        identifier = _text(step.get("id")).upper()
        if not STEP_ID.fullmatch(identifier):
            _add(result, "RD.PROTOCOL.STEP_ID_INVALID", "ERROR", f"Invalid STEP identity: {identifier!r}", f"{prefix}.id")
            continue
        if identifier in step_ids or identifier in identifiers.get("all", set()) or identifier in opr_ids:
            _add(result, "RD.ID.DUPLICATE", "ERROR", f"Duplicate global ID {identifier!r}", f"{prefix}.id")
        step_ids.add(identifier)
        step_records[identifier] = step
        design_id = _text(step.get("design_id")).upper()
        if design_id not in designs:
            _add(result, "RD.PROTOCOL.DESIGN_UNRESOLVED", "ERROR", f"Unknown Design ID {design_id!r}", f"{prefix}.design_id")
        claim_refs = _validate_refs(result, step.get("claim_ids"), claims, f"{prefix}.claim_ids", required=True)
        opr_refs = _validate_refs(result, step.get("operationalization_ids"), opr_ids, f"{prefix}.operationalization_ids", required=True)
        material_refs = _validate_refs(result, step.get("material_ids"), materials, f"{prefix}.material_ids") if materials else _ids(step.get("material_ids"))
        evidence_refs = _validate_refs(result, step.get("evidence_ids"), evidence, f"{prefix}.evidence_ids")
        for opr_id in opr_refs:
            steps_by_opr.setdefault(opr_id, set()).add(identifier)
            if not claim_refs <= opr_claims.get(opr_id, set()):
                _add(result, "RD.PROTOCOL.OPR_CLAIM_DRIFT", "ERROR", "Step claims exceed its operationalization", prefix)
            if opr_materials.get(opr_id) and not material_refs <= opr_materials.get(opr_id, set()):
                _add(result, "RD.PROTOCOL.OPR_MATERIAL_DRIFT", "ERROR", "Step materials exceed its operationalization", prefix)
            if opr_evidence.get(opr_id) and not evidence_refs <= opr_evidence.get(opr_id, set()):
                _add(result, "RD.PROTOCOL.OPR_EVIDENCE_DRIFT", "ERROR", "Step evidence exceeds its operationalization", prefix)
        run_kind = _text(step.get("run_kind"))
        if run_kind not in {"mvmr", "full"}:
            _add(result, "RD.PROTOCOL.RUN_KIND_INVALID", "ERROR", "run_kind must be mvmr or full", f"{prefix}.run_kind")
        elif run_kind == "mvmr" and design_id:
            mvmr_by_design.setdefault(design_id, set()).add(identifier)
            if design_id in empirical_designs and not material_refs:
                _add(
                    result,
                    "RD.PROTOCOL.MVMR_MATERIAL_MISSING",
                    "ERROR",
                    "Empirical MVMR step must bind at least one Material ID",
                    f"{prefix}.material_ids",
                )
        _require_text(result, step.get("goal"), f"{prefix}.goal", code="RD.PROTOCOL.GOAL_MISSING")
        for field_name in ("read_set", "write_set"):
            values = step.get(field_name)
            if not isinstance(values, list) or not values:
                _add(result, "RD.PROTOCOL.IO_MISSING", "ERROR", f"{field_name} must contain paths", f"{prefix}.{field_name}")
                continue
            for path_index, raw in enumerate(values):
                if not _safe_relative(raw):
                    _add(result, "RD.PROTOCOL.PATH_UNSAFE", "ERROR", f"Unsafe workspace-relative path: {_text(raw)!r}", f"{prefix}.{field_name}[{path_index}]")
        procedure = step.get("procedure")
        if not isinstance(procedure, Mapping):
            _add(result, "RD.PROTOCOL.PROCEDURE_MISSING", "ERROR", "Typed procedure is required", f"{prefix}.procedure")
            operation = ""
        else:
            for field_name in ("adapter", "operation", "parameters_ref"):
                _require_text(result, procedure.get(field_name), f"{prefix}.procedure.{field_name}", code="RD.PROTOCOL.PROCEDURE_MISSING")
            operation = _text(procedure.get("operation"))
            if design_id:
                operations_by_design.setdefault(design_id, set()).add(operation)
        try:
            risk_issues = researcher_dispatch_module().validate_risk_profile(
                step.get("researcher_risk"),
                path=f"{prefix}.researcher_risk",
            )
        except V4ContractError as exc:
            _add(result, "RD.RESEARCHER_RISK.COMPILER_INVALID", "ERROR", str(exc), f"{prefix}.researcher_risk")
            risk_issues = []
        for issue in risk_issues:
            _add(result, issue.code, "ERROR", issue.message, issue.path)
        expected = step.get("expected_artifacts")
        if not isinstance(expected, list) or not expected:
            _add(result, "RD.PROTOCOL.ARTIFACT_MISSING", "ERROR", "Step must declare expected artifacts", f"{prefix}.expected_artifacts")
        else:
            write_set = {_text(value).replace("\\", "/") for value in step.get("write_set") or []}
            for artifact_index, artifact in enumerate(expected):
                artifact_path = f"{prefix}.expected_artifacts[{artifact_index}]"
                if not isinstance(artifact, Mapping):
                    _add(result, "RD.PROTOCOL.ARTIFACT_INVALID", "ERROR", "Expected artifact must be an object", artifact_path)
                    continue
                for field_name in ("id", "role", "path"):
                    _require_text(result, artifact.get(field_name), f"{artifact_path}.{field_name}", code="RD.PROTOCOL.ARTIFACT_INVALID")
                role = _text(artifact.get("role"))
                path_value = _text(artifact.get("path")).replace("\\", "/")
                if design_id and role:
                    roles_by_design.setdefault(design_id, set()).add(role)
                if path_value and path_value not in write_set:
                    _add(result, "RD.PROTOCOL.ARTIFACT_WRITE_UNDECLARED", "ERROR", "Expected artifact path must be in write_set", f"{artifact_path}.path")
        checks = step.get("acceptance_checks")
        if not isinstance(checks, list) or not checks:
            _add(result, "RD.PROTOCOL.ACCEPTANCE_MISSING", "ERROR", "Step needs acceptance checks", f"{prefix}.acceptance_checks")
        else:
            for check_index, check in enumerate(checks):
                check_path = f"{prefix}.acceptance_checks[{check_index}]"
                if not isinstance(check, Mapping) or not _substantive(check.get("id")) or not _substantive(check.get("rule")):
                    _add(result, "RD.PROTOCOL.ACCEPTANCE_INVALID", "ERROR", "Acceptance check needs stable id and substantive rule", check_path)
        _validate_failure_routes(result, step.get("on_failure"), claims=claims, namespaces=namespaces, path=f"{prefix}.on_failure")
        disposition = step.get("result_disposition")
        if not isinstance(disposition, Mapping) or any(not _substantive(disposition.get(key)) for key in ("support", "contradict", "inconclusive")):
            _add(result, "RD.PROTOCOL.DISPOSITION_MISSING", "ERROR", "Step must declare support/contradict/inconclusive dispositions", f"{prefix}.result_disposition")
        prerequisites: set[str] = set()
        raw_preconditions = step.get("preconditions")
        if not isinstance(raw_preconditions, list):
            _add(result, "RD.PROTOCOL.PRECONDITION_INVALID", "ERROR", "preconditions must be an array", f"{prefix}.preconditions")
        else:
            for pre_index, precondition in enumerate(raw_preconditions):
                pre_path = f"{prefix}.preconditions[{pre_index}]"
                if not isinstance(precondition, Mapping):
                    _add(result, "RD.PROTOCOL.PRECONDITION_INVALID", "ERROR", "Precondition must be an object", pre_path)
                    continue
                parent = _text(precondition.get("step_id")).upper()
                if _text(precondition.get("required_status")) != "accepted":
                    _add(result, "RD.PROTOCOL.PRECONDITION_INVALID", "ERROR", "Only accepted prerequisites unlock a step", f"{pre_path}.required_status")
                if parent:
                    prerequisites.add(parent)
        dependencies[identifier] = prerequisites
    _validate_graph(result, step_ids, dependencies)

    for design_id, route in routes.items():
        family = _text(route.get("family"))
        try:
            profile = operation_profile(family, registry)
        except V4ContractError as exc:
            _add(result, "RD.PROTOCOL.PROFILE_INVALID", "ERROR", str(exc), f"method_routes[{design_id}]")
            continue
        required_operations = {_text(value) for value in profile.get("required_operation_kinds") or [] if _text(value)}
        required_roles = {_text(value) for value in profile.get("required_artifact_roles") or [] if _text(value)}
        missing_operations = sorted(required_operations - operations_by_design.get(design_id, set()))
        missing_roles = sorted(required_roles - roles_by_design.get(design_id, set()))
        if missing_operations:
            _add(result, "RD.PROTOCOL.OPERATION_INCOMPLETE", "ERROR", f"Route lacks required operations: {', '.join(missing_operations)}", f"method_routes[{design_id}]")
        if missing_roles:
            _add(result, "RD.PROTOCOL.ARTIFACT_ROLE_INCOMPLETE", "ERROR", f"Route lacks required artifact roles: {', '.join(missing_roles)}", f"method_routes[{design_id}]")
        mvmr_required = {
            _text(value)
            for value in ((profile.get("minimum_viable_run") or {}).get("required_operation_kinds") or [])
            if _text(value)
        }
        mvmr_operations = {
            _text((step_records[step_id].get("procedure") or {}).get("operation"))
            for step_id in mvmr_by_design.get(design_id, set())
            if isinstance(step_records.get(step_id), Mapping)
        }
        if not mvmr_by_design.get(design_id):
            _add(result, "RD.PROTOCOL.MVMR_MISSING", "ERROR", "Every method route needs an MVMR step", f"method_routes[{design_id}]")
        elif not mvmr_required <= mvmr_operations:
            _add(result, "RD.PROTOCOL.MVMR_INCOMPLETE", "ERROR", f"MVMR lacks required operations: {', '.join(sorted(mvmr_required - mvmr_operations))}", f"method_routes[{design_id}]")
        route_mvmr = mvmr_by_design.get(design_id, set())
        route_full = {
            step_id
            for step_id, step in step_records.items()
            if _text(step.get("design_id")).upper() == design_id
            and _text(step.get("run_kind")) == "full"
        }
        for step_id in route_mvmr:
            full_ancestors = _graph_ancestors(step_id, dependencies) & route_full
            if full_ancestors:
                _add(
                    result,
                    "RD.PROTOCOL.MVMR_AFTER_FULL",
                    "ERROR",
                    "MVMR operations cannot depend on full-run operations: "
                    + ", ".join(sorted(full_ancestors)),
                    f"execution_blueprint.steps[{step_id}]",
                )
        for step_id, step in step_records.items():
            if _text(step.get("design_id")).upper() != design_id or _text(step.get("run_kind")) != "full":
                continue
            missing_mvmr = route_mvmr - _graph_ancestors(step_id, dependencies)
            if missing_mvmr:
                _add(
                    result,
                    "RD.PROTOCOL.MVMR_NOT_PRECONDITION",
                    "ERROR",
                    "Full execution must depend on every accepted MVMR step; missing: "
                    + ", ".join(sorted(missing_mvmr)),
                    f"execution_blueprint.steps[{step_id}]",
                )

    for opr_id in sorted(opr_ids):
        if not steps_by_opr.get(opr_id):
            _add(result, "RD.PROTOCOL.OPR_UNPLANNED", "ERROR", f"Operationalization {opr_id} has no planned step", "execution_blueprint.steps")
    return identifiers


def _profile_operations(family: str, registry: Mapping[str, Any]) -> tuple[Mapping[str, Any], list[str], set[str]]:
    profile = operation_profile(family, registry)
    operations = [_text(value) for value in profile.get("required_operation_kinds") or [] if _text(value)]
    mvmr = {
        _text(value)
        for value in ((profile.get("minimum_viable_run") or {}).get("required_operation_kinds") or [])
        if _text(value)
    }
    if not operations:
        raise V4ContractError(f"Operation profile for {family!r} has no required operations")
    return profile, operations, mvmr


def _operationalizations_for_payload(payload: Mapping[str, Any]) -> list[dict[str, Any]]:
    concepts = [item for item in payload.get("concepts") or [] if isinstance(item, Mapping)]
    claims = [item for item in payload.get("claims") or [] if isinstance(item, Mapping)]
    material_plan = payload.get("material_plan") if isinstance(payload.get("material_plan"), Mapping) else {}
    materials = [
        _text(item.get("material_id") or item.get("id"))
        for item in material_plan.get("material_refs") or []
        if isinstance(item, Mapping) and _text(item.get("material_id") or item.get("id"))
    ]
    records: list[dict[str, Any]] = []
    for index, claim in enumerate(claims, 1):
        concept_ids = list(claim.get("concept_ids") or [])
        concept_id = _text(concept_ids[0]) if concept_ids else _text((concepts[0] if concepts else {}).get("id"))
        claim_id = _text(claim.get("id"))
        records.append(
            {
                "id": f"OPR-{index:03d}",
                "question_ids": list(claim.get("question_ids") or []),
                "claim_ids": [claim_id] if claim_id else [],
                "concept_id": concept_id,
                "dimension": "needs-review: concept dimension",
                "observable": "needs-review: observable phenomenon or argumentative implication",
                "recognition_or_measurement_rule": {
                    "type": "needs-review: rule type",
                    "rule": "needs-review: evidence-grounded recognition or measurement rule",
                },
                "unit_of_analysis": "needs-review: effective analysis unit",
                "material_ids": materials,
                "evidence_ids": list(claim.get("evidence_ids") or []),
                "extraction_rule": "needs-review: extraction or premise-registration rule",
                "transformation_rule": "needs-review: transformation or argumentative operation",
                "quality_checks": ["needs-review: method-specific quality diagnostic"],
                "decision_rule": {
                    "support": "needs-review: support condition",
                    "contradict": "needs-review: contradiction condition",
                    "inconclusive": "needs-review: inconclusive condition",
                },
                "failure_consequence": {
                    "contradict": f"narrow:{claim_id}" if claim_id else "human-review",
                    "inconclusive": "human-review",
                },
                "expected_result_type": _text(claim.get("type")),
            }
        )
    return records


def _blueprint_for_payload(payload: Mapping[str, Any]) -> dict[str, Any]:
    registry = load_adapter_registry()
    operationalizations = {
        claim_id: item
        for item in payload.get("operationalizations") or []
        if isinstance(item, Mapping)
        for claim_id in [_text(value).upper() for value in item.get("claim_ids") or []]
        if claim_id
    }
    steps: list[dict[str, Any]] = []
    sequence = 1
    for route_index, route in enumerate(payload.get("method_routes") or []):
        if not isinstance(route, Mapping):
            continue
        design_id = _text(route.get("id"))
        family = _text(route.get("family"))
        specification = (registry.get("families") or {}).get(family) or {}
        profile, operations, mvmr_operations = _profile_operations(family, registry)
        operations = [
            *[operation for operation in operations if operation in mvmr_operations],
            *[operation for operation in operations if operation not in mvmr_operations],
        ]
        roles = [_text(value) for value in profile.get("required_artifact_roles") or [] if _text(value)]
        adapter = _text(specification.get("top_level_engine")) or "empirical-research"
        route_claims = [_text(value) for value in route.get("claim_ids") or [] if _text(value)]
        failure_routes = deepcopy(list(profile.get("failure_routes") or []))
        for failure in failure_routes:
            if isinstance(failure, dict) and route_claims:
                failure["route"] = _text(failure.get("route")).replace(
                    "<Claim ID>", route_claims[0]
                )
        opr_records = [operationalizations.get(value.upper()) for value in route_claims]
        opr_records = [item for item in opr_records if isinstance(item, Mapping)]
        opr_ids = [_text(item.get("id")) for item in opr_records]
        material_ids = sorted({_text(value) for item in opr_records for value in item.get("material_ids") or [] if _text(value)})
        evidence_ids = sorted({_text(value) for item in opr_records for value in item.get("evidence_ids") or [] if _text(value)})
        previous: str | None = None
        route_mvmr_ids: list[str] = []
        for operation_index, operation in enumerate(operations, 1):
            step_id = f"STEP-{sequence:03d}"
            sequence += 1
            run_kind = "mvmr" if operation in mvmr_operations else "full"
            if run_kind == "mvmr":
                route_mvmr_ids.append(step_id)
            precondition_ids: list[str] = []
            if previous:
                precondition_ids.append(previous)
            if run_kind == "full" and not precondition_ids:
                precondition_ids.extend(route_mvmr_ids)
            artifact_path = f"repro/{family}/{design_id}/{step_id.lower()}-{operation}.json"
            assigned_roles = [roles[(operation_index - 1) % len(roles)]] if roles else ["method_artifact"]
            if operation_index == len(operations) and len(roles) > len(operations):
                assigned_roles.extend(roles[len(operations):])
            expected = [
                {
                    "id": f"ART-PLAN-{step_id[5:]}-{role_index:02d}",
                    "role": role,
                    "path": artifact_path,
                }
                for role_index, role in enumerate(assigned_roles, start=1)
            ]
            steps.append(
                {
                    "id": step_id,
                    "design_id": design_id,
                    "run_kind": run_kind,
                    "goal": f"needs-review: execute {operation} for {design_id}",
                    "claim_ids": route_claims,
                    "operationalization_ids": opr_ids,
                    "material_ids": material_ids,
                    "evidence_ids": evidence_ids,
                    "read_set": ["research_design.json", "reference_materials/"],
                    "write_set": [artifact_path],
                    "preconditions": [
                        {"step_id": parent, "required_status": "accepted"}
                        for parent in dict.fromkeys(precondition_ids)
                    ],
                    "procedure": {
                        "adapter": adapter,
                        "operation": operation,
                        "parameters_ref": f"/method_routes/{route_index}/method_fields",
                    },
                    "researcher_risk": {
                        "epistemic_fit": "independent_replication" if family in {"content_analysis", "text_as_data", "review", "comparative", "historical", "conceptual"} else "competing_readings" if family in {"grounded_theory", "interpretive", "discourse_analysis", "normative"} else "deterministic_recompute",
                        "interpretive_ambiguity": "moderate",
                        "consequence_of_error": "moderate",
                        "codebook_maturity": "provisional" if operation in {"codebook_freeze", "codebook_revision", "open_coding"} else "not_applicable",
                        "reference_basis": "model_constructed" if operation == "reference_validation" else "not_applicable",
                        "holdout_status": "planned" if operation in {"reference_validation", "domain_shift_test"} else "not_applicable",
                        "boundary_case_load": "high" if operation in {"boundary_case_test", "counterexample_search", "negative_case_search", "competing_reading_test", "context_boundary_audit", "error_analysis"} else "low",
                        "inference_distance": "one_step" if operation.endswith("disposition") or operation == "gap_test" else "direct",
                        "rationale": "needs-review: confirm the operation-specific ambiguity, error consequence, and epistemic fit before execution",
                    },
                    "expected_artifacts": expected,
                    "acceptance_checks": [
                        {"id": f"CHK-{step_id[5:]}-001", "rule": "needs-review: method-specific acceptance rule with locator"}
                    ],
                    "on_failure": failure_routes,
                    "result_disposition": {
                        "support": f"retain:{route_claims[0]}" if route_claims else "human-review",
                        "contradict": f"narrow:{route_claims[0]}" if route_claims else "human-review",
                        "inconclusive": "human-review",
                    },
                }
            )
            previous = step_id
    return {"schema_version": OPERATION_SCHEMA_VERSION, "steps": steps}


def template_payload(family: str, v2: Any, v3: Any) -> Mapping[str, Any]:
    payload = deepcopy(dict(v3.template_payload(family, v2)))
    payload["schema_version"] = SCHEMA_VERSION
    payload["operationalizations"] = _operationalizations_for_payload(payload)
    payload["execution_blueprint"] = _blueprint_for_payload(payload)
    return payload


def migrate_payload(payload: Mapping[str, Any], *, v2: Any, v3: Any) -> Mapping[str, Any]:
    """Conservatively migrate v1-v3 without inventing executable facts."""

    schema = _text(payload.get("schema_version"))
    if schema == SCHEMA_VERSION:
        return deepcopy(dict(payload))
    if schema in {"cnki-research-design/v1", "cnki-research-design/v2"}:
        migrated = deepcopy(dict(v3.migrate_payload(payload, v2=v2)))
    elif schema == "cnki-research-design/v3":
        migrated = deepcopy(dict(payload))
    else:
        raise V4ContractError(f"Cannot migrate unsupported design schema {schema!r}")
    migrated["schema_version"] = SCHEMA_VERSION
    migrated["status"] = "needs-review"
    migrated["operationalizations"] = _operationalizations_for_payload(migrated)
    migrated["execution_blueprint"] = _blueprint_for_payload(migrated)
    migration = dict(migrated.get("migration") or {})
    migration.update(
        {
            "from": schema,
            "to": SCHEMA_VERSION,
            "status": "needs-review",
            "note": (
                "Stable design identities were preserved. Operationalization and STEP shells "
                "remain needs-review; no legacy prose or action was promoted to an executable fact."
            ),
        }
    )
    migrated["migration"] = migration
    return migrated


def _md_cell(value: Any) -> str:
    return _text(value).replace("|", "\\|").replace("\n", "<br>") or "—"


def render_operationalization_matrix(payload: Mapping[str, Any]) -> str:
    lines = [
        GENERATED_MARKER,
        "# Operationalization Matrix",
        "",
        "| OPR | Questions | Claims | Concept | Dimension | Observable | Unit | Materials / Evidence | Result Type |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for item in payload.get("operationalizations") or []:
        if not isinstance(item, Mapping):
            continue
        lines.append(
            "| "
            + " | ".join(
                _md_cell(value)
                for value in (
                    item.get("id"),
                    ", ".join(item.get("question_ids") or []),
                    ", ".join(item.get("claim_ids") or []),
                    item.get("concept_id"),
                    item.get("dimension"),
                    item.get("observable"),
                    item.get("unit_of_analysis"),
                    ", ".join([*(item.get("material_ids") or []), *(item.get("evidence_ids") or [])]),
                    item.get("expected_result_type"),
                )
            )
            + " |"
        )
    lines.append("")
    return "\n".join(lines)


def render_execution_protocol(payload: Mapping[str, Any]) -> str:
    registry = load_adapter_registry()
    dispatch_compiler = researcher_dispatch_module()
    lines = [
        GENERATED_MARKER,
        "# Execution Protocol",
        "",
        "| STEP | Design | Kind | Operation | Researcher Mode | First-run Tasks | Post-run / Conditional Tasks | Risk Basis | Preconditions | Inputs | Outputs | Failure Routes |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    steps = (payload.get("execution_blueprint") or {}).get("steps") or []
    for item in steps:
        if not isinstance(item, Mapping):
            continue
        procedure = item.get("procedure") if isinstance(item.get("procedure"), Mapping) else {}
        dispatch = dispatch_compiler.compile_dispatch_decision(item, payload, registry)
        risk = dispatch.get("risk_profile") if isinstance(dispatch.get("risk_profile"), Mapping) else {}
        preconditions = [
            _text(value.get("step_id"))
            for value in item.get("preconditions") or []
            if isinstance(value, Mapping)
        ]
        failures = [
            f"{_text(value.get('code'))} → {_text(value.get('route'))}"
            for value in item.get("on_failure") or []
            if isinstance(value, Mapping)
        ]
        lines.append(
            "| "
            + " | ".join(
                _md_cell(value)
                for value in (
                    item.get("id"),
                    item.get("design_id"),
                    item.get("run_kind"),
                    procedure.get("operation"),
                    dispatch.get("mode"),
                    ", ".join(dispatch.get("task_kinds") or []),
                    "; ".join(
                        value
                        for value in (
                            "post=" + ",".join(dispatch.get("post_run_task_kinds") or []),
                            "conditional=" + ",".join(dispatch.get("conditional_task_kinds") or []),
                        )
                        if not value.endswith("=")
                    ),
                    "; ".join(
                        f"{field}={_text(risk.get(field))}"
                        for field in (
                            "interpretive_ambiguity",
                            "consequence_of_error",
                            "codebook_maturity",
                            "boundary_case_load",
                            "inference_distance",
                        )
                    ),
                    ", ".join(preconditions),
                    ", ".join(item.get("read_set") or []),
                    ", ".join(item.get("write_set") or []),
                    "; ".join(failures),
                )
            )
            + " |"
        )
    lines.append("")
    return "\n".join(lines)


def render_views(
    base: Path,
    payload: Mapping[str, Any],
    *,
    allow_unmanaged_replace: bool,
    v2: Any,
    v3: Any,
) -> list[Path]:
    written = v3.render_views(
        base,
        project_to_v3(payload),
        allow_unmanaged_replace=allow_unmanaged_replace,
        v2=v2,
    )
    rendered = {
        OPERATIONALIZATION_VIEW_REL: render_operationalization_matrix(payload),
        PROTOCOL_VIEW_REL: render_execution_protocol(payload),
    }
    for relative, content in rendered.items():
        target = base / relative
        if target.exists() and GENERATED_MARKER not in target.read_text(encoding="utf-8-sig", errors="ignore") and not allow_unmanaged_replace:
            raise V4ContractError(f"Refusing to overwrite hand-maintained view {target}; migrate explicitly first")
        v2._atomic_write_text(target, content)
    return [*written, *(base / relative for relative in rendered)]
