def is_content_provenance_url(value: Any) -> bool:
    if not is_http_url(value):
        return False
    try:
        host = (urlsplit(str(value or "")).hostname or "").lower()
    except ValueError:
        return False
    if host in {
        "scholar.google.com",
        "scholar.googleusercontent.com",
        "api.openalex.org",
        "openalex.org",
        "api.crossref.org",
        "doi.org",
        "dx.doi.org",
        "example.com",
        "example.net",
        "example.org",
        "localhost",
    }:
        return False
    if host.endswith((".example", ".invalid", ".test", ".localhost")):
        return False
    if host.split(".", 1)[0] in {"api", "metadata", "search", "scholar"}:
        return False
    return True


def related_origin_hosts(left: Any, right: Any) -> bool:
    left_host = canonical_origin_host(left)
    right_host = canonical_origin_host(right)
    if not left_host or not right_host:
        return False
    return (
        left_host == right_host
        or left_host.endswith("." + right_host)
        or right_host.endswith("." + left_host)
    )


def obvious_metadata_endpoint(value: Any) -> bool:
    try:
        parts = urlsplit(str(value or ""))
    except ValueError:
        return True
    host = (parts.hostname or "").lower()
    path = parts.path.lower()
    return (
        host.split(".", 1)[0] in {"api", "metadata", "search", "scholar"}
        or bool(
            re.search(
                r"/(?:api|metadata|search|export|citation|bibtex)(?:/|$)", path
            )
        )
    )


def is_http_url(value: Any) -> bool:
    try:
        parts = urlsplit(str(value or ""))
    except ValueError:
        return False
    return parts.scheme.lower() in {"http", "https"} and bool(parts.hostname)


def exact_result_count(value: Any) -> int | None:
    """Return a JSON integer count without accepting booleans or numeric text."""
    if isinstance(value, bool) or not isinstance(value, int):
        return None
    return value


def registry_target_matches_exception(registry_target: Any, exception_target: Any) -> bool:
    """Match a venue exactly, allowing only an explicit parenthetical target note."""
    registry_text = re.sub(r"\s+", " ", str(registry_target or "").strip()).casefold()
    exception_text = re.sub(r"\s+", " ", str(exception_target or "").strip()).casefold()
    if not registry_text or not exception_text:
        return False
    return registry_text == exception_text or registry_text.startswith(
        (exception_text + " (", exception_text + "（")
    )


def canonical_doi(value: Any) -> str:
    raw = re.sub(
        r"^(?:https?://(?:dx\.)?doi\.org/|doi:\s*)",
        "",
        str(value or "").strip(),
        flags=re.IGNORECASE,
    ).lower()
    return raw if STRICT_DOI_RE.fullmatch(raw) else ""


def query_contains_doi(query_text: Any, doi: str) -> bool:
    if not doi:
        return False
    return bool(
        re.search(
            rf"(?<![A-Za-z0-9]){re.escape(doi)}(?![-._;()/:A-Za-z0-9])",
            str(query_text or ""),
            re.IGNORECASE,
        )
    )


def target_exemplar_query_identifies_source(
    query: dict[str, Any], source: dict[str, Any]
) -> bool:
    """Require a positive query to identify the exemplar by strict DOI or full title."""
    doi = canonical_doi(source.get("doi"))
    query_text = normalized(query.get("query"))
    title = normalized(source.get("title"))
    return query_contains_doi(query.get("query"), doi) or (
        len(title) >= 12 and title in query_text
    )


def query_mentions_source_identity(query_text: Any, source: dict[str, Any]) -> bool:
    doi = canonical_doi(source.get("doi"))
    title = normalized(source.get("title"))
    return query_contains_doi(query_text, doi) or (
        len(title) >= 12 and title in normalized(query_text)
    )


def canonical_origin_host(value: Any) -> str:
    try:
        parts = urlsplit(str(value or ""))
    except ValueError:
        return ""
    if parts.scheme.lower() not in {"http", "https"}:
        return ""
    return (parts.hostname or "").lower().rstrip(".")


def canonical_allowed_host(value: Any) -> str:
    raw = str(value or "").strip().lower().rstrip(".")
    return raw if ORIGIN_HOST_RE.fullmatch(raw) else ""


def canonical_contract_value(field: str, value: Any) -> Any:
    if field in {"authorized_by", "scope", "activation_condition"}:
        return canonical_token(value)
    if field == "target_venue":
        return re.sub(r"\s+", " ", str(value or "").strip()).casefold()
    if field in {"exception_id", "authorized_at"}:
        return str(value or "").strip()
    if field == "cnki_probe_query_ids":
        if not isinstance(value, list):
            return None
        return tuple(sorted(str(item or "").strip() for item in value))
    if field == "allowed_channels":
        if not isinstance(value, list):
            return None
        return tuple(sorted(canonical_token(item) for item in value))
    if field == "allowed_origin_hosts":
        if not isinstance(value, list):
            return None
        return tuple(sorted(canonical_allowed_host(item) for item in value))
    if field == "required_count":
        return exact_result_count(value)
    if field == "require_not_for_citation":
        return value if isinstance(value, bool) else None
    return value


def target_exemplar_exception_issues(
    registry: dict[str, Any], source: dict[str, Any], config: dict[str, Any]
) -> list[str]:
    """Explain why a non-CNKI target exemplar does not qualify for the narrow exception.

    The exception waives only the source-level CNKI channel/provenance requirement.
    PDF integrity, sealing, title matching, distinctness, and tier counts remain in
    the normal validator.
    """
    issues: list[str] = []
    channel = canonical_token(source.get("channel"))
    if channel not in AUTHORIZED_EXTERNAL_TARGET_EXEMPLAR_CHANNELS:
        issues.append(
            "source channel is outside the publisher-official/lawful-institutional-repository whitelist"
        )

    verification = source.get("verification")
    if not isinstance(verification, dict):
        verification = {}
    exception_id = str(verification.get("acquisition_exception_id") or "").strip()
    if not exception_id:
        issues.append("verification.acquisition_exception_id is missing")
        return issues

    override = config.get("target_exemplar_acquisition_override")
    if not isinstance(override, dict):
        issues.append(
            "workflow_config.json target_exemplar_acquisition_override must be an object"
        )
        return issues
    override_id = str(override.get("exception_id") or "").strip()
    if override_id != exception_id:
        issues.append(
            "verification.acquisition_exception_id does not match the config authorization contract"
        )
        return issues

    raw_exceptions = registry.get("authorized_exceptions")
    if not isinstance(raw_exceptions, list):
        issues.append("registry authorized_exceptions must be a list")
        return issues
    matches = [
        item
        for item in raw_exceptions
        if isinstance(item, dict)
        and str(item.get("exception_id") or "").strip() == exception_id
    ]
    if len(matches) != 1:
        issues.append(
            f"acquisition exception {exception_id!r} must resolve to exactly one registry record"
        )
        return issues
    exception = matches[0]

    for field in TARGET_EXCEPTION_CONTRACT_FIELDS:
        config_value = canonical_contract_value(field, override.get(field))
        registry_value = canonical_contract_value(field, exception.get(field))
        if config_value != registry_value:
            issues.append(
                f"registry authorized exception field {field} differs from the config authorization contract"
            )

    if canonical_token(override.get("authorized_by")) != "user":
        issues.append("acquisition exception must be explicitly authorized_by=user")
    if not valid_iso_date(override.get("authorized_at")):
        issues.append("acquisition exception authorized_at must be an ISO date")
    if canonical_token(override.get("scope")) != "target-exemplar-channel":
        issues.append("acquisition exception scope must be target-exemplar-channel")
    if canonical_token(override.get("activation_condition")) != "completed-cnki-zero-result":
        issues.append(
            "acquisition exception activation_condition must be completed-cnki-zero-result"
        )

    exception_target = str(override.get("target_venue") or "").strip()
    if not registry_target_matches_exception(config.get("target_name"), exception_target):
        issues.append("acquisition exception target_venue does not match config target_name")
    if not registry_target_matches_exception(registry.get("target_name"), exception_target):
        issues.append("acquisition exception target_venue does not match registry target_name")
    if normalized(source.get("venue")) != normalized(exception_target):
        issues.append("source venue does not exactly match the authorized target_venue")

    raw_allowed_channels = override.get("allowed_channels")
    allowed_channel_items = (
        [canonical_token(item) for item in raw_allowed_channels]
        if isinstance(raw_allowed_channels, list)
        else []
    )
    allowed_channels = set(allowed_channel_items)
    if (
        not allowed_channel_items
        or any(not item for item in allowed_channel_items)
        or len(allowed_channels) != len(allowed_channel_items)
        or not allowed_channels.issubset(AUTHORIZED_EXTERNAL_TARGET_EXEMPLAR_CHANNELS)
    ):
        issues.append(
            "acquisition exception allowed_channels must contain distinct members of the hard channel whitelist"
        )
    elif channel not in allowed_channels:
        issues.append("source channel is not authorized by this acquisition exception")

    raw_allowed_hosts = override.get("allowed_origin_hosts")
    allowed_host_items = (
        [canonical_allowed_host(item) for item in raw_allowed_hosts]
        if isinstance(raw_allowed_hosts, list)
        else []
    )
    allowed_hosts = set(allowed_host_items)
    if (
        not allowed_host_items
        or any(not item for item in allowed_host_items)
        or len(allowed_hosts) != len(allowed_host_items)
    ):
        issues.append(
            "acquisition exception allowed_origin_hosts must contain distinct exact hostnames"
        )

    required_count = exact_result_count(override.get("required_count"))
    config_tier = canonical_token(config.get("tier"))
    registry_tier = canonical_token(registry.get("tier"))
    if config_tier != registry_tier:
        issues.append(
            "acquisition exception requires registry tier to match the config authorization contract tier"
        )
    if required_count is None or required_count <= 0:
        issues.append("acquisition exception required_count must be a positive JSON integer")

    raw_sources = registry.get("sources")
    source_records = (
        [item for item in raw_sources if isinstance(item, dict)]
        if isinstance(raw_sources, list)
        else []
    )
    exception_linked_sources: list[dict[str, Any]] = []
    authorized_sources: list[dict[str, Any]] = []
    for candidate in source_records:
        candidate_verification = candidate.get("verification")
        if not isinstance(candidate_verification, dict):
            candidate_verification = {}
        if (
            str(candidate_verification.get("acquisition_exception_id") or "").strip()
            != exception_id
        ):
            continue
        exception_linked_sources.append(candidate)
        candidate_roles = {
            ROLE_ALIASES.get(normalized(item), normalized(item))
            for item in as_list(candidate.get("roles"))
        }
        if (
            "target-example" in candidate_roles
            and canonical_token(candidate.get("channel")) in allowed_channels
            and normalized(candidate.get("venue")) == normalized(exception_target)
            and canonical_token(candidate.get("citation_scope")) == "not-for-citation"
        ):
            authorized_sources.append(candidate)
    if required_count is not None and len(exception_linked_sources) != required_count:
        issues.append(
            "acquisition exception required_count does not equal the number of source records linked to it"
        )
    if len(authorized_sources) != len(exception_linked_sources):
        issues.append(
            "every source linked to the acquisition exception must be an eligible external target exemplar"
        )

    if override.get("require_not_for_citation") is not True:
        issues.append("target-exemplar channel exception must require not-for-citation scope")
    if canonical_token(source.get("citation_scope")) != "not-for-citation":
        issues.append("source using the channel exception must remain citation_scope=not-for-citation")
    source_host = canonical_origin_host(source.get("url"))
    if not source_host:
        issues.append("source using the channel exception must retain an HTTP(S) provenance URL")
    elif source_host not in allowed_hosts:
        issues.append("source URL host is not authorized by allowed_origin_hosts")
    content_host = canonical_origin_host(verification.get("content_url"))
    if not content_host:
        issues.append(
            "source using the channel exception must record verification.content_url as HTTP(S) provenance"
        )
    elif content_host not in allowed_hosts:
        issues.append(
            "verification.content_url host is not authorized by allowed_origin_hosts"
        )
    raw_source_doi = str(source.get("doi") or "").strip()
    if raw_source_doi and not canonical_doi(raw_source_doi):
        issues.append("source DOI is not a valid strict DOI identifier")

    queries = registry.get("queries")
    if not isinstance(queries, list):
        queries = []
    queries_by_id = {
        str(query.get("query_id") or "").strip(): query
        for query in queries
        if isinstance(query, dict) and str(query.get("query_id") or "").strip()
    }

    raw_probe_ids = override.get("cnki_probe_query_ids")
    probe_ids = (
        [str(item or "").strip() for item in raw_probe_ids]
        if isinstance(raw_probe_ids, list)
        else []
    )
    if not probe_ids or any(not item for item in probe_ids) or len(set(probe_ids)) != len(probe_ids):
        issues.append("acquisition exception must name distinct CNKI probe query IDs")
    else:
        saw_target_probe = False
        saw_bound_venue_probe = False
        normalized_target = normalized(exception_target)
        for query_id in probe_ids:
            query = queries_by_id.get(query_id)
            if query is None:
                issues.append(f"CNKI probe query {query_id} is absent from the registry")
                continue
            purpose = canonical_token(query.get("purpose"))
            saw_target_probe = saw_target_probe or purpose == "target-exemplar"
            if purpose not in {"venue", "target-exemplar"}:
                issues.append(
                    f"CNKI probe query {query_id} must have purpose=venue or target-exemplar"
                )
            if canonical_token(query.get("channel")) != "cnki":
                issues.append(f"CNKI probe query {query_id} must have channel=CNKI")
            if canonical_token(query.get("status")) != "complete":
                issues.append(f"CNKI probe query {query_id} is not complete")
            if exact_result_count(query.get("result_count")) != 0:
                issues.append(f"CNKI probe query {query_id} must record exact result_count=0")
            if query.get("result_count_is_approximate") is True:
                issues.append(f"CNKI probe query {query_id} cannot mark its zero count approximate")
            if not meaningful(query.get("query")) or not is_cnki_url(query.get("url")):
                issues.append(
                    f"CNKI probe query {query_id} lacks reproducible CNKI query provenance"
                )
            query_text = query.get("query")
            if purpose == "venue":
                if normalized_target and normalized_target in normalized(query_text):
                    saw_bound_venue_probe = True
            elif purpose == "target-exemplar" and not (
                normalized_target
                and normalized_target in normalized(query_text)
                or any(
                    query_mentions_source_identity(query_text, candidate)
                    for candidate in authorized_sources
                )
            ):
                issues.append(
                    f"target-exemplar CNKI probe query {query_id} is not bound to the target venue or an authorized exemplar title/DOI"
                )
        if not saw_bound_venue_probe:
            issues.append(
                "acquisition exception requires at least one purpose=venue CNKI probe naming target_venue"
            )
        if not saw_target_probe:
            issues.append("acquisition exception requires at least one target-exemplar CNKI probe")

    linked_query_ids = [
        str(item or "").strip() for item in as_list(source.get("query_ids")) if str(item or "").strip()
    ]
    real_target_queries: list[dict[str, Any]] = []
    for query_id in linked_query_ids:
        query = queries_by_id.get(query_id)
        if query is None:
            continue
        count = exact_result_count(query.get("result_count"))
        if not (
            canonical_token(query.get("purpose")) == "target-exemplar"
            and canonical_token(query.get("channel")) == channel
            and canonical_token(query.get("status")) == "complete"
            and count is not None
            and count > 0
            and meaningful(query.get("query"))
            and is_http_url(query.get("url"))
            and target_exemplar_query_identifies_source(query, source)
        ):
            continue
        if canonical_origin_host(query.get("url")) not in allowed_hosts:
            issues.append(
                f"positive target-exemplar query {query_id} URL host is not authorized by allowed_origin_hosts"
            )
            continue
        real_target_queries.append(query)
    if not real_target_queries:
        issues.append(
            "source is not linked to a complete positive-result target-exemplar query on its recorded channel"
        )
    return issues


def international_role_source_issues(
    registry: dict[str, Any],
    source: dict[str, Any],
    config: dict[str, Any],
    role: str,
    base: Path | None = None,
) -> list[str]:
    """Validate a source-neutral exemplar/SOTA role on the international track.

    Discovery services may establish query provenance, but a role-bearing source
    must resolve to DOI/publisher/lawful-OA content.  This is a normal evidence
    contract, not an exception to a failed CNKI contract.
    """
    issues: list[str] = []
    expected_purpose = {
        "target-example": "target-exemplar",
        "field-sota": "sota",
    }.get(role)
    if expected_purpose is None:
        return [f"unsupported international source role {role!r}"]

    channel = canonical_token(source.get("channel"))
    if channel not in INTERNATIONAL_CONTENT_CHANNELS:
        issues.append(
            "source channel must be DOI, publisher-official, scholarly-publisher, or lawful-OA/full-text provenance"
        )

    verification = source.get("verification")
    if not isinstance(verification, dict):
        verification = {}
    content_url = verification.get("content_url")
    if not is_content_provenance_url(content_url):
        issues.append(
            "verification.content_url must point to publisher or lawful-OA content, not a discovery/metadata page"
        )

    source_doi = canonical_doi(source.get("doi")) or canonical_doi(source.get("url"))
    if channel == "doi" and not source_doi:
        issues.append("channel=DOI requires a valid source DOI")
    if (
        channel != "doi"
        and not source_doi
        and is_content_provenance_url(content_url)
        and not related_origin_hosts(source.get("url"), content_url)
    ):
        issues.append(
            "source URL and verification.content_url must share publisher/repository provenance when no DOI is recorded"
        )
    method = canonical_token(verification.get("method"))
    if method in {"full-text", "pdf"} and obvious_metadata_endpoint(content_url):
        issues.append(
            f"verification.method={method} cannot use a metadata/search/export endpoint as the content artifact"
        )
    if role == "field-sota":
        if method not in {"full-text", "pdf"}:
            issues.append(
                "international field-sota must be verified from a locally retained full-text PDF"
            )
        if base is None:
            issues.append(
                "international field-sota validation requires the workspace base for its local full-text artifact"
            )
        else:
            artifact = valid_pdf(base, source.get("local_file"))
            digest = str(source.get("sha256") or "").strip().lower()
            if artifact is None:
                issues.append(
                    "international field-sota must retain a parseable workspace-local full-text PDF"
                )
            elif not pdf_content_verified(base, artifact, source):
                issues.append(
                    "international field-sota PDF has no verifiable article-body text; retain a text-bearing PDF or sealed OCR text sidecar"
                )
            if not re.fullmatch(r"[0-9a-f]{64}", digest):
                issues.append(
                    "international field-sota must retain a SHA-256 seal for its full-text PDF"
                )
            elif artifact is not None and sha256_file(artifact) != digest:
                issues.append(
                    "international field-sota full-text PDF SHA-256 does not match the registry"
                )
    retraction_status = canonical_token(verification.get("retraction_status"))
    if retraction_status not in INTERNATIONAL_ROLE_RETRACTION_STATUSES:
        issues.append(
            "international role source must record retraction_status=not-retracted or corrected-version-verified"
        )
    if not valid_iso_date(verification.get("retraction_checked_at")):
        issues.append(
            "international role source must record an ISO retraction_checked_at date"
        )

    target_name = str(config.get("target_name") or registry.get("target_name") or "").strip()
    if role == "target-example":
        if not target_name:
            issues.append("target-example contract has no target_name")
        elif normalized(source.get("venue")) != normalized(target_name):
            issues.append("source venue does not match the target journal")

    queries = registry.get("queries")
    if not isinstance(queries, list):
        queries = []
    queries_by_id = {
        str(query.get("query_id") or "").strip(): query
        for query in queries
        if isinstance(query, dict) and str(query.get("query_id") or "").strip()
    }
    linked_query_ids = [
        str(item or "").strip()
        for item in as_list(source.get("query_ids"))
        if str(item or "").strip()
    ]
    qualifying_queries: list[dict[str, Any]] = []
    for query_id in linked_query_ids:
        query = queries_by_id.get(query_id)
        if query is None:
            continue
        query_channel = canonical_token(query.get("channel"))
        count = exact_result_count(query.get("result_count"))
        if not (
            canonical_token(query.get("purpose")) == expected_purpose
            and query_channel != "cnki"
            and query_channel in INTERNATIONAL_ACADEMIC_CHANNELS
            and canonical_token(query.get("status")) == "complete"
            and count is not None
            and count > 0
            and meaningful(query.get("query"))
            and is_http_url(query.get("url"))
        ):
            continue
        if role == "target-example" and not target_exemplar_query_identifies_source(
            query, source
        ):
            continue
        if (
            role == "field-sota"
            and not source_doi
            and not query_mentions_source_identity(query.get("query"), source)
        ):
            continue
        qualifying_queries.append(query)
    if not qualifying_queries:
        issues.append(
            f"source is not linked to a complete positive-result international {expected_purpose} query"
        )
    return issues


