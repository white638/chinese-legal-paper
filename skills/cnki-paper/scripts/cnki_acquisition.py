def is_public_web_source(source: dict[str, Any]) -> bool:
    """Return whether v2 requires lateral credibility review for this source.

    The exemption is deliberately provenance-based: a generic ``web`` record
    cannot avoid review merely by self-labelling its credibility class as
    official. Official primary records must use an explicit official channel.
    """
    channel = canonical_token(source.get("channel"))
    if channel in {"cnki", *OFFICIAL_CHANNELS, *INTERNATIONAL_CONTENT_CHANNELS}:
        return False
    if channel in PUBLIC_WEB_CHANNELS:
        return True
    try:
        scheme = urlsplit(str(source.get("url") or "")).scheme.lower()
    except ValueError:
        return False
    return scheme in {"http", "https"}


