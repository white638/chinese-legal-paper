def _restore_transaction_state(state: dict[Path, bytes | None]) -> list[str]:
    issues: list[str] = []
    for path, content in state.items():
        recovery = path.with_name(path.name + ".txn-restore")
        try:
            if content is None:
                if path.exists():
                    path.unlink()
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                recovery.write_bytes(content)
                recovery.replace(path)
        except OSError as exc:
            issues.append(f"could not restore {path}: {exc}")
        finally:
            try:
                if recovery.exists():
                    recovery.unlink()
            except OSError as exc:
                issues.append(f"could not remove recovery file {recovery}: {exc}")
    return issues


def _transaction_drift_count(state: dict[Path, bytes | None]) -> int:
    changed = 0
    for path, content in state.items():
        try:
            current = path.read_bytes() if path.is_file() else None
        except OSError:
            changed += 1
            continue
        if current != content:
            changed += 1
    return changed


