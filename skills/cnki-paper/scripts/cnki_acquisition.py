def seal_registry(base: Path) -> int:
    path = registry_path(base)
    try:
        registry = load_json(path)
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 2
    if registry_schema(registry) == SCHEMA_VERSION_V1:
        registry, migrated_ids = migrate_registry_payload(registry)
        print(
            "Upgraded the v1 registry to v2 before sealing; "
            f"{len(migrated_ids)} public-web final-source record(s) remain needs-review."
        )
    elif registry_schema(registry) not in {SCHEMA_VERSION_V2, SCHEMA_VERSION_V3}:
        print(
            "seal supports only cnki-acquisition/v1, v2, or v3",
            file=sys.stderr,
        )
        return 2
    sources = registry.get("sources")
    if not isinstance(sources, list):
        print("registry sources must be a list", file=sys.stderr)
        return 2
    sealed = 0
    for source in sources:
        if not isinstance(source, dict) or not source.get("local_file"):
            continue
        pdf_path = valid_pdf(base, source.get("local_file"))
        if pdf_path is None:
            continue
        digest = sha256_file(pdf_path)
        if source.get("sha256") != digest:
            source["sha256"] = digest
            sealed += 1
    atomic_write_json(path, registry)
    print(f"Sealed {sealed} PDF record(s) with SHA-256.")
    return 0


def sync_index(base: Path, *, force: bool = False) -> int:
    try:
        registry = load_json(registry_path(base))
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 2
    path = base / INDEX_REL
    citation_path = base / CITATION_REL
    unmanaged_index = (
        path.exists()
        and GENERATED_MARKER not in path.read_text(encoding="utf-8-sig", errors="ignore")
    )
    unmanaged_citation = (
        citation_path.exists()
        and CITATION_GENERATED_MARKER
        not in citation_path.read_text(encoding="utf-8-sig", errors="ignore")
    )
    if (unmanaged_index or unmanaged_citation) and not force:
        targets = [
            str(candidate)
            for candidate, unmanaged in (
                (path, unmanaged_index),
                (citation_path, unmanaged_citation),
            )
            if unmanaged
        ]
        print(
            "Refusing to overwrite non-generated views: "
            + ", ".join(targets)
            + ". Migrate their records first, then rerun with --force.",
            file=sys.stderr,
        )
        return 2
    if unmanaged_citation:
        backup = base / CITATION_BACKUP_REL
        backup.parent.mkdir(parents=True, exist_ok=True)
        if not backup.exists():
            backup.write_text(
                citation_path.read_text(encoding="utf-8-sig", errors="ignore"),
                encoding="utf-8",
            )
            print(f"Backed up legacy citation view: {backup}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build_source_index(registry), encoding="utf-8")
    citation_path.write_text(build_citation_support_bank(registry), encoding="utf-8")
    print(f"Synchronized generated source index: {path}")
    print(f"Synchronized generated citation coverage view: {citation_path}")
    return 0


def role_from_legacy(value: str) -> str:
    token = canonical_token(value)
    return ROLE_ALIASES.get(token) or ROLE_ALIASES.get(normalized(value)) or "other"


def migrate_legacy_index(base: Path) -> int:
    destination = registry_path(base)
    if destination.exists():
        print(f"Registry already exists: {destination}", file=sys.stderr)
        return 2
    source_path = base / INDEX_REL
    if not source_path.exists():
        print(f"Legacy source index is missing: {source_path}", file=sys.stderr)
        return 2
    selected = None
    for headers, rows in markdown_tables(source_path.read_text(encoding="utf-8-sig", errors="ignore")):
        if (
            find_column(headers, {"Source ID", "来源编号", "文献编号"}) is not None
            and find_column(headers, {"Title/Name", "Title", "题名", "名称"}) is not None
            and find_column(headers, {"Origin/URL/Path", "Origin", "URL", "Path", "来源", "链接"}) is not None
        ):
            selected = (headers, rows)
            break
    if selected is None:
        print("Legacy source index has no recognizable source table.", file=sys.stderr)
        return 2
    headers, rows = selected
    indices = {
        "id": find_column(headers, {"Source ID", "来源编号", "文献编号"}),
        "type": find_column(headers, {"Type", "类型"}),
        "title": find_column(headers, {"Title/Name", "Title", "题名", "名称"}),
        "origin": find_column(headers, {"Origin/URL/Path", "Origin", "URL", "Path", "来源", "链接"}),
        "reason": find_column(headers, {"Why Included", "纳入理由"}),
        "local": find_column(headers, {"Local File/Note", "Local File", "本地文件", "文件/笔记"}),
        "used": find_column(headers, {"Used For", "用途"}),
    }
    config = load_config(base)
    migrated_sources: list[dict[str, Any]] = []
    for number, row in enumerate(rows, start=1):
        def cell(name: str) -> str:
            index = indices[name]
            return row[index].strip() if index is not None and index < len(row) else ""

        source_id = cell("id") or f"LEGACY-{number:03d}"
        origin = cell("origin")
        local = cell("local")
        pdf_match = re.search(r"(?i)([^;|<>]+?\.pdf)", local)
        local_file = pdf_match.group(1).strip().strip("`") if pdf_match else ""
        pdf_path = valid_pdf(base, local_file)
        source: dict[str, Any] = {
            "source_id": source_id,
            "channel": "CNKI" if is_cnki_url(origin) else "local",
            "roles": [role_from_legacy(cell("type"))],
            "title": cell("title"),
            "url": origin,
            "query_ids": [],
            "state": "pdf-downloaded" if pdf_path else "discovered",
            "verification": {"method": "", "verified_at": "", "support_claim": ""},
            "local_file": local_file,
            "citation_scope": "candidate-only",
            "reason": cell("reason"),
            "used_for": [cell("used")] if cell("used") else [],
            "collected_at": date.today().isoformat(),
        }
        if pdf_path:
            source["sha256"] = sha256_file(pdf_path)
        migrated_sources.append(source)
    payload = {
        "schema_version": SCHEMA_VERSION_V3,
        "target_name": str(config.get("target_name") or "").strip(),
        "tier": canonical_token(config.get("tier")),
        "access": {
            "status": "unknown",
            "method": "",
            "checked_at": "",
            "download_probe": {"status": "not-run", "url": ""},
        },
        "queries": [],
        "sources": migrated_sources,
    }
    atomic_write_json(destination, payload)
    print(f"Migrated {len(migrated_sources)} legacy row(s) into a blocking registry scaffold.")
    print("Add query provenance and real verification states, then run seal and sync --force.")
    return 0


def migrate_registry_payload(
    registry: dict[str, Any],
) -> tuple[dict[str, Any], list[str]]:
    """Conservatively migrate v1 to v2 without inventing credibility PASS."""
    migrated = json.loads(json.dumps(registry, ensure_ascii=False))
    migrated["schema_version"] = SCHEMA_VERSION_V2
    needs_review: list[str] = []
    sources = migrated.get("sources")
    if not isinstance(sources, list):
        sources = []
        migrated["sources"] = sources
    for source in sources:
        if not isinstance(source, dict):
            continue
        if (
            canonical_token(source.get("citation_scope")) != "final-source"
            or not is_public_web_source(source)
        ):
            continue
        source_id = str(source.get("source_id") or "").strip() or "<unknown>"
        needs_review.append(source_id)
        if not isinstance(source.get("credibility"), dict):
            source["credibility"] = {
                "source_class": "open-web",
                "authorship_publisher": "needs-review",
                "sponsorship_interest": "needs-review",
                "corroborating_source_ids": [],
                "contradicting_source_ids": [],
                "checked_at": "",
                "status": "needs-review",
                "note": (
                    "Migrated from cnki-acquisition/v1. Authorship, interests, and "
                    "lateral corroboration have not yet been established."
                ),
            }
        else:
            source["credibility"]["status"] = "needs-review"
    return migrated, needs_review


def migrate_registry_v3_payload(
    registry: dict[str, Any],
) -> tuple[dict[str, Any], list[str]]:
    """Migrate v1/v2 to v3 without inventing integration identities or PASS."""

    source_schema = registry_schema(registry)
    needs_review: list[str] = []
    if source_schema == SCHEMA_VERSION_V1:
        migrated, needs_review = migrate_registry_payload(registry)
    else:
        migrated = json.loads(json.dumps(registry, ensure_ascii=False))
    migrated["schema_version"] = SCHEMA_VERSION_V3
    return migrated, needs_review


def _migration_root_for(target_schema: str) -> Path:
    return MIGRATION_V2_REL if target_schema == SCHEMA_VERSION_V2 else MIGRATION_V3_REL


def rollback_registry(base: Path, manifest_path: Path) -> int:
    workspace = base.resolve()
    try:
        resolved_manifest = (
            manifest_path if manifest_path.is_absolute() else workspace / manifest_path
        ).resolve()
        allowed_roots = {
            (workspace / MIGRATION_V2_REL).resolve(),
            (workspace / MIGRATION_V3_REL).resolve(),
        }
        if resolved_manifest.parent not in allowed_roots:
            raise ValueError("migration manifest is outside the controlled acquisition migration directory")
        if not resolved_manifest.name.startswith("migration.") or resolved_manifest.suffix != ".json":
            raise ValueError("acquisition rollback requires a controlled migration manifest")
        manifest = load_json(resolved_manifest)
        if manifest.get("schema_version") != MIGRATION_MANIFEST_SCHEMA:
            raise ValueError("unsupported acquisition migration manifest schema")
        if manifest.get("registry") != REGISTRY_REL.as_posix():
            raise ValueError("migration manifest registry path is not canonical")
        backup_rel = Path(str(manifest.get("backup") or ""))
        backup_path = (workspace / backup_rel).resolve()
        if (
            backup_path.parent != resolved_manifest.parent
            or not backup_path.name.startswith("literature_registry.")
            or backup_path.suffix != ".json"
        ):
            raise ValueError("acquisition migration backup is outside the manifest directory")
        registry = registry_path(workspace)
        current_bytes = registry.read_bytes()
        backup_bytes = backup_path.read_bytes()
        current_sha = hashlib.sha256(current_bytes).hexdigest()
        backup_sha = hashlib.sha256(backup_bytes).hexdigest()
        if current_sha != manifest.get("target_sha256"):
            raise ValueError(
                "literature_registry.json changed after migration; refusing destructive rollback"
            )
        if backup_sha != manifest.get("source_sha256"):
            raise ValueError("acquisition migration backup digest does not match the manifest")
        report = {
            "schema_version": MIGRATION_ROLLBACK_SCHEMA,
            "status": "rolled-back",
            "manifest": resolved_manifest.relative_to(workspace).as_posix(),
            "restored_sha256": backup_sha,
            "writes": 1,
        }
        receipt_path = resolved_manifest.parent / "rollback_receipt.json"
        transaction_paths = [
            registry,
            receipt_path,
            _atomic_temp_path(registry),
            _atomic_temp_path(receipt_path),
        ]
        state = _capture_transaction_state(transaction_paths)
        try:
            atomic_write_bytes(registry, backup_bytes)
            atomic_write_json(receipt_path, report)
        except (OSError, ValueError) as exc:
            restore_issues = _restore_transaction_state(state)
            drift = _transaction_drift_count(state)
            blocked = {
                "schema_version": MIGRATION_ROLLBACK_SCHEMA,
                "status": "blocked",
                "issues": [str(exc), *restore_issues],
                "writes": drift,
                "transaction_restored": drift == 0 and not restore_issues,
            }
            print(json.dumps(blocked, ensure_ascii=False, indent=2), file=sys.stderr)
            return 2
        print(json.dumps(report, ensure_ascii=False, indent=2))
        return 0
    except (OSError, ValueError) as exc:
        print(
            json.dumps(
                {
                    "schema_version": MIGRATION_ROLLBACK_SCHEMA,
                    "status": "blocked",
                    "issues": [str(exc)],
                    "writes": 0,
                    "transaction_restored": True,
                },
                ensure_ascii=False,
                indent=2,
            ),
            file=sys.stderr,
        )
        return 2


def migrate_registry(
    base: Path,
    *,
    apply: bool,
    to: str = "v3",
    rollback_manifest: Path | None = None,
) -> int:
    if rollback_manifest is not None:
        return rollback_registry(base, rollback_manifest)
    if to not in {"v2", "v3"}:
        print("Supported acquisition migration targets are v2 and v3.", file=sys.stderr)
        return 2
    target_schema = SCHEMA_VERSION_V2 if to == "v2" else SCHEMA_VERSION_V3
    path = registry_path(base)
    try:
        source_bytes = path.read_bytes()
        registry = load_json(path)
    except (OSError, ValueError) as exc:
        print(exc, file=sys.stderr)
        return 2
    source_schema = registry_schema(registry)
    if source_schema == target_schema:
        plan = {
            "mode": "apply" if apply else "dry-run",
            "source_schema": source_schema,
            "target_schema": target_schema,
            "status": "already-current",
            "writes": 0,
            "needs_review_source_ids": [],
        }
        print(json.dumps(plan, ensure_ascii=False, indent=2))
        return 0
    if target_schema == SCHEMA_VERSION_V2 and source_schema == SCHEMA_VERSION_V1:
        migrated, needs_review = migrate_registry_payload(registry)
    elif target_schema == SCHEMA_VERSION_V3 and source_schema in {
        SCHEMA_VERSION_V1,
        SCHEMA_VERSION_V2,
    }:
        migrated, needs_review = migrate_registry_v3_payload(registry)
    else:
        print(
            f"Refusing acquisition migration from {source_schema!r} to {target_schema!r}.",
            file=sys.stderr,
        )
        return 2
    digest = hashlib.sha256(source_bytes).hexdigest()
    target_bytes = (
        json.dumps(migrated, ensure_ascii=False, indent=2) + "\n"
    ).encode("utf-8")
    target_digest = hashlib.sha256(target_bytes).hexdigest()
    migration_root = _migration_root_for(target_schema)
    source_label = source_schema.rsplit("/", 1)[-1]
    backup_rel = migration_root / f"literature_registry.{digest[:12]}.{source_label}.json"
    manifest_rel = migration_root / f"migration.{digest[:12]}.json"
    plan = {
        "mode": "apply" if apply else "dry-run",
        "source_schema": source_schema,
        "target_schema": target_schema,
        "status": "planned" if not apply else "applied",
        "registry": str(path),
        "backup": str(base / backup_rel),
        "manifest": str(base / manifest_rel),
        "source_sha256": digest,
        "target_sha256": target_digest,
        "writes": 0 if not apply else 3,
        "needs_review_source_ids": needs_review,
        "next_action": (
            "review every listed public-web source, then run sync and validate"
            if needs_review
            else "run sync and validate"
        ),
    }
    if apply:
        backup_path = base / backup_rel
        manifest_path = base / manifest_rel
        transaction_paths = [
            path,
            backup_path,
            manifest_path,
            _atomic_temp_path(path),
            _atomic_temp_path(backup_path),
            _atomic_temp_path(manifest_path),
        ]
        state = _capture_transaction_state(transaction_paths)
        migration_directory = base / migration_root
        directory_state = [
            (migration_directory, migration_directory.exists()),
            (migration_directory.parent, migration_directory.parent.exists()),
        ]
        try:
            if not backup_path.exists():
                atomic_write_bytes(backup_path, source_bytes)
            elif hashlib.sha256(backup_path.read_bytes()).hexdigest() != digest:
                raise ValueError("existing acquisition migration backup failed digest verification")
            manifest = {
                "schema_version": MIGRATION_MANIFEST_SCHEMA,
                "source_schema": source_schema,
                "target_schema": target_schema,
                "registry": REGISTRY_REL.as_posix(),
                "backup": backup_rel.as_posix(),
                "source_sha256": digest,
                "target_sha256": target_digest,
            }
            atomic_write_json(manifest_path, manifest)
            atomic_write_json(path, migrated)
            if hashlib.sha256(path.read_bytes()).hexdigest() != target_digest:
                raise ValueError("acquisition migration target digest verification failed")
        except (OSError, ValueError) as exc:
            restore_issues = _restore_transaction_state(state)
            cleanup_issues = _remove_new_empty_directories(directory_state)
            drift = _transaction_drift_count(state)
            report = {
                "schema_version": MIGRATION_MANIFEST_SCHEMA,
                "status": "blocked",
                "issues": [str(exc), *restore_issues, *cleanup_issues],
                "writes": drift,
                "transaction_restored": (
                    drift == 0 and not restore_issues and not cleanup_issues
                ),
            }
            print(json.dumps(report, ensure_ascii=False, indent=2), file=sys.stderr)
            return 2
    print(json.dumps(plan, ensure_ascii=False, indent=2))
    return 0


def validate_command(
    base: Path,
    *,
    write: bool,
    require_citations: bool,
    require_exemplars: bool,
) -> int:
    if write and (
        not (base / INDEX_REL).is_file()
        or not (base / CITATION_REL).is_file()
    ):
        sync_result = sync_index(base)
        if sync_result != 0:
            return sync_result
    result = validate_registry(
        base,
        require_citations=require_citations,
        require_exemplars=require_exemplars,
    )
    report = render_report(result)
    print(report)
    if write:
        path = base / REPORT_REL
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(report, encoding="utf-8")
    return 0 if result.ok else 1


