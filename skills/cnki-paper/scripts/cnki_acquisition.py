@dataclass
class ValidationResult:
    issues: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    stats: dict[str, int | str] = field(default_factory=dict)

    @property
    def ok(self) -> bool:
        return not self.issues


def normalized(value: Any) -> str:
    return re.sub(r"[^a-z0-9\u4e00-\u9fff]+", "", str(value or "").lower())


def canonical_token(value: Any) -> str:
    return re.sub(r"[_\s]+", "-", str(value or "").strip().lower())


def meaningful(value: Any) -> bool:
    return normalized(value) not in {normalized(item) for item in GENERIC}


def as_list(value: Any) -> list[Any]:
    if isinstance(value, list):
        return value
    if value in (None, ""):
        return []
    return [value]


def valid_iso_date(value: Any) -> bool:
    try:
        date.fromisoformat(str(value))
    except (TypeError, ValueError):
        return False
    return True


def valid_iso_datetime(value: Any) -> bool:
    text = str(value or "").strip()
    if "T" not in text:
        return False
    try:
        datetime.fromisoformat(text.replace("Z", "+00:00"))
    except ValueError:
        return False
    return True


def canonical_url(value: Any) -> str:
    raw = str(value or "").strip()
    try:
        parts = urlsplit(raw)
    except ValueError:
        return raw.lower()
    if not parts.scheme or not parts.netloc:
        return raw.lower()
    return urlunsplit((parts.scheme.lower(), parts.netloc.lower(), parts.path, parts.query, ""))


def is_cnki_url(value: Any) -> bool:
    try:
        host = urlsplit(str(value or "")).hostname.lower()
        return host == "cnki.net" or host.endswith(".cnki.net")
    except (AttributeError, ValueError):
        return False


def is_google_scholar_host_url(value: Any) -> bool:
    try:
        host = (urlsplit(str(value or "")).hostname or "").lower()
    except ValueError:
        return False
    return host in {"scholar.google.com", "scholar.googleusercontent.com"}


def is_google_scholar_query_url(value: Any) -> bool:
    try:
        parts = urlsplit(str(value or ""))
    except ValueError:
        return False
    if parts.scheme.lower() not in {"http", "https"}:
        return False
    if (parts.hostname or "").lower() != "scholar.google.com":
        return False
    if parts.path.rstrip("/") != "/scholar":
        return False
    query = parse_qs(parts.query).get("q", [""])[0]
    return meaningful(query)


def canonical_publication_track(value: Any) -> str:
    token = canonical_token(value)
    aliases = {
        "cnki": "cnki-cn",
        "cnki-chinese": "cnki-cn",
        "chinese": "cnki-cn",
        "international": "international-ssci",
        "ssci": "international-ssci",
        "internationalssci": "international-ssci",
    }
    return aliases.get(token, token)


def resolve_publication_track(
    config: dict[str, Any], registry: dict[str, Any] | None = None
) -> str:
    """Resolve the evidence ecosystem without breaking legacy CNKI workspaces."""
    for raw in (
        config.get("publication_track"),
        (registry or {}).get("publication_track"),
    ):
        track = canonical_publication_track(raw)
        if track in PUBLICATION_TRACKS:
            return track
    return LEGACY_PUBLICATION_TRACK


def publication_track_issues(
    config: dict[str, Any], registry: dict[str, Any]
) -> list[str]:
    issues: list[str] = []
    config_raw = config.get("publication_track")
    registry_raw = registry.get("publication_track")
    config_track = canonical_publication_track(config_raw)
    registry_track = canonical_publication_track(registry_raw)
    if config_raw not in (None, "") and config_track not in PUBLICATION_TRACKS:
        issues.append(
            "workflow_config.json publication_track must be cnki-cn, international-ssci, or mixed"
        )
    if registry_raw not in (None, "") and registry_track not in PUBLICATION_TRACKS:
        issues.append(
            "registry publication_track must be cnki-cn, international-ssci, or mixed"
        )
    if (
        config_track in PUBLICATION_TRACKS
        and registry_track in PUBLICATION_TRACKS
        and config_track != registry_track
    ):
        issues.append(
            "registry publication_track does not match workflow_config.json"
        )
    if config_raw in (None, "") and registry_track in {
        "international-ssci",
        "mixed",
    }:
        issues.append(
            "international-ssci and mixed workspaces must persist publication_track in both workflow_config.json and the registry"
        )
    if registry_raw in (None, "") and config_track in {
        "international-ssci",
        "mixed",
    }:
        issues.append(
            "international-ssci and mixed workspaces must persist publication_track in both workflow_config.json and the registry"
        )
    return issues


