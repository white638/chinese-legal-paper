def safe_local_path(base: Path, raw: Any) -> Path | None:
    value = unquote(str(raw or "").strip().strip("\"'<>")).replace("\\", "/")
    if not value or re.match(r"^[a-z][a-z0-9+.-]*://", value, re.IGNORECASE):
        return None
    candidate = Path(value)
    if candidate.is_absolute():
        return None
    root = base.resolve()
    path = (root / candidate).resolve()
    try:
        path.relative_to(root)
    except ValueError:
        return None
    return path


def structurally_parseable_pdf(path: Path) -> bool:
    """Reject header-only pseudo-PDFs while keeping the gate dependency-light."""
    required_tokens = {
        b"catalog": False,
        b"page": False,
        b"root": False,
        b"xref": False,
    }
    try:
        with path.open("rb") as handle:
            carry = b""
            for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                sample = carry + chunk
                compact = re.sub(rb"\s+", b" ", sample)
                required_tokens[b"catalog"] |= bool(
                    re.search(rb"/Type\s*/Catalog\b", compact)
                )
                required_tokens[b"page"] |= bool(
                    re.search(rb"/Type\s*/Pages?\b", compact)
                )
                required_tokens[b"root"] |= b"/Root" in sample
                required_tokens[b"xref"] |= bool(
                    re.search(rb"(?:^|[\r\n])xref(?:\s)", sample)
                    or re.search(rb"/Type\s*/XRef\b", compact)
                )
                carry = sample[-256:]
            handle.seek(max(0, path.stat().st_size - 4096))
            tail = handle.read()
    except OSError:
        return False
    if not all(required_tokens.values()) or b"startxref" not in tail or b"%%EOF" not in tail:
        return False

    try:
        from pypdf import PdfReader
    except ImportError:
        return True
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            reader = PdfReader(str(path), strict=False)
            if reader.is_encrypted and not reader.decrypt(""):
                return False
            if len(reader.pages) < 1:
                return False
            _ = reader.pages[0].mediabox
    except Exception:
        return False
    return True


def pdf_text_profile(path: Path, page_limit: int = 12) -> tuple[str, int, int]:
    """Return bounded text, text-bearing pages, and total pages."""
    try:
        from pypdf import PdfReader
    except ImportError:
        try:
            payload = path.read_bytes()
        except OSError:
            return "", 0, 0
        chunks = re.findall(rb"\(([^()]*)\)\s*(?:Tj|'|\")", payload)
        decoded_chunks = [
            chunk.decode("latin-1", errors="ignore") for chunk in chunks
        ]
        text = "\f".join(decoded_chunks)
        total_pages = len(re.findall(rb"/Type\s*/Page\b", payload))
        text_pages = min(
            total_pages,
            sum(len(normalized(chunk)) >= 80 for chunk in decoded_chunks),
        )
        return text, text_pages, total_pages
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            reader = PdfReader(str(path), strict=False)
            if reader.is_encrypted and not reader.decrypt(""):
                return "", 0, 0
            pages: list[str] = []
            text_pages = 0
            total_pages = len(reader.pages)
            leading = list(range(min(8, total_pages)))
            trailing = list(range(max(0, total_pages - 4), total_pages))
            page_indexes = list(dict.fromkeys((leading + trailing)[:page_limit]))
            for page_index in page_indexes:
                page = reader.pages[page_index]
                page_text = page.extract_text() or ""
                pages.append(page_text)
                if len(normalized(page_text)) >= 80:
                    text_pages += 1
            return "\f".join(pages), text_pages, total_pages
    except Exception:
        return "", 0, 0


def extracted_pdf_text(path: Path, page_limit: int = 12) -> str:
    """Return bounded PDF text for diagnostics and tests."""
    return pdf_text_profile(path, page_limit)[0]


def metadata_only_evidence(value: Any) -> bool:
    text = str(value or "")
    signals = (
        bool(re.search(r"metadata[ -]?only|metadata record|bibliographic metadata", text, re.IGNORECASE)),
        bool(re.search(r"abstract snippet|abstract[ -]?only|title.+authors?.+venue.+year", text, re.IGNORECASE | re.DOTALL)),
        bool(re.search(r"no (?:article )?body|no full[ -]?text|no article (?:sections?|references?)", text, re.IGNORECASE)),
    )
    return sum(signals) >= 2


def article_body_signals(value: Any) -> bool:
    """Distinguish a sampled article body from a padded bibliographic record."""
    text = str(value or "")
    body_text = re.sub(
        r"(?:\babstract\b|摘要).*?(?:\bkey\s*words?\b|关键词)\s*[:：]?[^\f\n]*",
        " ",
        text,
        flags=re.IGNORECASE | re.DOTALL,
    )
    compact_cjk = re.sub(r"\s+", "", body_text)
    explicit_references = bool(
        re.search(r"\breferences\b|\bbibliography\b", body_text, re.IGNORECASE)
        or "参考文献" in compact_cjk
    )
    # Chinese humanities and social-science journals may use per-page scholarly
    # footnotes instead of a terminal bibliography. Treat that established
    # reference apparatus as evidence only when several independent signals
    # co-occur; a title/abstract metadata wrapper must not satisfy this branch.
    circled_notes = len(re.findall(r"[①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳]", compact_cjk))
    cited_titles = len(re.findall(r"《[^》]{2,120}》", compact_cjk))
    dated_citations = len(
        re.findall(r"《[^》]{2,120}》[^。；;\f]{0,100}\d{4}年", compact_cjk)
    )
    footnote_references = (
        circled_notes >= 3 and cited_titles >= 3 and dated_citations >= 2
    )
    references = explicit_references or footnote_references
    introduction = bool(
        re.search(r"\bintroduction\b", body_text, re.IGNORECASE)
        or re.search(r"引言|导论|问题的提出", compact_cjk)
    )
    theory = bool(
        re.search(
            r"\btheor(?:y|etical framework)\b|\bconceptual framework\b",
            body_text,
            re.IGNORECASE,
        )
        or re.search(r"理论框架|分析框架", compact_cjk)
    )
    numbered_sections = (
        len(re.findall(r"[一二三四五六七八九十]{1,3}、", compact_cjk)) >= 2
    )
    body_sections = (
        bool(
            re.search(
                r"\bmethods?\b|\bdata\b|\bresearch design\b",
                body_text,
                re.IGNORECASE,
            )
            or re.search(r"研究方法|研究设计|数据与方法", compact_cjk)
        ),
        bool(
            re.search(
                r"\banalysis\b|\bresults?\b|\bfindings?\b",
                body_text,
                re.IGNORECASE,
            )
            or re.search(r"实证分析|案例分析|研究发现", compact_cjk)
        ),
        bool(
            re.search(
                r"\bdiscussion\b|\bconclusion\b",
                body_text,
                re.IGNORECASE,
            )
            or re.search(r"讨论|结论|结语", compact_cjk)
        ),
    )
    return references and (introduction or theory or numbered_sections) and sum(body_sections) >= 1


def pdf_content_verified(
    base: Path,
    pdf_path: Path,
    source: dict[str, Any] | None = None,
    minimum_chars: int = 1500,
) -> bool:
    """Require multi-page article text, with a sealed OCR sidecar for scans."""
    pdf_text, text_pages, total_pages = pdf_text_profile(pdf_path)
    verification = (source or {}).get("verification")
    if not isinstance(verification, dict):
        verification = {}
    if (
        total_pages >= 3
        and text_pages >= 3
        and len(normalized(pdf_text)) >= minimum_chars
        and article_body_signals(pdf_text)
        and not metadata_only_evidence(pdf_text)
        and not metadata_only_evidence(verification.get("support_claim"))
    ):
        return True
    ocr_path = safe_local_path(base, verification.get("ocr_text_file"))
    ocr_digest = str(verification.get("ocr_text_sha256") or "").strip().lower()
    if (
        ocr_path is None
        or ocr_path.suffix.lower() not in {".txt", ".md"}
        or not re.fullmatch(r"[0-9a-f]{64}", ocr_digest)
    ):
        return False
    try:
        if not ocr_path.is_file() or sha256_file(ocr_path) != ocr_digest:
            return False
        ocr_text = ocr_path.read_text(encoding="utf-8-sig", errors="ignore")
    except OSError:
        return False
    if str(verification.get("acquisition_exception_id") or "").strip():
        # A user-authorized target-exemplar channel exception may bind a venue
        # document that is not article-shaped (e.g. a call for papers when the
        # venue publishes no proceedings). The sealed sidecar must still
        # capture real full text; identity, venue, and channel checks stay in
        # the exception contract itself.
        return (
            total_pages >= 1
            and len(normalized(ocr_text)) >= 300
            and not metadata_only_evidence(ocr_text)
            and not metadata_only_evidence(verification.get("support_claim"))
        )
    return (
        total_pages >= 3
        and len(normalized(ocr_text)) >= minimum_chars
        and article_body_signals(ocr_text)
        and not metadata_only_evidence(ocr_text)
        and not metadata_only_evidence(verification.get("support_claim"))
    )


def valid_pdf(base: Path, raw: Any) -> Path | None:
    path = safe_local_path(base, raw)
    if path is None:
        return None
    try:
        if not path.is_file() or path.suffix.lower() != ".pdf" or path.stat().st_size < 32:
            return None
        with path.open("rb") as handle:
            if handle.read(5) != b"%PDF-":
                return None
            handle.seek(max(0, path.stat().st_size - 2048))
            if b"%%EOF" not in handle.read():
                return None
    except OSError:
        return None
    if not structurally_parseable_pdf(path):
        return None
    return path


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def normalized_roles(source: dict[str, Any]) -> list[str]:
    roles: list[str] = []
    for value in as_list(source.get("roles") or source.get("role")):
        token = canonical_token(value)
        alias = ROLE_ALIASES.get(token) or ROLE_ALIASES.get(normalized(value))
        roles.append(alias or token)
    return list(dict.fromkeys(role for role in roles if role))


def markdown_escape(value: Any) -> str:
    text = str(value or "").replace("\r", " ").replace("\n", " ").strip()
    return text.replace("\\", "\\\\").replace("|", r"\|")


def display_list(value: Any) -> str:
    return ", ".join(str(item).strip() for item in as_list(value) if str(item).strip())


