def _atomic_write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content.rstrip() + "\n")
        os.replace(temporary, path)
    except Exception:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def render_views(
    base: Path,
    payload: Mapping[str, Any],
    *,
    allow_unmanaged_replace: bool = False,
) -> list[Path]:
    rendered = {
        VIEW_RELS[0]: render_knowledge_matrix(payload),
        VIEW_RELS[1]: render_concept_register(payload),
        VIEW_RELS[2]: render_claim_matrix(payload),
        VIEW_RELS[3]: render_method_route_matrix(payload),
        VIEW_RELS[4]: render_integrity_view(payload),
    }
    for relative in rendered:
        path = base / relative
        if path.exists() and GENERATED_MARKER not in path.read_text(encoding="utf-8-sig", errors="ignore"):
            if not allow_unmanaged_replace:
                raise V2ContractError(
                    f"Refusing to overwrite hand-maintained view {path}; run migrate --apply first"
                )
    for relative, content in rendered.items():
        _atomic_write_text(base / relative, content)
    return [base / relative for relative in rendered]


