"""Read-only compilation of a v4 research design into executable work items."""

from __future__ import annotations

import hashlib
import importlib.util
import json
import sys
from copy import deepcopy
from dataclasses import asdict, dataclass
from pathlib import Path, PurePosixPath
from typing import Any, Mapping


PROTOCOL_SCHEMA = "avereth-research-protocol/v1"
PROTOCOL_CHECK_SCHEMA = "avereth-research-protocol-check/v1"
DESIGN_SCHEMA = "cnki-research-design/v4"
EXECUTION_SCHEMA = "cnki-method-execution/v3"
GENERATED_MARKER = "<!-- generated by avereth protocol from machine facts; do not edit -->"
NEXT_ACTION_REL = Path("next_action.md")
METHOD_EXECUTION_PATH = (
    Path(__file__).resolve().parents[4]
    / "empirical-research"
    / "scripts"
    / "method_execution.py"
)
METHOD_REGISTRY_PATH = (
    Path(__file__).resolve().parents[4]
    / "empirical-research"
    / "references"
    / "method-adapter-registry.json"
)
RESEARCHER_DISPATCH_PATH = (
    Path(__file__).resolve().parents[4]
    / "empirical-research"
    / "scripts"
    / "researcher_dispatch.py"
)
_METHOD_EXECUTION_MODULE: Any | None = None
_RESEARCHER_DISPATCH_MODULE: Any | None = None


class ProtocolCompilerError(ValueError):
    pass


@dataclass(frozen=True)
class ProtocolIssue:
    code: str
    message: str
    path: str = ""


def _text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value.strip()
    return str(value).strip()


def canonical_digest(value: Mapping[str, Any]) -> str:
    encoded = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(encoded.encode("utf-8")).hexdigest()


def _load_object(path: Path, *, required: bool) -> Mapping[str, Any] | None:
    if not path.is_file():
        if required:
            raise ProtocolCompilerError(f"Required machine fact is missing: {path}")
        return None
    try:
        payload = json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ProtocolCompilerError(f"Could not read JSON fact {path}: {exc}") from exc
    if not isinstance(payload, Mapping):
        raise ProtocolCompilerError(f"JSON fact must be an object: {path}")
    return payload


def load_facts(outdir: Path) -> tuple[Mapping[str, Any], Mapping[str, Any] | None]:
    base = outdir.resolve()
    design = _load_object(base / "research_design.json", required=True)
    assert design is not None
    execution = _load_object(base / "method_execution.json", required=False)
    return design, execution


def _method_execution_module() -> Any:
    """Load the single execution validator without creating a second contract."""

    global _METHOD_EXECUTION_MODULE
    if _METHOD_EXECUTION_MODULE is not None:
        return _METHOD_EXECUTION_MODULE
    if not METHOD_EXECUTION_PATH.is_file():
        raise ProtocolCompilerError(
            f"Canonical method execution validator is missing: {METHOD_EXECUTION_PATH}"
        )
    module_name = "_avereth_canonical_method_execution"
    spec = importlib.util.spec_from_file_location(module_name, METHOD_EXECUTION_PATH)
    if spec is None or spec.loader is None:
        raise ProtocolCompilerError(
            f"Could not load canonical method execution validator: {METHOD_EXECUTION_PATH}"
        )
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    try:
        spec.loader.exec_module(module)
    except Exception:
        sys.modules.pop(module_name, None)
        raise
    _METHOD_EXECUTION_MODULE = module
    return module


def _researcher_dispatch_module() -> Any:
    """Load the empirical-research-owned risk router without copying its policy."""

    global _RESEARCHER_DISPATCH_MODULE
    if _RESEARCHER_DISPATCH_MODULE is not None:
        return _RESEARCHER_DISPATCH_MODULE
    if not RESEARCHER_DISPATCH_PATH.is_file():
        raise ProtocolCompilerError(
            f"Researcher dispatch compiler is missing: {RESEARCHER_DISPATCH_PATH}"
        )
    module_name = "_avereth_researcher_dispatch"
    spec = importlib.util.spec_from_file_location(module_name, RESEARCHER_DISPATCH_PATH)
    if spec is None or spec.loader is None:
        raise ProtocolCompilerError(
            f"Could not load researcher dispatch compiler: {RESEARCHER_DISPATCH_PATH}"
        )
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    try:
        spec.loader.exec_module(module)
    except Exception:
        sys.modules.pop(module_name, None)
        raise
    _RESEARCHER_DISPATCH_MODULE = module
    return module


def _execution_validation_issues(
    base: Path,
    execution: Mapping[str, Any],
) -> list[ProtocolIssue]:
    """Project only canonical ERRORs; callers must invoke this before action reads."""

    try:
        validation = _method_execution_module().validate_incremental_payload(
            base,
            execution,
        )
    except Exception as exc:
        return [
            ProtocolIssue(
                "PROTOCOL.EXECUTION_VALIDATOR_FAILED",
                str(exc),
                "method_execution.json",
            )
        ]
    return [
        ProtocolIssue(
            _text(getattr(issue, "code", "")) or "PROTOCOL.EXECUTION_INVALID",
            _text(getattr(issue, "message", "")) or "Canonical method execution validation failed",
            _text(getattr(issue, "path", "")),
        )
        for issue in getattr(validation, "issues", [])
        if _text(getattr(issue, "severity", "")).upper() == "ERROR"
    ]


def _declared_support_by_design(design: Mapping[str, Any]) -> dict[str, str]:
    """Read support labels from the one adapter registry and project by design id."""

    try:
        registry = _load_object(METHOD_REGISTRY_PATH, required=True)
    except ProtocolCompilerError:
        return {}
    families = registry.get("families") if isinstance(registry, Mapping) else None
    if not isinstance(families, Mapping):
        return {}
    projected: dict[str, str] = {}
    for route in design.get("method_routes") or []:
        if not isinstance(route, Mapping):
            continue
        design_id = _text(route.get("id")).upper()
        family = _text(route.get("family"))
        specification = families.get(family)
        if not design_id or not isinstance(specification, Mapping):
            continue
        status = _text(specification.get("declared_support_status"))
        if status:
            projected[design_id] = status
    return projected


def _protocol_validation_issues(
    base: Path,
    design: Mapping[str, Any],
) -> list[ProtocolIssue]:
    issues: list[ProtocolIssue] = []
    if _text(design.get("schema_version")) != DESIGN_SCHEMA:
        return [
            ProtocolIssue(
                "PROTOCOL.DESIGN_MIGRATION_REQUIRED",
                f"Executable protocol compilation requires {DESIGN_SCHEMA}",
                "research_design.json",
            )
        ]
    if _text(design.get("status")) != "confirmed":
        issues.append(
            ProtocolIssue(
                "PROTOCOL.DESIGN_UNCONFIRMED",
                "Executable protocol compilation requires a confirmed research design",
                "research_design.json:status",
            )
        )
    try:
        import research_design  # type: ignore

        result = research_design.ValidationResult()
        research_design._v4_module().validate_payload(
            base,
            design,
            stage="design",
            result=result,
            v2=research_design._v2_module(),
            v3=research_design._v3_module(),
        )
    except (ImportError, OSError, ValueError) as exc:
        return [ProtocolIssue("PROTOCOL.VALIDATOR_FAILED", str(exc), "research_design.json")]
    for finding in result.issues:
        if finding.severity == "ERROR" and (
            finding.code.startswith("RD.OPR.")
            or finding.code.startswith("RD.PROTOCOL.")
            or finding.code == "RD.ID.DUPLICATE"
        ):
            issues.append(ProtocolIssue(finding.code, finding.message, finding.path))
    return issues


def validate_protocol(outdir: Path) -> dict[str, Any]:
    base = outdir.resolve()
    try:
        design, execution = load_facts(base)
    except ProtocolCompilerError as exc:
        issues = [ProtocolIssue("PROTOCOL.FACT_MISSING", str(exc))]
        return {
            "schema_version": PROTOCOL_CHECK_SCHEMA,
            "status": "FAIL",
            "issues": [asdict(issue) for issue in issues],
        }
    issues = _protocol_validation_issues(base, design)
    design_digest = canonical_digest(design)
    if execution is not None:
        # This is deliberately evaluated before any action status is projected.
        issues.extend(_execution_validation_issues(base, execution))
        execution_schema = _text(execution.get("schema_version"))
        if execution_schema != EXECUTION_SCHEMA:
            issues.append(
                ProtocolIssue(
                    "PROTOCOL.EXECUTION_MIGRATION_REQUIRED",
                    f"A v4 design may only continue execution through {EXECUTION_SCHEMA}",
                    "method_execution.json:schema_version",
                )
            )
        elif _text(execution.get("design_sha256")).casefold() != design_digest.casefold():
            issues.append(
                ProtocolIssue(
                    "PROTOCOL.DESIGN_DRIFT",
                    "Compiled protocol is invalid because method execution is bound to another design digest",
                    "method_execution.json:design_sha256",
                )
            )
    return {
        "schema_version": PROTOCOL_CHECK_SCHEMA,
        "status": "PASS" if not issues else "FAIL",
        "design_sha256": design_digest,
        "issues": [asdict(issue) for issue in issues],
    }


def _latest_actions(execution: Mapping[str, Any] | None) -> dict[str, Mapping[str, Any]]:
    latest: dict[str, Mapping[str, Any]] = {}
    if not isinstance(execution, Mapping) or _text(execution.get("schema_version")) != EXECUTION_SCHEMA:
        return latest
    for run in execution.get("runs") or []:
        if not isinstance(run, Mapping):
            continue
        for action in run.get("actions") or []:
            if not isinstance(action, Mapping):
                continue
            operation_id = _text(action.get("operation_id")).upper()
            if not operation_id:
                continue
            try:
                attempt = int(action.get("attempt"))
            except (TypeError, ValueError):
                attempt = -1
            current = latest.get(operation_id)
            if current is None:
                latest[operation_id] = action
                continue
            try:
                current_attempt = int(current.get("attempt"))
            except (TypeError, ValueError):
                current_attempt = -1
            if attempt > current_attempt:
                latest[operation_id] = action
    return latest


def _path_set(values: Any) -> set[str]:
    return {_text(value).replace("\\", "/") for value in values or [] if _text(value)}


def _conflicts(left: Mapping[str, Any], right: Mapping[str, Any]) -> bool:
    left_reads = _path_set(left.get("read_set"))
    left_writes = _path_set(left.get("write_set"))
    right_reads = _path_set(right.get("read_set"))
    right_writes = _path_set(right.get("write_set"))
    return bool(
        left_writes & right_writes
        or left_writes & right_reads
        or right_writes & left_reads
    )


def _parallel_groups(items: list[dict[str, Any]]) -> list[list[str]]:
    groups: list[list[dict[str, Any]]] = []
    for item in items:
        for group in groups:
            if all(not _conflicts(item, existing) for existing in group):
                group.append(item)
                break
        else:
            groups.append([item])
    return [[_text(item.get("id")) for item in group] for group in groups]


def _failure_route(step: Mapping[str, Any], action: Mapping[str, Any] | None) -> str | None:
    if not isinstance(action, Mapping) or _text(action.get("status")) != "failed":
        return None
    declared = _text(action.get("disposition_route"))
    if declared:
        return declared
    code = _text(action.get("failure_code"))
    for candidate in step.get("on_failure") or []:
        if isinstance(candidate, Mapping) and _text(candidate.get("code")) == code:
            return _text(candidate.get("route")) or None
    return None


def _safe_projection_path(raw: Any) -> bool:
    token = _text(raw).replace("\\", "/")
    if not token or token.startswith("/") or (len(token) > 1 and token[1] == ":"):
        return False
    return ".." not in PurePosixPath(token).parts


def compile_protocol(
    outdir: Path,
    *,
    design: Mapping[str, Any] | None = None,
    execution: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Compile the current facts into a deterministic, non-persisted task graph."""

    base = outdir.resolve()
    if design is None:
        design, loaded_execution = load_facts(base)
        if execution is None:
            execution = loaded_execution
    check_issues = _protocol_validation_issues(base, design)
    design_digest = canonical_digest(design)
    canonical_execution_issues: list[ProtocolIssue] = []
    if isinstance(execution, Mapping):
        # Fail closed before _latest_actions is allowed to inspect accepted/failed.
        canonical_execution_issues = _execution_validation_issues(base, execution)
        check_issues.extend(canonical_execution_issues)
    if isinstance(execution, Mapping) and _text(execution.get("schema_version")) != EXECUTION_SCHEMA:
        check_issues.append(
            ProtocolIssue(
                "PROTOCOL.EXECUTION_MIGRATION_REQUIRED",
                f"A v4 design may only continue execution through {EXECUTION_SCHEMA}",
                "method_execution.json:schema_version",
            )
        )
    drift = bool(
        isinstance(execution, Mapping)
        and _text(execution.get("schema_version")) == EXECUTION_SCHEMA
        and _text(execution.get("design_sha256")).casefold() != design_digest.casefold()
    )
    if drift:
        check_issues.append(
            ProtocolIssue(
                "PROTOCOL.DESIGN_DRIFT",
                "The design changed after execution was bound; recompile and re-open execution",
                "method_execution.json:design_sha256",
            )
        )
    blueprint = design.get("execution_blueprint") if isinstance(design.get("execution_blueprint"), Mapping) else {}
    raw_steps = blueprint.get("steps") if isinstance(blueprint.get("steps"), list) else []
    latest = {} if canonical_execution_issues else _latest_actions(execution)
    accepted = {
        operation_id
        for operation_id, action in latest.items()
        if _text(action.get("status")) == "accepted"
    }
    required_mvmr_by_design: dict[str, set[str]] = {}
    for step in raw_steps:
        if not isinstance(step, Mapping) or _text(step.get("run_kind")) != "mvmr":
            continue
        design_id = _text(step.get("design_id")).upper()
        step_id = _text(step.get("id")).upper()
        if design_id and step_id:
            required_mvmr_by_design.setdefault(design_id, set()).add(step_id)
    accepted_mvmr_designs = {
        design_id
        for design_id, required_ids in required_mvmr_by_design.items()
        if required_ids and required_ids.issubset(accepted)
    }
    declared_support = _declared_support_by_design(design)
    dispatch_by_operation: dict[str, dict[str, Any]] = {}
    try:
        dispatch_registry = _load_object(METHOD_REGISTRY_PATH, required=True)
        assert dispatch_registry is not None
        dispatch_module = _researcher_dispatch_module()
        for raw in raw_steps:
            if not isinstance(raw, Mapping):
                continue
            step_id = _text(raw.get("id")).upper()
            if step_id:
                dispatch_by_operation[step_id] = dispatch_module.compile_dispatch_decision(
                    raw,
                    design,
                    dispatch_registry,
                )
    except (OSError, ValueError, ProtocolCompilerError) as exc:
        check_issues.append(
            ProtocolIssue(
                "PROTOCOL.RESEARCHER_DISPATCH_INVALID",
                str(exc),
                "research_design.json:execution_blueprint",
            )
        )
    items: list[dict[str, Any]] = []
    for raw in raw_steps:
        if not isinstance(raw, Mapping):
            continue
        item = deepcopy(dict(raw))
        step_id = _text(item.get("id")).upper()
        action = latest.get(step_id)
        status = _text(action.get("status")) if isinstance(action, Mapping) else "pending"
        prerequisites = [
            _text(value.get("step_id")).upper()
            for value in item.get("preconditions") or []
            if isinstance(value, Mapping)
        ]
        blocked_by = [value for value in prerequisites if value not in accepted]
        design_id = _text(item.get("design_id")).upper()
        if _text(item.get("run_kind")) == "full" and design_id not in accepted_mvmr_designs:
            marker = f"MVMR:{design_id}"
            if marker not in blocked_by:
                blocked_by.append(marker)
        unsafe = [
            value
            for value in [*(item.get("read_set") or []), *(item.get("write_set") or [])]
            if not _safe_projection_path(value)
        ]
        if unsafe:
            blocked_by.extend(f"UNSAFE_PATH:{value}" for value in unsafe)
        runnable = not check_issues and not blocked_by and status not in {
            "accepted",
            "running",
            "superseded",
        }
        item.update(
            {
                "execution_status": status,
                "latest_action_id": _text(action.get("id")) if isinstance(action, Mapping) else None,
                "method_support_status": declared_support.get(design_id, "unknown"),
                "researcher_dispatch": deepcopy(dispatch_by_operation.get(step_id)),
                "blocked_by": blocked_by,
                "runnable": runnable,
                "failure_route": _failure_route(item, action),
            }
        )
        items.append(item)
    runnable = [item for item in items if item.get("runnable")]
    runnable.sort(key=lambda item: _text(item.get("id")))
    completed = bool(items) and all(_text(item.get("execution_status")) == "accepted" for item in items)
    return {
        "schema_version": PROTOCOL_SCHEMA,
        "source": "research_design.json + method_execution.json",
        "persisted": False,
        "design_schema_version": _text(design.get("schema_version")),
        "design_sha256": design_digest,
        "execution_schema_version": _text(execution.get("schema_version")) if isinstance(execution, Mapping) else None,
        "execution_design_sha256": _text(execution.get("design_sha256")) if isinstance(execution, Mapping) else None,
        "method_support_by_design": declared_support,
        "researcher_dispatch_by_operation": dispatch_by_operation,
        "valid": not check_issues,
        "invalidated_by_design_change": drift,
        "issues": [asdict(issue) for issue in check_issues],
        "work_items": items,
        "next_executable_action": _text(runnable[0].get("id")) if runnable else None,
        "runnable_action_ids": [_text(item.get("id")) for item in runnable],
        "parallel_safe_groups": _parallel_groups(runnable),
        "completion_status": "complete" if completed else "blocked" if not runnable else "actionable",
    }


def next_projection(outdir: Path) -> dict[str, Any]:
    protocol = compile_protocol(outdir)
    next_id = _text(protocol.get("next_executable_action"))
    next_item = next(
        (
            item
            for item in protocol.get("work_items") or []
            if isinstance(item, Mapping) and _text(item.get("id")) == next_id
        ),
        None,
    )
    return {
        "schema_version": "avereth-next-action/v1",
        "status": protocol.get("completion_status"),
        "design_sha256": protocol.get("design_sha256"),
        "next_executable_action": next_id or None,
        "work_item": deepcopy(dict(next_item)) if isinstance(next_item, Mapping) else None,
        "researcher_dispatch": deepcopy(next_item.get("researcher_dispatch")) if isinstance(next_item, Mapping) else None,
        "runnable_action_ids": protocol.get("runnable_action_ids") or [],
        "parallel_safe_groups": protocol.get("parallel_safe_groups") or [],
        "issues": protocol.get("issues") or [],
    }


def protocol_markdown(protocol: Mapping[str, Any]) -> str:
    lines = [
        "# Avereth Executable Research Protocol",
        "",
        f"- valid: {str(bool(protocol.get('valid'))).lower()}",
        f"- persisted: {str(bool(protocol.get('persisted'))).lower()}",
        f"- completion_status: {_text(protocol.get('completion_status'))}",
        f"- next_executable_action: {_text(protocol.get('next_executable_action')) or 'none'}",
        "",
        "## Work Items",
        "",
    ]
    for item in protocol.get("work_items") or []:
        if not isinstance(item, Mapping):
            continue
        operation = (item.get("procedure") or {}).get("operation") if isinstance(item.get("procedure"), Mapping) else ""
        dispatch = item.get("researcher_dispatch") if isinstance(item.get("researcher_dispatch"), Mapping) else {}
        lines.append(
            f"- `{_text(item.get('id'))}` [{_text(item.get('run_kind'))}] "
            f"{_text(operation)} — status={_text(item.get('execution_status'))}, "
            f"runnable={str(bool(item.get('runnable'))).lower()}, "
            f"researcher_mode={_text(dispatch.get('mode')) or 'single'}, "
            f"first_tasks={','.join(dispatch.get('task_kinds') or []) or 'none'}, "
            f"post_tasks={','.join(dispatch.get('post_run_task_kinds') or []) or 'none'}, "
            f"conditional_tasks={','.join(dispatch.get('conditional_task_kinds') or []) or 'none'}"
        )
    if not protocol.get("work_items"):
        lines.append("- none")
    issues = protocol.get("issues") or []
    if issues:
        lines.extend(["", "## Issues", ""])
        for issue in issues:
            if isinstance(issue, Mapping):
                lines.append(f"- `{_text(issue.get('code'))}` {_text(issue.get('message'))}")
    lines.append("")
    return "\n".join(lines)


def next_markdown(projection: Mapping[str, Any]) -> str:
    lines = [
        GENERATED_MARKER,
        "# Next Research Action",
        "",
        f"- status: {_text(projection.get('status'))}",
        f"- next_executable_action: {_text(projection.get('next_executable_action')) or 'none'}",
    ]
    item = projection.get("work_item")
    if isinstance(item, Mapping):
        procedure = item.get("procedure") if isinstance(item.get("procedure"), Mapping) else {}
        dispatch = item.get("researcher_dispatch") if isinstance(item.get("researcher_dispatch"), Mapping) else {}
        lines.extend(
            [
                f"- goal: {_text(item.get('goal'))}",
                f"- adapter: {_text(procedure.get('adapter'))}",
                f"- operation: {_text(procedure.get('operation'))}",
                f"- researcher_mode: {_text(dispatch.get('mode')) or 'single'}",
                f"- researcher_roles: {', '.join(dispatch.get('roles') or []) or 'Researcher A'}",
                f"- researcher_first_run_tasks: {', '.join(dispatch.get('task_kinds') or []) or 'none'}",
                f"- researcher_post_run_tasks: {', '.join(dispatch.get('post_run_task_kinds') or []) or 'none'}",
                f"- researcher_conditional_tasks: {', '.join(dispatch.get('conditional_task_kinds') or []) or 'none'}",
                "",
                "## Read Set",
                "",
                *[f"- `{value}`" for value in item.get("read_set") or []],
                "",
                "## Write Set",
                "",
                *[f"- `{value}`" for value in item.get("write_set") or []],
                "",
                "## Acceptance Checks",
                "",
                *[
                    f"- `{_text(check.get('id'))}` {_text(check.get('rule'))}"
                    for check in item.get("acceptance_checks") or []
                    if isinstance(check, Mapping)
                ],
            ]
        )
    lines.append("")
    return "\n".join(lines)


def render_views(outdir: Path) -> list[Path]:
    """Explicitly refresh derived design views and next_action.md."""

    base = outdir.resolve()
    design, _execution = load_facts(base)
    if _text(design.get("schema_version")) != DESIGN_SCHEMA:
        raise ProtocolCompilerError(f"Protocol views require {DESIGN_SCHEMA}")
    try:
        import research_design  # type: ignore

        written = research_design.render_views(base, design)
    except (ImportError, OSError, ValueError) as exc:
        raise ProtocolCompilerError(str(exc)) from exc
    projection = next_projection(base)
    target = base / NEXT_ACTION_REL
    if target.exists() and GENERATED_MARKER not in target.read_text(encoding="utf-8-sig", errors="ignore"):
        raise ProtocolCompilerError(f"Refusing to overwrite hand-maintained view {target}")
    target.write_text(next_markdown(projection), encoding="utf-8", newline="\n")
    return [*written, target]
