class V3ContractError(ValueError):
    """Raised when a v3 contract cannot be safely validated or rendered."""


def _text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value.strip()
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, Mapping):
        return "; ".join(
            f"{key}={_text(item)}" for key, item in value.items() if _text(item)
        )
    if isinstance(value, Sequence) and not isinstance(value, (str, bytes, bytearray)):
        return "; ".join(_text(item) for item in value if _text(item))
    return str(value).strip()


def _substantive(value: Any) -> bool:
    token = _text(value)
    return bool(
        token
        and token.casefold() not in {"-", "--", "n/a", "na", "none", "null"}
        and "needs-review" not in token.casefold()
    )


def _add(result: Any, code: str, severity: str, message: str, path: str) -> None:
    result.add(code, severity, message, path)


def _method_contract_loader() -> Any:
    global _METHOD_CONTRACT_LOADER
    if _METHOD_CONTRACT_LOADER is not None:
        return _METHOD_CONTRACT_LOADER
    module_name = "avereth_method_contract_loader"
    if module_name in sys.modules:
        _METHOD_CONTRACT_LOADER = sys.modules[module_name]
        return _METHOD_CONTRACT_LOADER
    spec = importlib.util.spec_from_file_location(module_name, METHOD_CONTRACT_LOADER_PATH)
    if spec is None or spec.loader is None:
        raise ValueError(f"Cannot load shared method-contract loader: {METHOD_CONTRACT_LOADER_PATH}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    spec.loader.exec_module(module)
    _METHOD_CONTRACT_LOADER = module
    return module


def _method_contract_pointer_path(prefix: str, pointer: str) -> str:
    if pointer in {"", "/"}:
        return prefix
    rendered = prefix
    for raw in pointer.lstrip("/").split("/"):
        token = raw.replace("~1", "/").replace("~0", "~")
        rendered += f"[{token}]" if token.isdigit() else f".{token}"
    return rendered


def _add_method_contract_schema_issues(
    result: Any,
    issues: Sequence[Mapping[str, str]],
    *,
    prefix: str,
    supplemental: bool,
) -> None:
    for issue in issues:
        code = _text(issue.get("code"))
        if code.startswith("PTP."):
            rendered_code = code
        elif code == "SUPPLEMENTAL.RESERVED_AUTHORITY":
            rendered_code = "RD.METHOD_CONTRACT.SUPPLEMENTAL_RESERVED_AUTHORITY"
        else:
            suffix = code.removeprefix("SCHEMA.")
            namespace = (
                "RD.METHOD_CONTRACT.SUPPLEMENTAL_SCHEMA"
                if supplemental
                else "RD.METHOD_CONTRACT.SCHEMA"
            )
            rendered_code = f"{namespace}_{suffix}"
        _add(
            result,
            rendered_code,
            "ERROR",
            _text(issue.get("message")),
            _method_contract_pointer_path(prefix, _text(issue.get("path"))),
        )


def _require_text(
    result: Any,
    value: Any,
    path: str,
    *,
    code: str = "RD.CASE.BOUNDARY_MISSING",
) -> str:
    token = _text(value)
    if not _substantive(token):
        _add(result, code, "ERROR", f"A substantive declaration is required at {path}", path)
    return token


def _require_list(
    result: Any,
    value: Any,
    path: str,
    *,
    nonempty: bool = False,
) -> list[Any]:
    if not isinstance(value, list):
        _add(result, "RD.CASE.FIELD_INVALID", "ERROR", f"{path} must be an array", path)
        return []
    if nonempty and not value:
        _add(result, "RD.CASE.FIELD_MISSING", "ERROR", f"{path} must not be empty", path)
    return value


def project_to_v2(payload: Mapping[str, Any]) -> dict[str, Any]:
    """Project v3 onto the v2 base contract without weakening v3 checks."""
    projected = deepcopy(dict(payload))
    projected["schema_version"] = "cnki-research-design/v2"
    claim_map = {
        "causal_configuration": "association",
        "theory_evaluation": "theory_generation",
    }
    projected_claims: list[Any] = []
    for claim in projected.get("claims") or []:
        if not isinstance(claim, Mapping):
            projected_claims.append(claim)
            continue
        item = dict(claim)
        item["type"] = claim_map.get(_text(item.get("type")), item.get("type"))
        projected_claims.append(item)
    projected["claims"] = projected_claims
    projected.pop("case_design", None)
    return projected


def cross_artifact_projection(payload: Mapping[str, Any], v2: Any) -> Mapping[str, Any]:
    return v2.cross_artifact_projection(project_to_v2(payload))


def _collect_case_ids(
    case_design: Mapping[str, Any],
    existing: Mapping[str, set[str]],
    result: Any,
) -> dict[str, set[str]]:
    identifiers = {name: set(values) for name, values in existing.items()}
    global_ids = set(identifiers.get("all", set()))
    for collection in CASE_COLLECTIONS:
        values = _require_list(result, case_design.get(collection), f"case_design.{collection}")
        known: set[str] = set()
        for index, item in enumerate(values):
            path = f"case_design.{collection}[{index}]"
            if not isinstance(item, Mapping):
                _add(result, "RD.CASE.FIELD_INVALID", "ERROR", "Case-design entries must be objects", path)
                continue
            identifier = _text(item.get("id")).upper()
            if not identifier or not ID_PATTERNS[collection].fullmatch(identifier):
                _add(
                    result,
                    "RD.CASE.ID_INVALID",
                    "ERROR",
                    f"Expected a stable {ID_PATTERNS[collection].pattern} identifier",
                    f"{path}.id",
                )
                continue
            if identifier in global_ids:
                _add(
                    result,
                    "RD.ID.DUPLICATE",
                    "ERROR",
                    f"Duplicate global ID {identifier!r}",
                    f"{path}.id",
                )
            known.add(identifier)
            global_ids.add(identifier)
        identifiers[collection] = known
    identifiers["all"] = global_ids
    return identifiers


def _validate_ref_list(
    result: Any,
    value: Any,
    known: set[str],
    path: str,
    *,
    nonempty: bool = False,
) -> list[str]:
    values = _require_list(result, value, path, nonempty=nonempty)
    resolved: list[str] = []
    for index, raw in enumerate(values):
        token = _text(raw).upper()
        if not token or token not in known:
            _add(
                result,
                "RD.ID.UNRESOLVED",
                "ERROR",
                f"Unknown internal reference {token!r}",
                f"{path}[{index}]",
            )
        else:
            resolved.append(token)
    return resolved


def _validate_universes(
    case_design: Mapping[str, Any],
    identifiers: Mapping[str, set[str]],
    result: Any,
) -> None:
    del identifiers
    for index, universe in enumerate(case_design.get("case_universes") or []):
        if not isinstance(universe, Mapping):
            continue
        prefix = f"case_design.case_universes[{index}]"
        for field in UNIVERSE_BOUNDARY_FIELDS:
            _require_text(result, universe.get(field), f"{prefix}.{field}")


def _validate_cases(
    case_design: Mapping[str, Any],
    identifiers: Mapping[str, set[str]],
    result: Any,
) -> None:
    for index, case in enumerate(case_design.get("cases") or []):
        if not isinstance(case, Mapping):
            continue
        prefix = f"case_design.cases[{index}]"
        universe_id = _text(case.get("universe_id")).upper()
        if universe_id not in identifiers.get("case_universes", set()):
            _add(
                result,
                "RD.ID.UNRESOLVED",
                "ERROR",
                f"Unknown case-universe reference {universe_id!r}",
                f"{prefix}.universe_id",
            )
        _validate_ref_list(
            result,
            case.get("design_ids"),
            identifiers.get("method_routes", set()),
            f"{prefix}.design_ids",
            nonempty=True,
        )
        for field in CASE_BOUNDARY_FIELDS:
            value = _require_text(result, case.get(field), f"{prefix}.{field}")
            if field == "selection_strategy" and value not in SELECTION_STRATEGIES and _substantive(value):
                _add(
                    result,
                    "RD.CASE.SELECTION_UNSUPPORTED",
                    "ERROR",
                    f"Unsupported selection strategy {value!r}",
                    f"{prefix}.{field}",
                )
            if (
                field == "outcome_knowledge_at_selection"
                and value not in OUTCOME_KNOWLEDGE_STATES
                and _substantive(value)
            ):
                _add(
                    result,
                    "RD.CASE.OUTCOME_KNOWLEDGE_INVALID",
                    "ERROR",
                    f"Unsupported outcome-knowledge state {value!r}",
                    f"{prefix}.{field}",
                )
        outcome_state = _text(case.get("outcome_knowledge_at_selection"))
        if outcome_state in {"known", "partially-known"}:
            _add(
                result,
                "RD.REVIEW.CASE_OUTCOME_AWARE_SELECTION",
                "REVIEW",
                "Review whether outcome-aware selection is transparent and appropriate for the stated theoretical purpose",
                f"{prefix}.outcome_knowledge_at_selection",
            )
        material_roles = _require_list(
            result,
            case.get("material_roles"),
            f"{prefix}.material_roles",
            nonempty=True,
        )
        by_material: dict[str, list[Mapping[str, Any]]] = {}
        for role_index, role in enumerate(material_roles):
            role_path = f"{prefix}.material_roles[{role_index}]"
            if not isinstance(role, Mapping):
                _add(result, "RD.CASE.FIELD_INVALID", "ERROR", "Material roles must be objects", role_path)
                continue
            material_id = _require_text(
                result,
                role.get("material_id"),
                f"{role_path}.material_id",
                code="RD.CASE.MATERIAL_ROLE_MISSING",
            )
            _require_text(
                result,
                role.get("role"),
                f"{role_path}.role",
                code="RD.CASE.MATERIAL_ROLE_MISSING",
            )
            _require_text(
                result,
                role.get("independence"),
                f"{role_path}.independence",
                code="RD.CASE.MATERIAL_ROLE_MISSING",
            )
            if material_id:
                by_material.setdefault(material_id, []).append(role)
        for material_id, roles in by_material.items():
            role_names = {_text(role.get("role")) for role in roles}
            claimed_independent = any(
                _text(role.get("independence")) in {"independent", "independent-validation"}
                for role in roles
            )
            if (
                {"theory_generation", "validation"}.issubset(role_names)
                or {"theory_generation", "theory_evaluation"}.issubset(role_names)
            ) and claimed_independent:
                _add(
                    result,
                    "RD.CASE.MATERIAL_CIRCULARITY",
                    "ERROR",
                    f"Material {material_id!r} is used to construct and independently validate the same claim",
                    f"{prefix}.material_roles",
                )


def _validate_scopes(
    case_design: Mapping[str, Any],
    identifiers: Mapping[str, set[str]],
    result: Any,
) -> None:
    for index, scope in enumerate(case_design.get("scope_conditions") or []):
        if not isinstance(scope, Mapping):
            continue
        prefix = f"case_design.scope_conditions[{index}]"
        for field in ("statement", "status", "inference_impact"):
            _require_text(result, scope.get(field), f"{prefix}.{field}")
        _validate_ref_list(
            result,
            scope.get("claim_ids"),
            identifiers.get("claims", set()),
            f"{prefix}.claim_ids",
            nonempty=True,
        )
        _validate_ref_list(
            result,
            scope.get("design_ids"),
            identifiers.get("method_routes", set()),
            f"{prefix}.design_ids",
            nonempty=True,
        )
        _validate_ref_list(
            result,
            scope.get("evidence_ids", []),
            identifiers.get("evidence", set()),
            f"{prefix}.evidence_ids",
        )
        _add(
            result,
            "RD.REVIEW.SCOPE_CONDITION_QUALITY",
            "REVIEW",
            "Review whether the scope condition is theoretically justified and calibrated to the evidence",
            prefix,
        )


def _validate_comparisons(
    case_design: Mapping[str, Any],
    identifiers: Mapping[str, set[str]],
    result: Any,
) -> None:
    for index, comparison in enumerate(case_design.get("comparisons") or []):
        if not isinstance(comparison, Mapping):
            continue
        prefix = f"case_design.comparisons[{index}]"
        mode = _require_text(result, comparison.get("mode"), f"{prefix}.mode")
        if mode not in COMPARISON_MODES and _substantive(mode):
            _add(
                result,
                "RD.CASE.COMPARISON_MODE_INVALID",
                "ERROR",
                f"Unsupported comparison mode {mode!r}",
                f"{prefix}.mode",
            )
        case_ids = _validate_ref_list(
            result,
            comparison.get("case_ids"),
            identifiers.get("cases", set()),
            f"{prefix}.case_ids",
            nonempty=True,
        )
        if len(set(case_ids)) < 2:
            _add(
                result,
                "RD.CASE.CROSS_CASE_COUNT",
                "ERROR",
                "A cross-case comparison must register at least two distinct cases",
                f"{prefix}.case_ids",
            )
        _validate_ref_list(
            result,
            comparison.get("design_ids"),
            identifiers.get("method_routes", set()),
            f"{prefix}.design_ids",
            nonempty=True,
        )
        for field in (
            "logic",
            "time_alignment",
            "level_alignment",
            "common_dimensions",
            "contrast_dimensions",
            "target_inference",
            "threats",
            "inference_ceiling",
        ):
            _require_text(result, comparison.get(field), f"{prefix}.{field}")
        _validate_ref_list(
            result,
            comparison.get("evidence_ids", []),
            identifiers.get("evidence", set()),
            f"{prefix}.evidence_ids",
        )
        _add(
            result,
            "RD.REVIEW.COMPARABILITY",
            "REVIEW",
            "Review substantive comparability, temporal alignment, and the limits of the comparison",
            prefix,
        )


def _validate_within_case(
    case_design: Mapping[str, Any],
    identifiers: Mapping[str, set[str]],
    result: Any,
) -> None:
    for index, analysis in enumerate(case_design.get("within_case_analyses") or []):
        if not isinstance(analysis, Mapping):
            continue
        prefix = f"case_design.within_case_analyses[{index}]"
        mode = _require_text(result, analysis.get("mode"), f"{prefix}.mode")
        if mode not in WITHIN_CASE_MODES and _substantive(mode):
            _add(
                result,
                "RD.CASE.WITHIN_MODE_INVALID",
                "ERROR",
                f"Unsupported within-case mode {mode!r}",
                f"{prefix}.mode",
            )
        _validate_ref_list(
            result,
            analysis.get("case_ids"),
            identifiers.get("cases", set()),
            f"{prefix}.case_ids",
            nonempty=True,
        )
        _validate_ref_list(
            result,
            analysis.get("design_ids"),
            identifiers.get("method_routes", set()),
            f"{prefix}.design_ids",
            nonempty=True,
        )
        _validate_ref_list(
            result,
            analysis.get("claim_ids"),
            identifiers.get("claims", set()),
            f"{prefix}.claim_ids",
            nonempty=True,
        )
        _validate_ref_list(
            result,
            analysis.get("evidence_ids", []),
            identifiers.get("evidence", set()),
            f"{prefix}.evidence_ids",
        )
        for field in ("purpose", "inference_ceiling"):
            _require_text(result, analysis.get(field), f"{prefix}.{field}")
        if mode == "process_tracing":
            for field in ("mechanism_nodes", "expected_traces", "rival_mechanisms"):
                _require_list(result, analysis.get(field), f"{prefix}.{field}", nonempty=True)
            _add(
                result,
                "RD.REVIEW.MECHANISM_DIAGNOSTICITY",
                "REVIEW",
                "Review the diagnostic value, source independence, rivals, and negative evidence for each mechanism trace",
                prefix,
            )
        if mode == "congruence_analysis":
            for field in ("competing_theories", "theory_predictions", "observable_implications"):
                _require_list(result, analysis.get(field), f"{prefix}.{field}", nonempty=True)
            _add(
                result,
                "RD.REVIEW.CONGRUENCE_DISCRIMINATION",
                "REVIEW",
                "Review whether the predictions discriminate among theories; congruence alone does not prove an effect or mechanism",
                prefix,
            )


def _validate_integration(
    case_design: Mapping[str, Any],
    identifiers: Mapping[str, set[str]],
    result: Any,
) -> None:
    integration = case_design.get("integration")
    if not isinstance(integration, Mapping):
        _add(result, "RD.CASE.INTEGRATION_MISSING", "ERROR", "case_design.integration is required", "case_design.integration")
        return
    sequence = _text(integration.get("sequence"))
    if sequence not in INTEGRATION_SEQUENCES:
        _add(
            result,
            "RD.CASE.INTEGRATION_INVALID",
            "ERROR",
            f"Unsupported case integration sequence {sequence!r}",
            "case_design.integration.sequence",
        )
    _validate_ref_list(
        result,
        integration.get("comparison_ids", []),
        identifiers.get("comparisons", set()),
        "case_design.integration.comparison_ids",
    )
    _validate_ref_list(
        result,
        integration.get("within_case_analysis_ids", []),
        identifiers.get("within_case_analyses", set()),
        "case_design.integration.within_case_analysis_ids",
    )
    _validate_ref_list(
        result,
        integration.get("route_order", []),
        identifiers.get("method_routes", set()),
        "case_design.integration.route_order",
    )
    for field in ("handoffs", "material_role_separation", "conflict_policy", "inference_ceiling"):
        _require_text(result, integration.get(field), f"case_design.integration.{field}")
    separation = _text(integration.get("material_role_separation"))
    if separation == "same-material-claimed-independent":
        _add(
            result,
            "RD.CASE.MATERIAL_CIRCULARITY",
            "ERROR",
            "The same material is represented as independent construction and validation evidence",
            "case_design.integration.material_role_separation",
        )
    comparisons = case_design.get("comparisons") or []
    within = case_design.get("within_case_analyses") or []
    if comparisons and within and sequence not in {
        "cross-case-first",
        "within-case-first",
        "iterative",
        "needs-review",
    }:
        _add(
            result,
            "RD.CASE.INTEGRATION_SEQUENCE_MISSING",
            "ERROR",
            "A combined cross-case/within-case design must declare its analytic sequence",
            "case_design.integration.sequence",
        )


def _validate_route_profile_requirements(
    payload: Mapping[str, Any],
    case_design: Mapping[str, Any],
    identifiers: Mapping[str, set[str]],
    result: Any,
) -> None:
    routes = [
        route for route in payload.get("method_routes") or [] if isinstance(route, Mapping)
    ]
    family_by_id = {_text(route.get("id")).upper(): _text(route.get("family")) for route in routes}
    active_ids = {identifier for identifier, family in family_by_id.items() if family in CASE_FAMILIES}
    linked_ids = set(
        _validate_ref_list(
            result,
            case_design.get("linked_design_ids"),
            identifiers.get("method_routes", set()),
            "case_design.linked_design_ids",
            nonempty=True,
        )
    )
    missing = active_ids - linked_ids
    if missing:
        _add(
            result,
            "RD.CASE.ROUTE_UNLINKED",
            "ERROR",
            f"Case-oriented routes are absent from case_design.linked_design_ids: {', '.join(sorted(missing))}",
            "case_design.linked_design_ids",
        )
    comparisons = [
        item for item in case_design.get("comparisons") or [] if isinstance(item, Mapping)
    ]
    within = [
        item for item in case_design.get("within_case_analyses") or [] if isinstance(item, Mapping)
    ]
    for route_id in active_ids:
        family = family_by_id[route_id]
        route_comparisons = [
            item for item in comparisons if route_id in {_text(value).upper() for value in item.get("design_ids") or []}
        ]
        route_within = [
            item for item in within if route_id in {_text(value).upper() for value in item.get("design_ids") or []}
        ]
        if family in {"comparative", "qca"} and not route_comparisons:
            _add(
                result,
                "RD.CASE.COMPARISON_MISSING",
                "ERROR",
                f"{family} route {route_id} requires a registered cross-case comparison",
                "case_design.comparisons",
            )
        if family == "process_tracing" and not any(
            _text(item.get("mode")) == "process_tracing" for item in route_within
        ):
            _add(
                result,
                "RD.CASE.PROCESS_TRACING_MISSING",
                "ERROR",
                f"Process-tracing route {route_id} requires a process_tracing within-case analysis",
                "case_design.within_case_analyses",
            )
        if family == "congruence_analysis" and not any(
            _text(item.get("mode")) == "congruence_analysis" for item in route_within
        ):
            _add(
                result,
                "RD.CASE.CONGRUENCE_MISSING",
                "ERROR",
                f"Congruence-analysis route {route_id} requires a congruence_analysis within-case record",
                "case_design.within_case_analyses",
            )


def _validate_claim_capabilities(
    payload: Mapping[str, Any],
    case_design: Mapping[str, Any],
    registry: Mapping[str, Any],
    result: Any,
) -> None:
    capabilities = (
        registry.get("claim_capabilities")
        if isinstance(registry.get("claim_capabilities"), Mapping)
        else {}
    )
    routes = {
        _text(route.get("id")).upper(): route
        for route in payload.get("method_routes") or []
        if isinstance(route, Mapping)
    }
    within = [
        item for item in case_design.get("within_case_analyses") or [] if isinstance(item, Mapping)
    ]
    comparisons = [
        item for item in case_design.get("comparisons") or [] if isinstance(item, Mapping)
    ]
    for index, claim in enumerate(payload.get("claims") or []):
        if not isinstance(claim, Mapping):
            continue
        prefix = f"claims[{index}]"
        claim_id = _text(claim.get("id")).upper()
        claim_type = _text(claim.get("type"))
        if claim_type not in CLAIM_TYPES:
            _add(
                result,
                "RD.CLAIM.TYPE_UNSUPPORTED",
                "ERROR",
                f"Unsupported claim type {claim_type!r}",
                f"{prefix}.type",
            )
            continue
        mapped = [
            routes[token]
            for token in (_text(value).upper() for value in claim.get("design_ids") or [])
            if token in routes
        ]
        capable: list[Mapping[str, Any]] = []
        for route in mapped:
            family = _text(route.get("family"))
            allowed = set(capabilities.get(family) or [])
            if claim_type not in allowed:
                continue
            if claim_type in CAUSAL_CLAIM_TYPES and _text(route.get("function")) != "identification":
                continue
            if claim_type == "causal_effect" and family == "quantitative":
                fields = route.get("method_fields") if isinstance(route.get("method_fields"), Mapping) else {}
                if _text(fields.get("task_type")) != "causal":
                    continue
            capable.append(route)
        if not capable:
            _add(
                result,
                "RD.CLAIM.CAPABILITY_EXCEEDED",
                "ERROR",
                f"Claim {claim_id or index} of type {claim_type!r} exceeds every mapped adapter's registered capability",
                f"{prefix}.design_ids",
            )
            continue
        if claim_type == "causal_mechanism":
            process_route_ids = {
                _text(route.get("id")).upper()
                for route in capable
                if _text(route.get("family")) == "process_tracing"
            }
            if process_route_ids and not any(
                _text(item.get("mode")) == "process_tracing"
                and claim_id in {_text(value).upper() for value in item.get("claim_ids") or []}
                and process_route_ids
                & {_text(value).upper() for value in item.get("design_ids") or []}
                for item in within
            ):
                _add(
                    result,
                    "RD.CLAIM.MECHANISM_TRACE_MISSING",
                    "ERROR",
                    "A process-tracing mechanism claim must link to a registered within-case mechanism analysis",
                    f"{prefix}.design_ids",
                )
        if claim_type == "causal_configuration":
            qca_ids = {
                _text(route.get("id")).upper()
                for route in capable
                if _text(route.get("family")) == "qca"
            }
            if qca_ids and not any(
                qca_ids & {_text(value).upper() for value in item.get("design_ids") or []}
                for item in comparisons
            ):
                _add(
                    result,
                    "RD.CLAIM.CONFIGURATION_COMPARISON_MISSING",
                    "ERROR",
                    "A configurational claim must link its QCA route to a registered comparison",
                    f"{prefix}.design_ids",
                )
        if claim_type == "theory_evaluation":
            congruence_ids = {
                _text(route.get("id")).upper()
                for route in capable
                if _text(route.get("family")) == "congruence_analysis"
            }
            if congruence_ids and not any(
                _text(item.get("mode")) == "congruence_analysis"
                and claim_id in {_text(value).upper() for value in item.get("claim_ids") or []}
                and congruence_ids
                & {_text(value).upper() for value in item.get("design_ids") or []}
                for item in within
            ):
                _add(
                    result,
                    "RD.CLAIM.CONGRUENCE_MATRIX_MISSING",
                    "ERROR",
                    "A congruence-based theory evaluation must link to its prediction-observation design",
                    f"{prefix}.design_ids",
                )


def _validate_typed_method_contracts(
    payload: Mapping[str, Any],
    result: Any,
    registry: Mapping[str, Any],
) -> None:
    contracts = (
        registry.get("method_contracts")
        if isinstance(registry.get("method_contracts"), Mapping)
        else {}
    )
    families = registry.get("families") if isinstance(registry.get("families"), Mapping) else {}
    loader = _method_contract_loader()
    claim_types_by_route: dict[str, set[str]] = {}
    for claim in payload.get("claims") or []:
        if not isinstance(claim, Mapping):
            continue
        for route_id in claim.get("design_ids") or []:
            claim_types_by_route.setdefault(_text(route_id).upper(), set()).add(
                _text(claim.get("type"))
            )
    causal_contracts = {
        "causal-design/v1",
        "causal-panel/v1",
        "event-history/v1",
        "text-matching/v2",
    }
    for index, route in enumerate(payload.get("method_routes") or []):
        if not isinstance(route, Mapping):
            continue
        prefix = f"method_routes[{index}]"
        route_id = _text(route.get("id")).upper()
        family = _text(route.get("family"))
        claim_types = claim_types_by_route.get(route_id, set())
        schema_id = _text(route.get("method_contract_schema"))
        supplemental_id = _text(route.get("supplemental_profile_id"))
        supplemental_contract = route.get("supplemental_contract")
        supplemental_layer_present = any(
            field in route
            for field in ("supplemental_profile_id", "supplemental_contract")
        )
        if supplemental_layer_present and not supplemental_id:
            _add(
                result,
                "RD.METHOD_CONTRACT.SUPPLEMENTAL_PROFILE_MISSING",
                "ERROR",
                "Any supplemental field requires a registered supplemental_profile_id",
                f"{prefix}.supplemental_profile_id",
            )
        if supplemental_layer_present and not schema_id:
            _add(
                result,
                "RD.METHOD_CONTRACT.SUPPLEMENTAL_CORE_MISSING",
                "ERROR",
                "Any supplemental field requires a non-empty core method_contract_schema",
                f"{prefix}.method_contract_schema",
            )
        if supplemental_layer_present and not _text(route.get("method_contract_revision")):
            _add(
                result,
                "RD.METHOD_CONTRACT.SUPPLEMENTAL_CORE_REVISION_MISSING",
                "ERROR",
                "Any supplemental field requires a non-empty core method_contract_revision",
                f"{prefix}.method_contract_revision",
            )
        if supplemental_id and not isinstance(supplemental_contract, Mapping):
            _add(
                result,
                "RD.METHOD_CONTRACT.SUPPLEMENTAL_CONTRACT_MISSING",
                "ERROR",
                "A selected supplemental profile requires supplemental_contract to be an object",
                f"{prefix}.supplemental_contract",
            )
        if supplemental_id:
            try:
                supplemental_core_id, supplemental_core_revision = (
                    loader.supplemental_profile_binding(registry, supplemental_id)
                )
            except (OSError, ValueError) as exc:
                _add(
                    result,
                    "RD.METHOD_CONTRACT.SUPPLEMENTAL_REGISTRY_INVALID",
                    "ERROR",
                    str(exc),
                    f"{prefix}.supplemental_profile_id",
                )
            else:
                if schema_id and schema_id != supplemental_core_id:
                    _add(
                        result,
                        "RD.METHOD_CONTRACT.SUPPLEMENTAL_CORE_MISMATCH",
                        "ERROR",
                        f"Supplemental profile {supplemental_id!r} requires core {supplemental_core_id!r}",
                        f"{prefix}.method_contract_schema",
                    )
                if (
                    _text(route.get("method_contract_revision"))
                    and _text(route.get("method_contract_revision"))
                    != supplemental_core_revision
                ):
                    _add(
                        result,
                        "RD.METHOD_CONTRACT.SUPPLEMENTAL_CORE_REVISION_MISMATCH",
                        "ERROR",
                        f"Supplemental profile {supplemental_id!r} requires core revision {supplemental_core_revision!r}",
                        f"{prefix}.method_contract_revision",
                    )
        required_schema = ""
        allowed_required: set[str] = set()
        if family == "text_as_data":
            required_schema = "text-as-data/measurement-v2"
        elif family == "process_tracing" and "causal_mechanism" in claim_types:
            required_schema = "process-tracing/v1"
        elif "causal_effect" in claim_types:
            allowed_required = causal_contracts
        if required_schema and schema_id != required_schema:
            _add(
                result,
                "RD.METHOD_CONTRACT.REQUIRED",
                "ERROR",
                f"{family} requires typed method contract {required_schema}",
                f"{prefix}.method_contract_schema",
            )
        if allowed_required and schema_id not in allowed_required:
            _add(
                result,
                "RD.METHOD_CONTRACT.CAUSAL_REQUIRED",
                "ERROR",
                "causal_effect requires an estimand/counterfactual typed contract",
                f"{prefix}.method_contract_schema",
            )
        has_layer = any(
            field in route
            for field in (
                "method_contract_schema",
                "method_contract",
                "supplemental_profile_id",
                "supplemental_contract",
                "artifact_refs",
            )
        )
        if not schema_id:
            if has_layer:
                if not isinstance(route.get("method_contract"), Mapping):
                    _add(
                        result,
                        "RD.METHOD_CONTRACT.INVALID",
                        "ERROR",
                        "method_contract must be an object",
                        f"{prefix}.method_contract",
                    )
                if not isinstance(route.get("artifact_refs"), list):
                    _add(
                        result,
                        "RD.METHOD_CONTRACT.INVALID",
                        "ERROR",
                        "artifact_refs must be an array",
                        f"{prefix}.artifact_refs",
                    )
            continue
        spec = contracts.get(schema_id)
        if not isinstance(spec, Mapping):
            retired = registry.get("retired_method_contracts")
            retired_spec = retired.get(schema_id) if isinstance(retired, Mapping) else None
            if isinstance(retired_spec, Mapping):
                successor = _text(retired_spec.get("successor"))
                _add(
                    result,
                    "RD.METHOD_CONTRACT.MIGRATION_REQUIRED",
                    "ERROR",
                    f"Retired method_contract_schema {schema_id!r} requires explicit migration to {successor!r}",
                    f"{prefix}.method_contract_schema",
                )
                continue
            _add(
                result,
                "RD.METHOD_CONTRACT.SCHEMA_UNKNOWN",
                "ERROR",
                f"Unknown method_contract_schema {schema_id!r}",
                f"{prefix}.method_contract_schema",
            )
            continue
        if _text(route.get("method_contract_revision")) != _text(spec.get("revision")):
            _add(
                result,
                "RD.METHOD_CONTRACT.REVISION_MISMATCH",
                "ERROR",
                "method_contract_revision differs from the active registry",
                f"{prefix}.method_contract_revision",
            )
        if not _substantive(route.get("method_profile")):
            _add(
                result,
                "RD.METHOD_CONTRACT.PROFILE_MISSING",
                "ERROR",
                "Typed method contract requires an explicit method_profile identity",
                f"{prefix}.method_profile",
            )
        allowed_families = {
            name
            for name, adapter in families.items()
            if isinstance(adapter, Mapping)
            and schema_id in set(adapter.get("method_contract_profiles") or [])
        }
        if family not in allowed_families:
            _add(
                result,
                "RD.METHOD_CONTRACT.FAMILY_MISMATCH",
                "ERROR",
                f"{schema_id} is not registered for family {family!r}",
                f"{prefix}.method_contract_schema",
            )
        contract = route.get("method_contract")
        if not isinstance(contract, Mapping):
            _add(
                result,
                "RD.METHOD_CONTRACT.INVALID",
                "ERROR",
                "method_contract must be an object",
                f"{prefix}.method_contract",
            )
            continue
        for key in spec.get("design_required") or []:
            if not _substantive(contract.get(key)):
                _add(
                    result,
                    "RD.METHOD_CONTRACT.DESIGN_INCOMPLETE",
                    "ERROR",
                    f"Typed design contract requires substantive key {key!r}",
                    f"{prefix}.method_contract.{key}",
                )
        try:
            core_issues = loader.validate_core_contract(
                registry,
                schema_id,
                contract,
                phase="design",
            )
        except (OSError, ValueError) as exc:
            _add(
                result,
                "RD.METHOD_CONTRACT.SCHEMA_LOAD_FAILURE",
                "ERROR",
                str(exc),
                f"{prefix}.method_contract_schema",
            )
        else:
            _add_method_contract_schema_issues(
                result,
                core_issues,
                prefix=f"{prefix}.method_contract",
                supplemental=False,
            )
        if not isinstance(route.get("artifact_refs"), list):
            _add(
                result,
                "RD.METHOD_CONTRACT.INVALID",
                "ERROR",
                "artifact_refs must be an array of design-stage artifact references",
                f"{prefix}.artifact_refs",
            )
        if not supplemental_id:
            continue
        if not isinstance(supplemental_contract, Mapping):
            continue
        try:
            supplemental_issues, supplemental_artifact_ids = (
                loader.validate_supplemental_contract(
                    registry,
                    schema_id,
                    _text(spec.get("revision")),
                    supplemental_id,
                    supplemental_contract,
                )
            )
        except (OSError, ValueError) as exc:
            _add(
                result,
                "RD.METHOD_CONTRACT.SUPPLEMENTAL_REGISTRY_INVALID",
                "ERROR",
                str(exc),
                f"{prefix}.supplemental_profile_id",
            )
            continue
        _add_method_contract_schema_issues(
            result,
            supplemental_issues,
            prefix=f"{prefix}.supplemental_contract",
            supplemental=True,
        )
        design_artifact_ids = {
            _text(value).upper()
            for value in route.get("artifact_refs") or []
            if _text(value)
        }
        missing_supplemental_refs = sorted(
            supplemental_artifact_ids - design_artifact_ids
        )
        if missing_supplemental_refs:
            _add(
                result,
                "RD.METHOD_CONTRACT.SUPPLEMENTAL_ARTIFACT_REF_MISSING",
                "ERROR",
                "Supplemental Artifact IDs are absent from design artifact_refs: "
                + ", ".join(missing_supplemental_refs),
                f"{prefix}.artifact_refs",
            )


def _canonical_digest(value: Any) -> str:
    return hashlib.sha256(
        json.dumps(
            value,
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
        ).encode("utf-8")
    ).hexdigest()


def _validate_research_decision_reference(
    base: Path,
    payload: Mapping[str, Any],
    result: Any,
) -> None:
    """Bind design to the cleared candidate and exact question version.

    Legacy isolated v3 fixtures without a research-stage contract remain
    readable. Production stage gates require ``research_decision.json``; once
    it exists, an absent or stale design reference fails closed.
    """

    decision_path = base / "research_decision.json"
    reference = payload.get("research_decision_ref")
    if not decision_path.is_file():
        if reference not in (None, {}):
            _add(
                result,
                "RD.RESEARCH_DECISION.MISSING",
                "ERROR",
                "research_design references a missing research_decision.json",
                "research_decision_ref",
            )
        return
    try:
        decision = json.loads(decision_path.read_text(encoding="utf-8-sig"))
    except (OSError, json.JSONDecodeError) as exc:
        _add(
            result,
            "RD.RESEARCH_DECISION.INVALID",
            "ERROR",
            f"research_decision.json cannot be read: {exc}",
            "research_decision_ref",
        )
        return
    if not isinstance(decision, Mapping):
        _add(
            result,
            "RD.RESEARCH_DECISION.INVALID",
            "ERROR",
            "research_decision.json must contain one object",
            "research_decision_ref",
        )
        return
    try:
        from research_decision import validate_payload as validate_research_decision

        decision_result = validate_research_decision(base, decision, check_views=False)
    except (ImportError, OSError, ValueError) as exc:
        _add(
            result,
            "RD.RESEARCH_DECISION.INVALID",
            "ERROR",
            f"research decision could not be revalidated: {exc}",
            "research_decision_ref",
        )
        return
    for issue in decision_result.errors:
        _add(
            result,
            "RD.RESEARCH_DECISION.INVALID",
            "ERROR",
            f"research decision [{issue.code}] {issue.message}",
            "research_decision_ref",
        )
    if _text(decision.get("disposition")) != "cleared":
        _add(
            result,
            "RD.RESEARCH_DECISION.NOT_CLEARED",
            "ERROR",
            "design cannot start while the research decision is reopened or all candidates are withdrawn",
            "research_decision_ref",
        )
    if not isinstance(reference, Mapping):
        _add(
            result,
            "RD.RESEARCH_DECISION.REF_MISSING",
            "ERROR",
            "v3 design must reference the canonical research decision",
            "research_decision_ref",
        )
        return
    selected_id = _text(decision.get("selected_candidate_id"))
    selected = next(
        (
            item
            for item in decision.get("candidates") or []
            if isinstance(item, Mapping) and _text(item.get("id")) == selected_id
        ),
        None,
    )
    question = None
    if selected is not None:
        active_id = _text(selected.get("active_question_version_id"))
        question = next(
            (
                item
                for item in selected.get("question_versions") or []
                if isinstance(item, Mapping) and _text(item.get("id")) == active_id
            ),
            None,
        )
    if selected is None or question is None:
        _add(
            result,
            "RD.RESEARCH_DECISION.ACTIVE_QUESTION",
            "ERROR",
            "cleared research decision lacks a resolvable selected candidate and active question",
            "research_decision_ref",
        )
        return
    expected = {
        "decision_id": _text(decision.get("decision_id")),
        "candidate_id": selected_id,
        "selected_candidate_subgraph_digest": _text(
            decision.get("selected_candidate_subgraph_digest")
        ),
        "question_version_id": _text(question.get("id")),
        "question_sha256": _canonical_digest(question),
        "research_feasibility_ref": decision.get("research_feasibility_ref"),
        "feasibility_basis_digest": _text(
            (decision.get("research_feasibility_ref") or {}).get("basis_digest")
        )
        if isinstance(decision.get("research_feasibility_ref"), Mapping)
        else "",
    }
    for field_name, expected_value in expected.items():
        if reference.get(field_name) != expected_value:
            _add(
                result,
                "RD.RESEARCH_DECISION.STALE",
                "ERROR",
                f"research_decision_ref.{field_name} does not match the current cleared question version",
                f"research_decision_ref.{field_name}",
            )
    primary_questions = [
        item
        for item in payload.get("research_questions") or []
        if isinstance(item, Mapping) and _text(item.get("role")) == "primary"
    ]
    if len(primary_questions) == 1:
        primary = primary_questions[0]
        if _text(primary.get("text")) != _text(question.get("text")):
            _add(
                result,
                "RD.RESEARCH_DECISION.QUESTION_DRIFT",
                "ERROR",
                "design primary question text differs from the active research-decision question version",
                "research_questions",
            )
        if _text(primary.get("primary_type")) != _text(question.get("primary_type")):
            _add(
                result,
                "RD.RESEARCH_DECISION.TYPE_DRIFT",
                "ERROR",
                "design primary question type differs from the active research-decision question version",
                "research_questions",
            )


def _validate_material_plan(base: Path, payload: Mapping[str, Any], result: Any) -> None:
    """Bind design scope to the exact selected F2 material boundary."""

    if not (base / "research_feasibility.json").is_file():
        return
    try:
        from research_feasibility import feasibility_reference, validate_contract

        _root, feasibility, feasibility_result = validate_contract(base)
        reference, reference_issues = feasibility_reference(base)
    except (ImportError, OSError, ValueError) as exc:
        _add(result, "RD.MATERIAL_PLAN.FEASIBILITY_INVALID", "ERROR", str(exc), "material_plan")
        return
    if feasibility is None or feasibility_result.errors or reference is None:
        detail = reference_issues[0] if reference_issues else "F2 feasibility contract is invalid"
        _add(result, "RD.MATERIAL_PLAN.FEASIBILITY_INVALID", "ERROR", detail, "material_plan")
        return
    plan = payload.get("material_plan")
    if not isinstance(plan, Mapping):
        _add(
            result,
            "RD.MATERIAL_PLAN.MISSING",
            "ERROR",
            "v6.2 design must bind the selected F2 material realization plan",
            "material_plan",
        )
        return
    selected_id = _text(feasibility.get("selected_candidate_id"))
    assessment = next(
        (
            item
            for item in feasibility.get("candidate_assessments") or []
            if isinstance(item, Mapping) and _text(item.get("candidate_id")) == selected_id
        ),
        None,
    )
    if assessment is None:
        _add(result, "RD.MATERIAL_PLAN.ASSESSMENT", "ERROR", "selected F2 assessment is missing", "material_plan")
        return
    boundary = assessment.get("allowed_question_boundary") if isinstance(assessment.get("allowed_question_boundary"), Mapping) else {}
    expected_refs = [
        {
            "material_id": _text(item.get("material_id")),
            "probe_ids": sorted(_text(value) for value in item.get("probe_ids") or [] if _text(value)),
        }
        for item in assessment.get("material_refs") or []
        if isinstance(item, Mapping)
    ]
    actual_refs = [
        {
            "material_id": _text(item.get("material_id")),
            "probe_ids": sorted(_text(value) for value in item.get("probe_ids") or [] if _text(value)),
        }
        for item in plan.get("material_refs") or []
        if isinstance(item, Mapping)
    ]
    expected = {
        "feasibility_basis_digest": _text(reference.get("basis_digest")),
        "allowed_question_boundary_digest": _canonical_digest(boundary),
        "time_scope": _text(boundary.get("time_scope")),
        "spatial_scope": _text(boundary.get("spatial_scope")),
        "unit_scope": _text(boundary.get("unit_scope")),
        "required_fields_or_roles": sorted(
            _text(item) for item in boundary.get("required_fields_or_roles") or [] if _text(item)
        ),
        "material_refs": sorted(expected_refs, key=lambda item: item["material_id"]),
    }
    actual = {
        "feasibility_basis_digest": _text(plan.get("feasibility_basis_digest")),
        "allowed_question_boundary_digest": _text(plan.get("allowed_question_boundary_digest")),
        "time_scope": _text(plan.get("time_scope")),
        "spatial_scope": _text(plan.get("spatial_scope")),
        "unit_scope": _text(plan.get("unit_scope")),
        "required_fields_or_roles": sorted(
            _text(item) for item in plan.get("required_fields_or_roles") or [] if _text(item)
        ),
        "material_refs": sorted(actual_refs, key=lambda item: item["material_id"]),
    }
    if actual != expected:
        _add(
            result,
            "RD.MATERIAL_PLAN.STALE",
            "ERROR",
            "material_plan exceeds or no longer matches the selected F2 boundary",
            "material_plan",
        )
    for field_name in ("linkage_plan", "variation_or_identification_plan", "realization_rule"):
        if len(_text(plan.get(field_name))) < 8:
            _add(
                result,
                "RD.MATERIAL_PLAN.INCOMPLETE",
                "ERROR",
                f"material_plan lacks substantive {field_name}",
                f"material_plan.{field_name}",
            )


def validate_payload(
    base: Path,
    payload: Mapping[str, Any],
    *,
    stage: str,
    result: Any,
    v2: Any,
) -> dict[str, set[str]]:
    """Validate v3 by composing the frozen v2 core with case-specific rules."""
    if _text(payload.get("schema_version")) != SCHEMA_VERSION:
        _add(
            result,
            "RD.SCHEMA.UNSUPPORTED",
            "ERROR",
            f"Expected {SCHEMA_VERSION}, found {_text(payload.get('schema_version'))!r}",
            "schema_version",
        )
        return {"all": set()}
    projected = project_to_v2(payload)
    identifiers = v2.validate_payload(base, projected, stage=stage, result=result)
    _validate_research_decision_reference(base, payload, result)
    _validate_material_plan(base, payload, result)
    case_design = payload.get("case_design")
    if not isinstance(case_design, Mapping):
        _add(
            result,
            "RD.CASE.DESIGN_MISSING",
            "ERROR",
            "Every v3 contract must declare case_design, including explicit non-applicability",
            "case_design",
        )
        return identifiers
    applicability = _text(case_design.get("applicability"))
    if applicability not in APPLICATION_STATES:
        _add(
            result,
            "RD.CASE.APPLICABILITY_INVALID",
            "ERROR",
            f"Unsupported case-design applicability {applicability!r}",
            "case_design.applicability",
        )
    _require_text(
        result,
        case_design.get("rationale"),
        "case_design.rationale",
        code="RD.CASE.RATIONALE_MISSING",
    )
    identifiers = _collect_case_ids(case_design, identifiers, result)
    routes = [
        route for route in payload.get("method_routes") or [] if isinstance(route, Mapping)
    ]
    case_routes = [route for route in routes if _text(route.get("family")) in CASE_FAMILIES]
    historical_routes = [
        route for route in routes if _text(route.get("family")) == HISTORICAL_AMBIGUOUS_FAMILY
    ]
    registry = v2.load_adapter_registry()
    _validate_claim_capabilities(payload, case_design, registry, result)
    _validate_typed_method_contracts(payload, result, registry)
    if applicability == "not-applicable":
        if case_routes:
            _add(
                result,
                "RD.CASE.APPLICABILITY_MISMATCH",
                "ERROR",
                "Case-oriented routes cannot declare case_design as not-applicable",
                "case_design.applicability",
            )
        for collection in CASE_COLLECTIONS:
            if case_design.get(collection):
                _add(
                    result,
                    "RD.CASE.NOT_APPLICABLE_HAS_FACTS",
                    "ERROR",
                    f"A not-applicable case design must leave {collection} empty",
                    f"case_design.{collection}",
                )
        integration = case_design.get("integration")
        sequence = _text(integration.get("sequence")) if isinstance(integration, Mapping) else ""
        if sequence != "not-applicable":
            _add(
                result,
                "RD.CASE.INTEGRATION_INVALID",
                "ERROR",
                "A not-applicable case design must use integration.sequence=not-applicable",
                "case_design.integration.sequence",
            )
        return identifiers
    if applicability == "needs-review":
        _add(
            result,
            "RD.CASE.MIGRATION_REVIEW_REQUIRED",
            "ERROR",
            "Case applicability and case roles require independent evidence-backed review before the design can pass",
            "case_design.applicability",
        )
        if historical_routes:
            _add(
                result,
                "RD.REVIEW.HISTORICAL_CASE_ORIENTATION",
                "REVIEW",
                "Historical research is not inferred to be case-oriented from its method label alone",
                "case_design.applicability",
            )
        return identifiers
    if not case_routes:
        _add(
            result,
            "RD.CASE.APPLICABILITY_MISMATCH",
            "ERROR",
            "An active case design requires at least one case-oriented method route",
            "case_design.applicability",
        )
    purposes = _require_list(
        result,
        case_design.get("theoretical_purposes"),
        "case_design.theoretical_purposes",
        nonempty=True,
    )
    for index, value in enumerate(purposes):
        if _text(value) not in THEORETICAL_PURPOSES:
            _add(
                result,
                "RD.CASE.PURPOSE_INVALID",
                "ERROR",
                f"Unsupported theoretical purpose {_text(value)!r}",
                f"case_design.theoretical_purposes[{index}]",
            )
    logics = _require_list(
        result,
        case_design.get("causal_logics"),
        "case_design.causal_logics",
        nonempty=True,
    )
    for index, value in enumerate(logics):
        if _text(value) not in CAUSAL_LOGICS:
            _add(
                result,
                "RD.CASE.CAUSAL_LOGIC_INVALID",
                "ERROR",
                f"Unsupported causal logic {_text(value)!r}",
                f"case_design.causal_logics[{index}]",
            )
    _add(
        result,
        "RD.REVIEW.CASE_THEORETICAL_FIT",
        "REVIEW",
        "Review the fit among theoretical purpose, causal logic, selection strategy, evidence, and inference ceiling",
        "case_design",
    )
    _require_list(result, case_design.get("case_universes"), "case_design.case_universes", nonempty=True)
    _require_list(result, case_design.get("cases"), "case_design.cases", nonempty=True)
    _validate_universes(case_design, identifiers, result)
    _validate_cases(case_design, identifiers, result)
    _validate_scopes(case_design, identifiers, result)
    _validate_comparisons(case_design, identifiers, result)
    _validate_within_case(case_design, identifiers, result)
    _validate_integration(case_design, identifiers, result)
    _validate_route_profile_requirements(payload, case_design, identifiers, result)
    return identifiers


def _md_cell(value: Any) -> str:
    text = _text(value).replace("\r", " ").replace("\n", " ").replace("|", r"\|")
    return re.sub(r"\s+", " ", text).strip()


def _ids(value: Any) -> str:
    return ", ".join(_text(item) for item in value or [] if _text(item)) if isinstance(value, list) else ""


def render_case_design_matrix(payload: Mapping[str, Any]) -> str:
    case_design = payload.get("case_design") if isinstance(payload.get("case_design"), Mapping) else {}
    lines = [
        GENERATED_MARKER,
        "# Case Design Matrix",
        "",
        f"- Applicability: `{_md_cell(case_design.get('applicability'))}`",
        f"- Rationale: {_md_cell(case_design.get('rationale'))}",
        f"- Theoretical purposes: {_md_cell(_ids(case_design.get('theoretical_purposes')))}",
        f"- Causal logics: {_md_cell(_ids(case_design.get('causal_logics')))}",
        "",
        "## Case universes and cases",
        "",
        "| ID | Kind | Label | Universe | Time | Level | Boundary or selection | Design IDs |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for universe in case_design.get("case_universes") or []:
        if isinstance(universe, Mapping):
            lines.append(
                "| "
                + " | ".join(
                    _md_cell(value)
                    for value in (
                        universe.get("id"),
                        "universe",
                        universe.get("label"),
                        "",
                        universe.get("time_scope"),
                        universe.get("level"),
                        f"include={_text(universe.get('inclusion'))}; exclude={_text(universe.get('exclusion'))}",
                        "",
                    )
                )
                + " |"
            )
    for case in case_design.get("cases") or []:
        if isinstance(case, Mapping):
            lines.append(
                "| "
                + " | ".join(
                    _md_cell(value)
                    for value in (
                        case.get("id"),
                        "case",
                        case.get("label"),
                        case.get("universe_id"),
                        case.get("time_scope"),
                        case.get("level"),
                        f"{_text(case.get('selection_strategy'))}: {_text(case.get('case_boundary'))}",
                        _ids(case.get("design_ids")),
                    )
                )
                + " |"
            )
    lines.extend(
        [
            "",
            "## Scope conditions",
            "",
            "| ID | Statement | Status | Claim IDs | Design IDs | Inference impact |",
            "|---|---|---|---|---|---|",
        ]
    )
    for scope in case_design.get("scope_conditions") or []:
        if isinstance(scope, Mapping):
            lines.append(
                "| "
                + " | ".join(
                    _md_cell(value)
                    for value in (
                        scope.get("id"),
                        scope.get("statement"),
                        scope.get("status"),
                        _ids(scope.get("claim_ids")),
                        _ids(scope.get("design_ids")),
                        scope.get("inference_impact"),
                    )
                )
                + " |"
            )
    lines.extend(
        [
            "",
            "## Cross-case and within-case components",
            "",
            "| ID | Mode | Case IDs | Design IDs | Claim IDs | Target or purpose | Inference ceiling |",
            "|---|---|---|---|---|---|---|",
        ]
    )
    for item in case_design.get("comparisons") or []:
        if isinstance(item, Mapping):
            lines.append(
                "| "
                + " | ".join(
                    _md_cell(value)
                    for value in (
                        item.get("id"),
                        item.get("mode"),
                        _ids(item.get("case_ids")),
                        _ids(item.get("design_ids")),
                        "",
                        item.get("target_inference"),
                        item.get("inference_ceiling"),
                    )
                )
                + " |"
            )
    for item in case_design.get("within_case_analyses") or []:
        if isinstance(item, Mapping):
            lines.append(
                "| "
                + " | ".join(
                    _md_cell(value)
                    for value in (
                        item.get("id"),
                        item.get("mode"),
                        _ids(item.get("case_ids")),
                        _ids(item.get("design_ids")),
                        _ids(item.get("claim_ids")),
                        item.get("purpose"),
                        item.get("inference_ceiling"),
                    )
                )
                + " |"
            )
    integration = case_design.get("integration") if isinstance(case_design.get("integration"), Mapping) else {}
    lines.extend(
        [
            "",
            "## Integration",
            "",
            f"- Sequence: `{_md_cell(integration.get('sequence'))}`",
            f"- Route order: {_md_cell(_ids(integration.get('route_order')))}",
            f"- Handoffs: {_md_cell(integration.get('handoffs'))}",
            f"- Material-role separation: {_md_cell(integration.get('material_role_separation'))}",
            f"- Conflict policy: {_md_cell(integration.get('conflict_policy'))}",
            f"- Integrated inference ceiling: {_md_cell(integration.get('inference_ceiling'))}",
            "",
        ]
    )
    return "\n".join(lines)


def render_views(
    base: Path,
    payload: Mapping[str, Any],
    *,
    allow_unmanaged_replace: bool,
    v2: Any,
) -> list[Path]:
    written = v2.render_views(
        base,
        project_to_v2(payload),
        allow_unmanaged_replace=allow_unmanaged_replace,
    )
    target = base / CASE_VIEW_REL
    if (
        target.exists()
        and GENERATED_MARKER not in target.read_text(encoding="utf-8-sig", errors="ignore")
        and not allow_unmanaged_replace
    ):
        raise V3ContractError(
            f"Refusing to overwrite hand-maintained view {target}; run migrate --apply first"
        )
    v2._atomic_write_text(target, render_case_design_matrix(payload))
    return [*written, target]


