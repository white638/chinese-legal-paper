def require_fields(
    result: ValidationResult,
    value: Any,
    fields: tuple[str, ...],
    code: str,
    context: str,
) -> dict[str, Any]:
    if not isinstance(value, dict):
        result.add(code, f"{context} must be an object")
        return {}
    for name in fields:
        if not substantive(value.get(name)):
            result.add(code, f"{context}.{name} is missing or unresolved")
    return value


def validate_anchor(result: ValidationResult, anchor: Any, context: str) -> str:
    if not isinstance(anchor, dict):
        result.add("LA.READING.ANCHOR", f"{context} must be an object")
        return ""
    anchor_type = canonical(anchor.get("anchor_type"))
    if anchor_type not in ANCHOR_TYPES:
        result.add("LA.READING.ANCHOR", f"{context}.anchor_type is unsupported")
    if not substantive(anchor.get("locator")):
        result.add("LA.READING.ANCHOR", f"{context}.locator is missing")
    if not substantive(anchor.get("observation")):
        result.add("LA.READING.ANCHOR", f"{context}.observation is missing")
    return anchor_type


def validate_permissions(
    result: ValidationResult,
    reading: dict[str, Any],
    reading_id: str,
    level: str,
) -> set[str]:
    permissions = reading.get("claim_permissions")
    if not isinstance(permissions, dict):
        result.add("LA.PERMISSION.SHAPE", f"{reading_id} claim_permissions must be an object")
        return set()
    allowed = {canonical(item) for item in permissions.get("allowed") or [] if canonical(item)}
    forbidden = {canonical(item) for item in permissions.get("forbidden") or [] if canonical(item)}
    unknown = (allowed | forbidden) - CLAIM_PERMISSIONS
    if unknown:
        result.add(
            "LA.PERMISSION.UNKNOWN",
            f"{reading_id} has unsupported claim permissions: {', '.join(sorted(unknown))}",
        )
    overlap = allowed & forbidden
    if overlap:
        result.add(
            "LA.PERMISSION.OVERLAP",
            f"{reading_id} marks permissions both allowed and forbidden: {', '.join(sorted(overlap))}",
        )
    missing = CLAIM_PERMISSIONS - allowed - forbidden
    if missing:
        result.add(
            "LA.PERMISSION.UNDECIDED",
            f"{reading_id} leaves claim permissions undecided: {', '.join(sorted(missing))}",
        )
    if level in {"abstract", "detail"}:
        overreach = allowed - LIMITED_ALLOWED
        if overreach:
            result.add(
                "LA.PERMISSION.FULLTEXT_REQUIRED",
                f"{reading_id} uses {level} evidence for full-text-only permissions: "
                + ", ".join(sorted(overreach)),
            )
        missing_heavy = HEAVY_PERMISSIONS - forbidden
        if missing_heavy:
            result.add(
                "LA.PERMISSION.LIMIT_NOT_DECLARED",
                f"{reading_id} must forbid full-text-only uses: {', '.join(sorted(missing_heavy))}",
            )
    return allowed


def validate_background_reading(
    result: ValidationResult,
    reading: dict[str, Any],
    *,
    context: str,
    level: str,
) -> set[str]:
    """Validate a proportional note for a non-core final source.

    Background sources still need a verified purpose, a bounded content note,
    and a locator. They do not mechanically repeat the seven-step core-reading
    form when they carry no theory, method, decisive fact/result, countervoice,
    or conflict-adjudication responsibility.
    """
    note = require_fields(
        result,
        reading.get("background_reading"),
        ("purpose", "content_summary", "use_boundary"),
        "LA.READING.BACKGROUND",
        f"{context}.background_reading",
    )
    anchors = note.get("anchors")
    if not isinstance(anchors, list) or not anchors:
        result.add(
            "LA.READING.BACKGROUND",
            f"{context}.background_reading needs at least one content locator",
        )
        anchors = []
    anchor_types = {
        validate_anchor(result, anchor, f"{context}.background_reading.anchor[{number}]")
        for number, anchor in enumerate(anchors, start=1)
    }
    if level == "full-text" and not (anchor_types & FULL_TEXT_ANCHORS):
        result.add(
            "LA.READING.BACKGROUND",
            f"{context} full-text background reading lacks a page/section/figure/table/data locator",
        )
    return validate_permissions(result, reading, context, level)


def validate_reading(
    result: ValidationResult,
    reading: Any,
    source: dict[str, Any] | None,
    final: bool,
    core: bool,
) -> tuple[str, set[str], str]:
    if not isinstance(reading, dict):
        result.add("LA.READING.SHAPE", "each source_readings item must be an object")
        return "", set(), ""
    reading_id = str(reading.get("reading_id") or "").strip()
    source_id = str(reading.get("source_id") or "").strip()
    context = reading_id or source_id or "unnamed reading"
    if not re.fullmatch(r"CR-[A-Za-z0-9][A-Za-z0-9._-]{0,63}", reading_id):
        result.add("LA.READING.ID", f"{context} has an invalid reading_id")
    if source is None:
        result.add("LA.READING.SOURCE", f"{context} references unknown Source ID {source_id!r}")
        return source_id, set(), reading_id
    if not final:
        result.warn(
            "LA.READING.NONFINAL",
            f"{context} analyses a non-final source; it cannot carry a synthesis claim",
        )
    expected_fingerprint = source_fingerprint(source)
    if reading.get("source_fingerprint") != expected_fingerprint:
        result.add(
            "LA.READING.STALE",
            f"{context} source_fingerprint does not match the current registry record",
        )
    expected_level = evidence_level(source)
    level = canonical(reading.get("evidence_level"))
    if level != expected_level:
        result.add(
            "LA.READING.EVIDENCE_LEVEL",
            f"{context} evidence_level={level or 'missing'}; registry requires {expected_level}",
        )
    if expected_level == "unknown":
        result.add(
            "LA.READING.EVIDENCE_LEVEL",
            f"{context} has no accepted abstract/detail/full-text/PDF content-verification level",
        )
    status = canonical(reading.get("status"))
    if status not in READING_STATUSES:
        result.add("LA.READING.STATUS", f"{context} has unsupported status {status!r}")
    if status == "needs-review":
        result.add("LA.READING.INCOMPLETE", f"{context} still has status=needs-review")
        return source_id, set(), reading_id
    if level == "full-text" and status != "complete":
        result.add(
            "LA.READING.STATUS_LEVEL",
            f"{context} has full text and must complete the critical-reading record",
        )
    if level in {"abstract", "detail"} and status != "limited":
        result.add(
            "LA.READING.STATUS_LEVEL",
            f"{context} has {level} evidence and must declare status=limited",
        )
    depth = canonical(reading.get("reading_depth"))
    expected_depth = "core" if core else "background"
    if depth != expected_depth:
        result.add(
            "LA.READING.DEPTH",
            f"{context} reading_depth must be {expected_depth} under literature_sufficiency",
        )
    if not core:
        return (
            source_id,
            validate_background_reading(result, reading, context=context, level=level),
            reading_id,
        )
    if reading.get("analysis_sequence") != ANALYSIS_SEQUENCE:
        result.add(
            "LA.READING.SEQUENCE",
            f"{context} must record independent evidence interpretation before reading/comparing the author discussion",
        )
    source_type = canonical(reading.get("source_type"))
    if source_type not in SOURCE_TYPES:
        result.add("LA.READING.TYPE", f"{context} has unsupported source_type {source_type!r}")
    require_fields(
        result,
        reading.get("aerial_view"),
        ("scope_and_design", "core_question_or_purpose", "stated_gap_or_context"),
        "LA.READING.AERIAL",
        f"{context}.aerial_view",
    )
    interrogation = require_fields(
        result,
        reading.get("interrogation"),
        ("method_or_argument_fit",),
        "LA.READING.INTERROGATION",
        f"{context}.interrogation",
    )
    independent = interrogation.get("independent_interpretation")
    if not isinstance(independent, dict):
        result.add(
            "LA.READING.INDEPENDENT",
            f"{context}.interrogation.independent_interpretation must be an object",
        )
        independent = {}
    independent_status = canonical(independent.get("status"))
    if independent_status not in {"assessed", "not-assessable"}:
        result.add("LA.READING.INDEPENDENT", f"{context} has invalid independent status")
    if not substantive(independent.get("judgment")):
        result.add("LA.READING.INDEPENDENT", f"{context} lacks an independent judgment")
    anchors = independent.get("anchors")
    if not isinstance(anchors, list) or not anchors:
        result.add("LA.READING.ANCHOR", f"{context} needs at least one evidence locator")
        anchors = []
    anchor_types = {
        validate_anchor(result, anchor, f"{context}.anchor[{number}]")
        for number, anchor in enumerate(anchors, start=1)
    }
    if level == "full-text":
        if independent_status != "assessed":
            result.add(
                "LA.READING.INDEPENDENT",
                f"{context} full-text reading must contain an assessed independent interpretation",
            )
        if not (anchor_types & FULL_TEXT_ANCHORS):
            result.add(
                "LA.READING.ANCHOR",
                f"{context} full-text interpretation lacks a page/section/figure/table/data locator",
            )
    elif level in {"abstract", "detail"} and independent_status != "not-assessable":
        result.add(
            "LA.READING.INDEPENDENT",
            f"{context} cannot claim independent result interpretation from {level} evidence",
        )
    appraisal = interrogation.get("appraisal")
    if not isinstance(appraisal, dict):
        result.add("LA.APPRAISAL.SHAPE", f"{context}.appraisal must be an object")
        appraisal = {}
    profile = canonical(appraisal.get("profile"))
    if profile != source_type:
        result.add(
            "LA.APPRAISAL.PROFILE",
            f"{context} appraisal.profile must match source_type={source_type or 'missing'}",
        )
    criteria = appraisal.get("criteria")
    if not isinstance(criteria, list):
        result.add("LA.APPRAISAL.CRITERIA", f"{context}.appraisal.criteria must be a list")
        criteria = []
    criterion_ids: set[str] = set()
    for number, criterion in enumerate(criteria, start=1):
        if not isinstance(criterion, dict):
            result.add("LA.APPRAISAL.CRITERIA", f"{context} criterion {number} must be an object")
            continue
        criterion_id = canonical(criterion.get("criterion_id"))
        if criterion_id in criterion_ids:
            result.add("LA.APPRAISAL.CRITERIA", f"{context} duplicates criterion {criterion_id}")
        criterion_ids.add(criterion_id)
        if canonical(criterion.get("status")) not in APPRAISAL_STATUSES:
            result.add("LA.APPRAISAL.CRITERIA", f"{context} criterion {criterion_id} has invalid status")
        if not substantive(criterion.get("judgment")):
            result.add("LA.APPRAISAL.CRITERIA", f"{context} criterion {criterion_id} lacks a judgment")
        criterion_anchors = criterion.get("anchors")
        if criterion_anchors is not None and not isinstance(criterion_anchors, list):
            result.add("LA.APPRAISAL.CRITERIA", f"{context} criterion {criterion_id} anchors must be a list")
    required_criteria = APPRAISAL_CRITERIA.get(source_type, set())
    missing_criteria = required_criteria - criterion_ids
    if missing_criteria:
        result.add(
            "LA.APPRAISAL.TYPE_COVERAGE",
            f"{context} lacks type-appropriate criteria: {', '.join(sorted(missing_criteria))}",
        )
    verdict = require_fields(
        result,
        reading.get("verdict"),
        ("author_conclusion", "reader_author_comparison", "conflicts_of_interest", "bounded_verdict"),
        "LA.READING.VERDICT",
        f"{context}.verdict",
    )
    for field_name in ("alternative_explanations", "limitations"):
        values = verdict.get(field_name)
        if not isinstance(values, list) or not any(substantive(item) for item in values):
            result.add(
                "LA.READING.VERDICT",
                f"{context}.verdict.{field_name} must contain at least one considered item",
            )
    missing_evidence = reading.get("missing_evidence")
    if status == "limited" and (
        not isinstance(missing_evidence, list)
        or not any(substantive(item) for item in missing_evidence)
    ):
        result.add(
            "LA.READING.LIMITED",
            f"{context} limited reading must identify the unavailable evidence",
        )
    allowed = validate_permissions(result, reading, context, level)
    return source_id, allowed, reading_id


def validate_synthesis(
    result: ValidationResult,
    item: Any,
    final: dict[str, dict[str, Any]],
    permissions: dict[str, set[str]],
    levels: dict[str, str],
    edges_by_id: dict[str, dict[str, Any]] | None = None,
    registry_has_edges: bool = False,
) -> str:
    if not isinstance(item, dict):
        result.add("LA.SYNTHESIS.SHAPE", "each syntheses item must be an object")
        return ""
    synthesis_id = str(item.get("synthesis_id") or "").strip()
    context = synthesis_id or "unnamed synthesis"
    if not re.fullmatch(r"SYN-[A-Za-z0-9][A-Za-z0-9._-]{0,63}", synthesis_id):
        result.add("LA.SYNTHESIS.ID", f"{context} has an invalid synthesis_id")
    kind = canonical(item.get("kind"))
    if kind not in SYNTHESIS_KINDS:
        result.add("LA.SYNTHESIS.KIND", f"{context} has unsupported kind {kind!r}")
    claim_class = canonical(item.get("claim_class"))
    permission = CLAIM_CLASS_PERMISSION.get(claim_class)
    if permission is None:
        result.add("LA.SYNTHESIS.CLAIM_CLASS", f"{context} has unsupported claim_class {claim_class!r}")
    for field_name in (
        "review_question",
        "proposition",
        "comparability_basis",
        "appraisal_weighting",
        "conflict_or_heterogeneity",
        "analyst_judgment",
        "residual_uncertainty",
    ):
        if not substantive(item.get(field_name)):
            result.add("LA.SYNTHESIS.CONTENT", f"{context}.{field_name} is missing")
    if canonical(item.get("writing_role")) not in WRITING_ROLES:
        result.add("LA.SYNTHESIS.WRITING_ROLE", f"{context} has unsupported writing_role")
    links = item.get("source_links")
    if not isinstance(links, list) or not links:
        result.add("LA.SYNTHESIS.LINK", f"{context} needs at least one source link")
        links = []
    if kind == "cross-source-synthesis" and len(links) < 2:
        result.add(
            "LA.SYNTHESIS.CROSS_SOURCE",
            f"{context} declares cross-source synthesis but links fewer than two sources",
        )
    linked_ids: set[str] = set()
    evidence_links = 0
    for number, link in enumerate(links, start=1):
        if not isinstance(link, dict):
            result.add("LA.SYNTHESIS.LINK", f"{context} link {number} must be an object")
            continue
        source_id = str(link.get("source_id") or "").strip()
        if source_id in linked_ids:
            result.add("LA.SYNTHESIS.LINK", f"{context} duplicates Source ID {source_id}")
        linked_ids.add(source_id)
        if source_id not in final:
            result.add(
                "LA.SYNTHESIS.FINAL_SOURCE",
                f"{context} uses {source_id or 'missing Source ID'} which is not a current final-source",
            )
        relation = canonical(link.get("relation"))
        use = canonical(link.get("use"))
        comparability = canonical(link.get("comparability"))
        if relation not in SYNTHESIS_RELATIONS:
            result.add("LA.SYNTHESIS.LINK", f"{context} link {source_id} has unsupported relation")
        if use not in SYNTHESIS_USES:
            result.add("LA.SYNTHESIS.LINK", f"{context} link {source_id} has unsupported use")
        if comparability not in COMPARABILITY:
            result.add("LA.SYNTHESIS.LINK", f"{context} link {source_id} has unsupported comparability")
        if not substantive(link.get("rationale")):
            result.add("LA.SYNTHESIS.LINK", f"{context} link {source_id} lacks a rationale")
        raw_edge_ids = link.get("edge_ids")
        if raw_edge_ids is not None:
            if (
                not isinstance(raw_edge_ids, list)
                or not raw_edge_ids
                or any(not str(value).strip() for value in raw_edge_ids)
            ):
                result.add("LA.SYNTHESIS.EDGE", f"{context} link {source_id} edge_ids must be a non-empty list")
            else:
                for raw_edge in raw_edge_ids:
                    edge_id = str(raw_edge).strip()
                    edge = (edges_by_id or {}).get(edge_id)
                    if edge is None:
                        result.add("LA.SYNTHESIS.EDGE", f"{context} link {source_id} cites unknown citation edge {edge_id}")
                        continue
                    endpoints = {
                        str(edge.get("from_source_id") or "").strip(),
                        str(edge.get("to_source_id") or "").strip(),
                    }
                    if source_id not in endpoints:
                        result.add("LA.SYNTHESIS.EDGE", f"{context} link {source_id} edge {edge_id} does not touch this source")
        elif registry_has_edges and relation == "contradicts":
            result.warn(
                "LA.SYNTHESIS.EDGE",
                f"{context} link {source_id} claims contradiction without a verified citation edge; "
                "the relation between sources is asserted, not observed",
            )
        if use == "evidence":
            evidence_links += 1
            if permission and permission not in permissions.get(source_id, set()):
                result.add(
                    "LA.SYNTHESIS.PERMISSION",
                    f"{context} uses {source_id} as evidence for {claim_class} without that reading permission",
                )
            if levels.get(source_id) in {"abstract", "detail"}:
                result.add(
                    "LA.SYNTHESIS.FULLTEXT_REQUIRED",
                    f"{context} uses {source_id} as evidence for synthesis from {levels[source_id]} only",
                )
    if claim_class in {
        "method-quality",
        "result-interpretation",
        "causal-mechanism",
        "robustness-generalization",
        "conflict-adjudication",
    } and not evidence_links:
        result.add(
            "LA.SYNTHESIS.EVIDENCE",
            f"{context} makes a load-bearing {claim_class} judgment without a full-text evidence link",
        )
    return synthesis_id


def validate_problem_arc(
    result: ValidationResult,
    arc: Any,
    *,
    authority_ids: set[str],
) -> int:
    """Validate an optional problem biography inside the canonical analysis.

    The arc records analyst judgments about how the live question changed.  It
    does not create source identities: every transition must resolve to an
    existing Source, CR, or SYN identity.
    """

    if arc is None:
        return 0
    if not isinstance(arc, dict):
        result.add("AP.ARC.SHAPE", "problem_arc must be an object")
        return 0
    arc_id = str(arc.get("arc_id") or "").strip()
    if not re.fullmatch(r"ARC-[A-Za-z0-9][A-Za-z0-9._-]*", arc_id):
        result.add("AP.ARC.SHAPE", "problem_arc.arc_id is invalid")
    states = arc.get("states")
    if not isinstance(states, list) or not states:
        result.add("AP.ARC.SHAPE", "problem_arc.states must be a non-empty array")
        return 0
    seen: set[str] = set()
    branches: dict[str, list[dict[str, Any]]] = {}
    for index, state in enumerate(states, start=1):
        context = f"problem_arc.states[{index}]"
        if not isinstance(state, dict):
            result.add("AP.ARC.SHAPE", f"{context} must be an object")
            continue
        state_id = str(state.get("state_id") or "").strip()
        if not re.fullmatch(r"ARC-STATE-[A-Za-z0-9][A-Za-z0-9._-]*", state_id):
            result.add("AP.ARC.SHAPE", f"{context}.state_id is invalid")
        elif state_id in seen:
            result.add("AP.ARC.ORDER_INVALID", f"problem_arc repeats state_id {state_id}")
        for field_name in (
            "live_question",
            "provisional_answer",
            "pressure",
            "updated_problem",
            "residual_unknown",
        ):
            if not substantive(state.get(field_name)):
                result.add("AP.ARC.CONTENT", f"{context}.{field_name} is missing")
        transition = str(state.get("transition_type") or "").strip().upper()
        if transition not in PROBLEM_ARC_TRANSITIONS:
            result.add("AP.ARC.TRANSITION_INVALID", f"{context}.transition_type is unsupported")
        refs = state.get("authority_refs")
        if not isinstance(refs, list) or not refs:
            result.add("AP.ARC.AUTHORITY_MISSING", f"{context} has no transition authority")
        else:
            normalized = {str(value or "").strip() for value in refs if str(value or "").strip()}
            unknown = sorted(normalized - authority_ids)
            if not normalized or unknown:
                detail = ", ".join(unknown) or "no current Source/CR/SYN identity"
                result.add("AP.ARC.AUTHORITY_MISSING", f"{context} has unresolved transition authority: {detail}")
        predecessors = state.get("predecessor_state_refs", [])
        if not isinstance(predecessors, list):
            result.add("AP.ARC.ORDER_INVALID", f"{context}.predecessor_state_refs must be an array")
        else:
            future_or_unknown = sorted(
                {str(value or "").strip() for value in predecessors if str(value or "").strip()} - seen
            )
            if future_or_unknown:
                result.add(
                    "AP.ARC.ORDER_INVALID",
                    f"{context} references a predecessor that is absent or not earlier: {', '.join(future_or_unknown)}",
                )
        branch_id = str(state.get("branch_id") or "").strip()
        if branch_id:
            branches.setdefault(branch_id, []).append(state)
        seen.add(state_id)
    major = {
        str(value or "").strip()
        for value in arc.get("major_branch_ids") or []
        if str(value or "").strip()
    }
    if major:
        missing = sorted(major - set(branches))
        if missing:
            result.add(
                "AP.ARC.BRANCH_DROPPED",
                "problem_arc omits declared major competing branches: " + ", ".join(missing),
            )
        for branch_id in sorted(major & set(branches)):
            terminal = branches[branch_id][-1]
            if not substantive(terminal.get("branch_disposition")):
                result.add(
                    "AP.ARC.BRANCH_DROPPED",
                    f"major branch {branch_id} ends without a documented disposition",
                )
    return len(states)


def identity_tokens(value: Any, prefix: str) -> set[str]:
    pattern = rf"\b{re.escape(prefix)}-[A-Za-z0-9][A-Za-z0-9._-]*"
    return {
        match.group(0).rstrip(".,;:")
        for match in re.finditer(pattern, str(value or ""))
    }


def validate_design_links(
    result: ValidationResult,
    base: Path,
    review_type: str,
    reading_ids: set[str],
    synthesis_ids: set[str],
) -> None:
    path = base / "research_design.json"
    if not path.is_file():
        return
    try:
        design = load_object(path, "research design")
    except ValueError:
        return
    knowledge = design.get("knowledge_state")
    if not isinstance(knowledge, dict):
        return
    if canonical(knowledge.get("review_type")) != review_type:
        result.add(
            "LA.DESIGN.REVIEW_TYPE",
            "research_design.json knowledge_state.review_type does not match literature_analysis.json",
        )
    contracts = {
        "reading_records": ("CR", reading_ids),
        "quality_appraisal": ("CR", reading_ids),
        "gap_authenticity": ("SYN", synthesis_ids),
        "synthesis_logic": ("SYN", synthesis_ids),
        "contradictory_evidence": ("SYN", synthesis_ids),
    }
    for field_name, (prefix, known) in contracts.items():
        tokens = identity_tokens(knowledge.get(field_name), prefix)
        if not tokens:
            result.add(
                "LA.DESIGN.LINK_MISSING",
                f"research_design.json knowledge_state.{field_name} must cite current {prefix}-* identities",
            )
            continue
        unknown = tokens - known
        if unknown:
            result.add(
                "LA.DESIGN.LINK_UNKNOWN",
                f"research_design.json knowledge_state.{field_name} cites unknown identities: "
                + ", ".join(sorted(unknown)),
            )


def validate_analysis(base: Path, *, stage: str = "research") -> tuple[ValidationResult, dict[str, Any]]:
    result = ValidationResult()
    try:
        registry = load_object(base / REGISTRY_REL, "literature registry")
    except ValueError as exc:
        result.add("LA.REGISTRY.MISSING", str(exc))
        return result, {}
    try:
        analysis = load_object(base / ANALYSIS_REL, "literature analysis")
    except ValueError as exc:
        result.add(
            "LA.ANALYSIS.MISSING",
            f"{exc}; run literature_analysis.py migrate OUTDIR --dry-run, review it, then --apply",
        )
        return result, {}
    schema = str(analysis.get("schema_version") or "")
    if schema != SCHEMA_VERSION:
        result.add(
            "LA.SCHEMA",
            f"schema_version must be {SCHEMA_VERSION}; {SCHEMA_VERSION_V1} is migration-readable only",
        )
    if schema == SCHEMA_VERSION_V2:
        binding = analysis.get("registry_binding")
        if not isinstance(binding, dict):
            result.add("LA.REGISTRY.BINDING", "registry_binding is required in literature analysis v2")
        else:
            bound_ids = binding.get("source_ids")
            if not isinstance(bound_ids, list) or any(not str(item).strip() for item in bound_ids):
                result.add("LA.REGISTRY.BINDING", "registry_binding.source_ids must list load-bearing sources")
            else:
                normalized_ids = [str(item).strip() for item in bound_ids]
                expected = registry_binding_digest(registry, normalized_ids)
                if binding.get("digest") != expected:
                    result.add(
                        "LA.REGISTRY.STALE",
                        "a load-bearing source identity, permission, verification, relevance, or file hash changed",
                    )
    else:
        expected_registry_digest = file_digest(base / REGISTRY_REL)
        if analysis.get("registry_digest") != expected_registry_digest:
            result.add(
                "LA.REGISTRY.STALE",
                "legacy literature analysis is bound to an older literature_registry.json",
            )
    scope = analysis.get("review_scope")
    if not isinstance(scope, dict):
        result.add("LA.SCOPE.SHAPE", "review_scope must be an object")
        scope = {}
    review_type = canonical(scope.get("review_type"))
    if review_type not in REVIEW_TYPES:
        result.add("LA.SCOPE.TYPE", f"review_scope.review_type is unsupported: {review_type!r}")
    for field_name in (
        "review_question",
        "search_scope",
        "inclusion_boundary",
        "exclusion_boundary",
        "synthesis_logic",
    ):
        if not substantive(scope.get(field_name)):
            result.add("LA.SCOPE.CONTENT", f"review_scope.{field_name} is missing")
    if review_type in {"scoping", "systematic"} and not substantive(scope.get("reporting_standard")):
        result.add(
            "LA.SCOPE.REPORTING",
            f"{review_type} review must declare its applicable reporting standard",
        )
    migration_status = canonical(analysis.get("migration_status"))
    if migration_status not in MIGRATION_STATUSES:
        result.add("LA.MIGRATION.STATUS", f"unsupported migration_status {migration_status!r}")
    final = final_sources(registry)
    registry_sources = all_sources(registry)
    readings = analysis.get("source_readings")
    if not isinstance(readings, list):
        result.add("LA.READING.SHAPE", "source_readings must be a list")
        readings = []
    sufficiency_contract = (
        analysis.get("literature_sufficiency")
        if isinstance(analysis.get("literature_sufficiency"), dict)
        else {}
    )
    raw_core_ids = sufficiency_contract.get("core_reading_source_ids")
    core_source_ids = {
        str(item).strip()
        for item in raw_core_ids or []
        if str(item).strip()
    } if isinstance(raw_core_ids, list) else set()
    result.stats.update(
        {
            "review_type": review_type or "missing",
            "migration_status": migration_status or "missing",
            "final_sources": len(final),
            "source_readings": len(readings),
        }
    )
    if migration_status == "legacy-limited":
        declaration = analysis.get("legacy_declaration")
        if not isinstance(declaration, dict):
            result.add("LA.LEGACY.DECLARATION", "legacy-limited analysis needs legacy_declaration")
            declaration = {}
        if declaration.get("audit_only") is not True:
            result.add("LA.LEGACY.DECLARATION", "legacy_declaration.audit_only must be true")
        if declaration.get("no_new_literature_claims") is not True:
            result.add(
                "LA.LEGACY.DECLARATION",
                "legacy_declaration.no_new_literature_claims must be true",
            )
        if not substantive(declaration.get("limitation_note")):
            result.add("LA.LEGACY.DECLARATION", "legacy_declaration.limitation_note is missing")
        if task_profile(base) != "manuscript_audit" or canonical(stage) not in {"audit", "output"}:
            result.add(
                "LA.LEGACY.SCOPE",
                "legacy-limited is allowed only for an explicitly declared manuscript_audit at audit/output",
            )
        declared_unreviewed = {
            str(item or "").strip()
            for item in analysis.get("unreviewed_final_source_ids") or []
            if str(item or "").strip()
        }
        if declared_unreviewed != set(final):
            result.add(
                "LA.LEGACY.COVERAGE",
                "unreviewed_final_source_ids must exactly declare every current final-source",
            )
        result.warn(
            "LA.LEGACY.REDUCED_ASSURANCE",
            "legacy audit proceeds with reduced literature-analysis assurance and cannot introduce new literature claims",
        )
        config = project_config(base)
        sufficiency = evaluate_literature_sufficiency(
            config=config,
            registry=registry,
            analysis=analysis,
            profile=task_profile(base),
            stage=stage,
        )
        for message in sufficiency.issues:
            result.warn("LA.SUFFICIENCY.LEGACY", message)
        for message in sufficiency.warnings:
            result.warn("LA.SUFFICIENCY.GAP", message)
        result.stats["literature_sufficiency"] = sufficiency.summary
        result.stats["syntheses"] = 0
        return result, analysis
    if migration_status == "needs-review":
        result.add(
            "LA.MIGRATION.INCOMPLETE",
            "migration scaffold still needs source-by-source critical reading and synthesis",
        )
    seen_source_ids: set[str] = set()
    seen_reading_ids: set[str] = set()
    permissions: dict[str, set[str]] = {}
    levels: dict[str, str] = {}
    for reading in readings:
        source_id = str(reading.get("source_id") or "").strip() if isinstance(reading, dict) else ""
        reading_id = str(reading.get("reading_id") or "").strip() if isinstance(reading, dict) else ""
        if source_id in seen_source_ids and source_id:
            result.add("LA.READING.DUPLICATE", f"duplicate source reading for {source_id}")
        if reading_id in seen_reading_ids and reading_id:
            result.add("LA.READING.DUPLICATE", f"duplicate reading_id {reading_id}")
        seen_source_ids.add(source_id)
        seen_reading_ids.add(reading_id)
        source_id, allowed, _ = validate_reading(
            result,
            reading,
            registry_sources.get(source_id),
            source_id in final,
            source_id in core_source_ids,
        )
        permissions[source_id] = allowed
        if source_id in registry_sources:
            levels[source_id] = evidence_level(registry_sources[source_id])
    missing_final = set(final) - seen_source_ids
    if missing_final:
        result.add(
            "LA.READING.COVERAGE",
            "every final-source requires a critical-reading record; missing: "
            + ", ".join(sorted(missing_final)),
        )
    syntheses = analysis.get("syntheses")
    if not isinstance(syntheses, list) or not syntheses:
        result.add("LA.SYNTHESIS.MISSING", "at least one problem-led synthesis unit is required")
        syntheses = []
    seen_synthesis_ids: set[str] = set()
    for item in syntheses:
        synthesis_id = validate_synthesis(
            result,
            item,
            final,
            permissions,
            levels,
            edges_by_id=citation_edges.edges_by_id(registry),
            registry_has_edges=citation_edges.has_edges(registry),
        )
        if synthesis_id in seen_synthesis_ids and synthesis_id:
            result.add("LA.SYNTHESIS.DUPLICATE", f"duplicate synthesis_id {synthesis_id}")
        seen_synthesis_ids.add(synthesis_id)
    result.stats["syntheses"] = len(syntheses)
    result.stats["problem_arc_states"] = validate_problem_arc(
        result,
        analysis.get("problem_arc"),
        authority_ids=set(registry_sources) | seen_reading_ids | seen_synthesis_ids,
    )
    config = project_config(base)
    sufficiency = evaluate_literature_sufficiency(
        config=config,
        registry=registry,
        analysis=analysis,
        profile=task_profile(base),
        stage=stage,
    )
    for message in sufficiency.issues:
        result.add("LA.SUFFICIENCY", message)
    for message in sufficiency.warnings:
        result.warn("LA.SUFFICIENCY.GAP", message)
    result.stats["literature_sufficiency"] = sufficiency.summary
    if canonical(stage) in DESIGN_AND_LATER:
        validate_design_links(
            result,
            base,
            review_type,
            seen_reading_ids,
            seen_synthesis_ids,
        )
    return result, analysis


def markdown_escape(value: Any) -> str:
    return str(value or "").replace("|", r"\|").replace("\r", " ").replace("\n", " ")


def render_readings(base: Path, analysis: dict[str, Any], registry: dict[str, Any]) -> str:
    sources = all_sources(registry)
    scope = analysis.get("review_scope") if isinstance(analysis.get("review_scope"), dict) else {}
    lines = [
        GENERATED_MARKER,
        "# Critical Reading Report",
        "",
        f"- Schema: {analysis.get('schema_version', 'missing')}",
        f"- Migration status: {analysis.get('migration_status', 'missing')}",
        f"- Review type: {scope.get('review_type', 'missing')}",
        f"- Review question: {scope.get('review_question', 'missing')}",
        "",
    ]
    for reading in analysis.get("source_readings") or []:
        if not isinstance(reading, dict):
            continue
        source_id = str(reading.get("source_id") or "")
        source = sources.get(source_id, {})
        lines.extend(
            [
                f"## {reading.get('reading_id', 'CR-missing')} — {source_id}",
                "",
                f"- Title: {source.get('title', 'missing')}",
                f"- Source type: {reading.get('source_type', 'missing')}",
                f"- Evidence level: {reading.get('evidence_level', 'missing')}",
                f"- Reading status: {reading.get('status', 'missing')}",
                f"- Reading depth: {reading.get('reading_depth', 'missing')}",
                "",
            ]
        )
        if canonical(reading.get("status")) == "needs-review":
            lines.extend(["This record still requires an independent evidence-backed critical reading.", ""])
            continue
        if canonical(reading.get("reading_depth")) == "background":
            note = (
                reading.get("background_reading")
                if isinstance(reading.get("background_reading"), dict)
                else {}
            )
            permissions = (
                reading.get("claim_permissions")
                if isinstance(reading.get("claim_permissions"), dict)
                else {}
            )
            lines.extend(
                [
                    "### Proportional background reading",
                    "",
                    f"- Purpose: {note.get('purpose', 'missing')}",
                    f"- Content summary: {note.get('content_summary', 'missing')}",
                    f"- Use boundary: {note.get('use_boundary', 'missing')}",
                    f"- Allowed uses: {', '.join(permissions.get('allowed') or []) or 'none'}",
                    f"- Forbidden uses: {', '.join(permissions.get('forbidden') or []) or 'none'}",
                    "",
                ]
            )
            continue
        aerial = reading.get("aerial_view") if isinstance(reading.get("aerial_view"), dict) else {}
        interrogation = reading.get("interrogation") if isinstance(reading.get("interrogation"), dict) else {}
        independent = interrogation.get("independent_interpretation") if isinstance(interrogation.get("independent_interpretation"), dict) else {}
        verdict = reading.get("verdict") if isinstance(reading.get("verdict"), dict) else {}
        lines.extend(
            [
                "### Phase 1 — Aerial view",
                "",
                f"- Scope/design: {aerial.get('scope_and_design', 'missing')}",
                f"- Core question/purpose: {aerial.get('core_question_or_purpose', 'missing')}",
                f"- Stated gap/context: {aerial.get('stated_gap_or_context', 'missing')}",
                "",
                "### Phase 2 — Interrogation",
                "",
                f"- Method/argument fit: {interrogation.get('method_or_argument_fit', 'missing')}",
                f"- Independent interpretation ({independent.get('status', 'missing')}): {independent.get('judgment', 'missing')}",
                "",
                "### Phase 3 — Verdict",
                "",
                f"- Author conclusion: {verdict.get('author_conclusion', 'missing')}",
                f"- Reader–author comparison: {verdict.get('reader_author_comparison', 'missing')}",
                f"- Bounded verdict: {verdict.get('bounded_verdict', 'missing')}",
                f"- Conflicts of interest: {verdict.get('conflicts_of_interest', 'missing')}",
                "",
            ]
        )
        appraisal = interrogation.get("appraisal") if isinstance(interrogation.get("appraisal"), dict) else {}
        lines.extend(
            [
                "### Type-adapted appraisal",
                "",
                "| Criterion | Status | Judgment |",
                "|---|---|---|",
            ]
        )
        for criterion in appraisal.get("criteria") or []:
            if isinstance(criterion, dict):
                lines.append(
                    "| "
                    + " | ".join(
                        markdown_escape(criterion.get(key))
                        for key in ("criterion_id", "status", "judgment")
                    )
                    + " |"
                )
        permissions = reading.get("claim_permissions") if isinstance(reading.get("claim_permissions"), dict) else {}
        lines.extend(
            [
                "",
                f"- Allowed uses: {', '.join(permissions.get('allowed') or []) or 'none'}",
                f"- Forbidden uses: {', '.join(permissions.get('forbidden') or []) or 'none'}",
                "",
            ]
        )
    return "\n".join(lines).rstrip() + "\n"


def render_syntheses(analysis: dict[str, Any]) -> str:
    scope = analysis.get("review_scope") if isinstance(analysis.get("review_scope"), dict) else {}
    lines = [
        GENERATED_MARKER,
        "# Literature Synthesis Matrix",
        "",
        f"- Review type: {scope.get('review_type', 'missing')}",
        f"- Review question: {scope.get('review_question', 'missing')}",
        f"- Search scope: {scope.get('search_scope', 'missing')}",
        f"- Inclusion boundary: {scope.get('inclusion_boundary', 'missing')}",
        f"- Exclusion boundary: {scope.get('exclusion_boundary', 'missing')}",
        f"- Synthesis logic: {scope.get('synthesis_logic', 'missing')}",
        f"- Reporting standard: {scope.get('reporting_standard', 'not-applicable')}",
        "",
        "| Synthesis ID | Kind | Claim class | Proposition | Source relations | Comparability | Analyst judgment | Remaining uncertainty | Writing role |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for item in analysis.get("syntheses") or []:
        if not isinstance(item, dict):
            continue
        relations = "; ".join(
            f"{link.get('source_id')}:{link.get('relation')}/{link.get('use')}"
            for link in item.get("source_links") or []
            if isinstance(link, dict)
        )
        row = [
            item.get("synthesis_id"),
            item.get("kind"),
            item.get("claim_class"),
            item.get("proposition"),
            relations,
            item.get("comparability_basis"),
            item.get("analyst_judgment"),
            item.get("residual_uncertainty"),
            item.get("writing_role"),
        ]
        lines.append("| " + " | ".join(markdown_escape(value) for value in row) + " |")
    arc = analysis.get("problem_arc") if isinstance(analysis.get("problem_arc"), dict) else None
    if arc:
        lines.extend(
            [
                "",
                "## Problem Arc",
                "",
                "| State ID | Live Question | Provisional Answer | Pressure | Transition | Updated Problem | Residual Unknown | Authority Refs | Branch | Branch Disposition |",
                "|---|---|---|---|---|---|---|---|---|---|",
            ]
        )
        for state in arc.get("states") or []:
            if not isinstance(state, dict):
                continue
            lines.append(
                "| "
                + " | ".join(
                    markdown_escape(value)
                    for value in (
                        state.get("state_id"),
                        state.get("live_question"),
                        state.get("provisional_answer"),
                        state.get("pressure"),
                        state.get("transition_type"),
                        state.get("updated_problem"),
                        state.get("residual_unknown"),
                        ", ".join(state.get("authority_refs") or []),
                        state.get("branch_id") or "main",
                        state.get("branch_disposition") or "continues",
                    )
                )
                + " |"
            )
    lines.append("")
    return "\n".join(lines)


def render_report(result: ValidationResult, schema: str) -> str:
    lines = [
        GENERATED_MARKER,
        "# Literature Analysis Check",
        "",
        f"Status: {'PASS' if result.ok else 'FAIL'}",
        "",
        f"- schema_version: {schema}",
    ]
    for key, value in result.stats.items():
        lines.append(f"- {key}: {value}")
    if result.issues:
        lines.extend(["", "## Blocking Issues", ""])
        lines.extend(f"- {item.code}: {item.message}" for item in result.issues)
    if result.warnings:
        lines.extend(["", "## Warnings", ""])
        lines.extend(f"- {item.code}: {item.message}" for item in result.warnings)
    lines.append("")
    return "\n".join(lines)


def write_views(base: Path, result: ValidationResult, analysis: dict[str, Any]) -> None:
    try:
        registry = load_object(base / REGISTRY_REL, "literature registry")
    except ValueError:
        registry = {}
    (base / READING_VIEW_REL).write_text(
        render_readings(base, analysis, registry),
        encoding="utf-8",
    )
    (base / SYNTHESIS_VIEW_REL).write_text(render_syntheses(analysis), encoding="utf-8")
    (base / REPORT_REL).write_text(
        render_report(result, str(analysis.get("schema_version") or "missing")),
        encoding="utf-8",
    )


def scaffold(base: Path, *, review_type: str, legacy_limited: bool) -> dict[str, Any]:
    registry = load_object(base / REGISTRY_REL, "literature registry")
    final = final_sources(registry)
    registered = all_sources(registry)
    readings = [
        {
            "reading_id": f"CR-{source_id}",
            "source_id": source_id,
            "source_fingerprint": source_fingerprint(source),
            "source_type": "other",
            "evidence_level": evidence_level(source),
            "status": "needs-review",
            "reading_depth": "background",
            "background_reading": {
                "purpose": "",
                "content_summary": "",
                "use_boundary": "",
                "anchors": [],
            },
        }
        for source_id, source in sorted(final.items())
    ]
    sufficiency = empty_sufficiency_contract()
    sufficiency["screened_source_ids"] = sorted(registered)
    sufficiency["final_source_ids"] = sorted(final)
    sufficiency["current_qualified_count"] = 0
    payload: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "registry_binding": {
            "source_ids": sorted(final),
            "digest": registry_binding_digest(registry, sorted(final)),
        },
        "legacy_registry_digest": file_digest(base / REGISTRY_REL),
        "migration_status": "legacy-limited" if legacy_limited else "needs-review",
        "review_scope": {
            "review_type": review_type,
            "review_question": "",
            "search_scope": "",
            "inclusion_boundary": "",
            "exclusion_boundary": "",
            "synthesis_logic": "",
            "reporting_standard": "",
        },
        "source_readings": readings,
        "syntheses": [],
        "literature_sufficiency": sufficiency,
    }
    if legacy_limited:
        payload["unreviewed_final_source_ids"] = sorted(final)
        payload["legacy_declaration"] = {
            "audit_only": True,
            "no_new_literature_claims": True,
            "limitation_note": "",
        }
    return payload


def command_validate(args: argparse.Namespace) -> int:
    base = Path(args.outdir).resolve()
    result, analysis = validate_analysis(base, stage=args.stage)
    if args.write and analysis:
        write_views(base, result, analysis)
    schema = str(analysis.get("schema_version") or "missing") if analysis else "missing"
    if args.json:
        print(json.dumps(result.as_dict(schema), ensure_ascii=False, indent=2))
    else:
        print(render_report(result, schema), end="")
    return 0 if result.ok else 1


def command_render(args: argparse.Namespace) -> int:
    base = Path(args.outdir).resolve()
    result, analysis = validate_analysis(base, stage=args.stage)
    if not analysis:
        print(render_report(result, "missing"), end="")
        return 1
    write_views(base, result, analysis)
    print(f"wrote {READING_VIEW_REL}, {SYNTHESIS_VIEW_REL}, and {REPORT_REL}")
    return 0 if result.ok else 1


def command_migrate(args: argparse.Namespace) -> int:
    base = Path(args.outdir).resolve()
    path = base / ANALYSIS_REL
    if path.exists():
        print(f"refusing to overwrite existing canonical analysis: {path}", file=sys.stderr)
        return 2
    try:
        payload = scaffold(
            base,
            review_type=args.review_type,
            legacy_limited=args.legacy_limited,
        )
    except ValueError as exc:
        print(str(exc), file=sys.stderr)
        return 2
    print(json.dumps(payload, ensure_ascii=False, indent=2))
    if args.apply:
        path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        result, analysis = validate_analysis(base, stage="audit" if args.legacy_limited else "research")
        write_views(base, result, analysis)
        print(f"\nwrote {path}; all scaffolded readings remain needs-review")
    else:
        print("\ndry-run only; rerun with --apply after reviewing this migration scaffold")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)

    validate = subparsers.add_parser("validate", help="validate the canonical analysis")
    validate.add_argument("outdir")
    validate.add_argument(
        "--stage",
        default="research",
        choices=("research", "design", "execution", "build", "audit", "output"),
    )
    validate.add_argument("--json", action="store_true")
    validate.add_argument("--write", action="store_true", help="refresh generated views and report")
    validate.set_defaults(func=command_validate)

    render = subparsers.add_parser("render", help="render generated human-readable views")
    render.add_argument("outdir")
    render.add_argument(
        "--stage",
        default="research",
        choices=("research", "design", "execution", "build", "audit", "output"),
    )
    render.set_defaults(func=command_render)

    migrate = subparsers.add_parser(
        "migrate",
        help="scaffold analysis records without inventing critical judgments",
    )
    migrate.add_argument("outdir")
    migrate.add_argument("--review-type", choices=sorted(REVIEW_TYPES), default="embedded")
    migrate.add_argument("--legacy-limited", action="store_true")
    mode = migrate.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true")
    mode.add_argument("--apply", action="store_true")
    migrate.set_defaults(func=command_migrate)
    return parser


def main() -> int:
    args = build_parser().parse_args()
    return int(args.func(args))


if __name__ == "__main__":
    raise SystemExit(main())
