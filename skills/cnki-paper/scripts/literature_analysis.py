@dataclass
class Issue:
    code: str
    message: str

    def as_dict(self) -> dict[str, str]:
        return {"code": self.code, "message": self.message}


@dataclass
class ValidationResult:
    issues: list[Issue] = field(default_factory=list)
    warnings: list[Issue] = field(default_factory=list)
    stats: dict[str, Any] = field(default_factory=dict)

    @property
    def ok(self) -> bool:
        return not self.issues

    def add(self, code: str, message: str) -> None:
        self.issues.append(Issue(code, message))

    def warn(self, code: str, message: str) -> None:
        self.warnings.append(Issue(code, message))

    def as_dict(self, schema_version: str = "missing") -> dict[str, Any]:
        return {
            "ok": self.ok,
            "schema_version": schema_version,
            "issues": [item.as_dict() for item in self.issues],
            "warnings": [item.as_dict() for item in self.warnings],
            "stats": self.stats,
        }


def canonical(value: Any) -> str:
    return re.sub(r"[_\s]+", "-", str(value or "").strip().lower())


def substantive(value: Any) -> bool:
    if not isinstance(value, str):
        return False
    return canonical(value) not in PLACEHOLDERS


def load_object(path: Path, label: str) -> dict[str, Any]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8-sig"))
    except FileNotFoundError as exc:
        raise ValueError(f"missing {label}: {path}") from exc
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"invalid {label}: {path}: {exc}") from exc
    if not isinstance(payload, dict):
        raise ValueError(f"{label} must contain one JSON object")
    return payload


def file_digest(path: Path) -> str:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return ""


def semantic_source_payload(source: dict[str, Any]) -> dict[str, Any]:
    """Return only claim-bearing source fields.

    Discovery queries, collection timestamps, and candidate notes are intentionally
    excluded. Identity, permission, verification, relevance, and file hashes remain
    binding because changing any of them can change what the manuscript may claim.
    """
    verification = source.get("verification") if isinstance(source.get("verification"), dict) else {}
    credibility = source.get("credibility") if isinstance(source.get("credibility"), dict) else {}
    relevance = source.get("relevance") if isinstance(source.get("relevance"), dict) else {}
    return {
        "source_id": source.get("source_id"),
        "channel": source.get("channel"),
        "title": source.get("title"),
        "authors": source.get("authors") or source.get("author"),
        "publication_year": source.get("publication_year") or source.get("year"),
        "venue": source.get("venue"),
        "doi": source.get("doi"),
        "identity": source.get("identity") if isinstance(source.get("identity"), dict) else {},
        "url": source.get("url"),
        "local_file": source.get("local_file"),
        "sha256": source.get("sha256") or source.get("file_sha256"),
        "state": source.get("state"),
        "citation_scope": source.get("citation_scope"),
        "roles": source.get("roles"),
        "material_role": source.get("material_role"),
        "document_role": source.get("document_role"),
        "academic_work": source.get("academic_work"),
        "verification": {
            key: verification.get(key)
            for key in (
                "method",
                "content_url",
                "support_claim",
                "verified_at",
                "retraction_status",
                "ocr_text_file",
                "ocr_text_sha256",
            )
            if key in verification
        },
        "credibility": {
            key: credibility.get(key)
            for key in ("source_class", "status", "checked_at", "corroborating_source_ids", "contradicting_source_ids")
            if key in credibility
        },
        "relevance": {
            key: relevance.get(key)
            for key in ("status", "responsibilities", "problem_ids", "position_ids", "claim_ids", "method_ids")
            if key in relevance
        },
    }


def source_fingerprint(source: dict[str, Any]) -> str:
    payload = json.dumps(
        semantic_source_payload(source),
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def registry_binding_digest(registry: dict[str, Any], source_ids: list[str]) -> str:
    sources = all_sources(registry)
    payload = [
        semantic_source_payload(sources[source_id])
        for source_id in sorted(set(source_ids))
        if source_id in sources
    ]
    raw = json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()


def evidence_level(source: dict[str, Any]) -> str:
    verification = source.get("verification")
    method = canonical(verification.get("method")) if isinstance(verification, dict) else ""
    if method in {"full-text", "pdf"}:
        return "full-text"
    if method == "detail":
        return "detail"
    if method == "abstract":
        return "abstract"
    return "unknown"


def final_sources(registry: dict[str, Any]) -> dict[str, dict[str, Any]]:
    records: dict[str, dict[str, Any]] = {}
    for item in registry.get("sources") or []:
        if not isinstance(item, dict):
            continue
        source_id = str(item.get("source_id") or "").strip()
        if source_id and canonical(item.get("citation_scope")) == "final-source":
            records[source_id] = item
    return records


def all_sources(registry: dict[str, Any]) -> dict[str, dict[str, Any]]:
    records: dict[str, dict[str, Any]] = {}
    for item in registry.get("sources") or []:
        if isinstance(item, dict) and str(item.get("source_id") or "").strip():
            records[str(item["source_id"]).strip()] = item
    return records


