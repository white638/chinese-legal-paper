def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()


def revision_working_manuscripts(base: Path, contract: dict[str, object]) -> list[Path]:
    """Locate revision manuscripts while keeping all mutable copies in the workspace."""
    try:
        config = workflow_config(base)
    except (OSError, ValueError):
        config = {}
    raw_candidates: list[Path] = []
    if isinstance(config, dict) and str(config.get("draft_path") or "").strip():
        raw_candidates.append(Path(str(config["draft_path"])))
    baseline = contract.get("baseline") if isinstance(contract.get("baseline"), dict) else {}
    if str(baseline.get("kind") or "").strip().lower() == "workspace" and str(
        baseline.get("path") or ""
    ).strip():
        raw_candidates.append(Path(str(baseline["path"])))
    raw_candidates.extend(
        [
            Path("working_manuscript.docx"),
            Path("working_manuscript.md"),
            Path("working_manuscript.tex"),
            Path("final_paper/main.tex"),
            Path("final_paper/manuscript.md"),
            Path("final_paper/paper.md"),
            Path("final_paper/paper.docx"),
            Path("final_paper/paper.zh.docx"),
        ]
    )
    resolved: list[Path] = []
    root = base.resolve()
    for candidate in raw_candidates:
        path = candidate if candidate.is_absolute() else base / candidate
        try:
            path = path.resolve()
            path.relative_to(root)
        except (OSError, ValueError):
            continue
        if path.is_file() and path.stat().st_size > 0 and path not in resolved:
            resolved.append(path)
    return resolved


def check_revision_build_artifacts(base: Path, contract: dict[str, object]) -> list[str]:
    """Use a proportional build gate for build-only surface/argument revisions."""
    issues: list[str] = []
    baseline = contract.get("baseline") if isinstance(contract.get("baseline"), dict) else {}
    baseline_digest = str(baseline.get("sha256") or "").strip().lower()
    manuscripts = revision_working_manuscripts(base, contract)
    if not manuscripts:
        return ["controlled revision has no non-empty working or final manuscript inside the workspace"]
    if baseline_digest and not any(_sha256(path) != baseline_digest for path in manuscripts):
        issues.append("controlled revision manuscript is unchanged from the hash-bound baseline")

    classes = revision_change_classes(contract)
    if "argument" in classes:
        if not any(
            is_meaningful_file(base / relative)
            for relative in ("rewrite_matrix.md", "dialogic_argument_map.md")
        ):
            issues.append(
                "argument revision requires a meaningful rewrite_matrix.md or dialogic_argument_map.md"
            )
    return issues


