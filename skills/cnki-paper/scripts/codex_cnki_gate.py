def check_contribution_calibration(base: Path) -> list[str]:
    """Require actual contribution calibration after execution and before prose construction."""
    text = read_text(base / "confirmed_contribution.md")
    section = markdown_section(
        text,
        {"Calibration Receipt", "Contribution Calibration", "贡献校准凭证", "贡献校准"},
    )
