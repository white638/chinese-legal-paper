def check_citation_bank(
    base: Path,
    target: int,
    recent_threshold: int,
    recent_ratio: float,
    min_content_verified: int | None = None,
) -> list[str]:
    text = read_text(base / "citation_support_bank.md")
    issues: list[str] = []
    config = workflow_config(base)
    try:
        registry = load_acquisition_json(acquisition_registry_path(base))
    except ValueError:
        registry = {}
    publication_track = resolve_publication_track(
        config if isinstance(config, dict) else {},
        registry if isinstance(registry, dict) else {},
    )
    if GENERATED_CITATION_MARKER not in text:
        issues.append(
            "citation_support_bank.md is not a generated registry view; migrate it and rerun "
            "cnki_acquisition.py sync --force"
        )
    v4_groups = {
        "candidate id": {"candidate id", "候选编号", "文献编号"},
        "reference/citation": {"reference", "citation", "文献", "著录"},
        "year": {"year", "年份"},
        "recency": {"recency", "新近性", "时效性"},
        "supports section": {"supports section", "section", "支撑章节", "适用章节"},
        "support sentence": {"support claim sentence", "support sentence", "支撑主张句", "支撑句", "可用句"},
        "why fits": {"why this paper fits", "why fits", "适配理由", "为何适用"},
        "source": {"source", "origin", "url", "来源", "链接"},
        "source channel": {"source channel", "来源渠道", "采集渠道"},
        "verified": {"verified", "已核验", "核验状态"},
        "citation scope": {"citation scope", "scope", "引用范围", "引用状态"},
        "verification note": {"verification note", "核验说明", "验证说明", "核验记录"},
    }
    legacy_groups = {
        "reference/citation": v4_groups["reference/citation"],
        "claim": {"claim", "主张", "支撑主张"},
        "support sentence": v4_groups["support sentence"],
        "source": v4_groups["source"],
        "verification status": {"status", "verified", "verification", "核验", "验证", "状态"},
    }
    local_checker = local_tool_script("citation_bank_check.py").exists()
    groups = v4_groups if local_checker else legacy_groups
    table = find_table(text, list(groups.values()))
    if table is None:
        if local_checker:
            return issues + [
                "citation_support_bank.md must use the local 12-column schema: Candidate ID, Reference/BibTeX, "
                "Year, Recency, Supports Section, Support Claim Sentence, Why This Paper Fits, Source, "
                "Source Channel, Verified, Citation Scope, and Verification Note"
            ]
        return issues + [
            "citation_support_bank.md must contain reference, claim, support sentence, source, and verification-status columns"
        ]
    headers, rows = table
    rows = [row for row in rows if any(not is_generic(cell) for cell in row)]
    indexes = {label: column_index(headers, names) for label, names in groups.items()}
    reference_index = indexes["reference/citation"]
    assert reference_index is not None
    year_index = indexes.get("year")
    recent = 0
    for row in rows:
        year_text = " ".join(
            value
            for value in (
                row[year_index] if year_index is not None and year_index < len(row) else "",
                row[reference_index] if reference_index < len(row) else "",
            )
            if value
        )
        years = [int(year) for year in re.findall(r"(?<!\d)(20\d{2})(?!\d)", year_text)]
        if any(year >= recent_threshold for year in years):
            recent += 1
    # Candidate-pool size and recency are coverage diagnostics, not universal hard
    # gates. The configured minimum number of content-verified final sources below
    # remains enforceable; historical, normative, or foundational work may
    # legitimately have a different candidate/recency profile.

    weak_rows: list[int] = []
    invalid_scope_rows: list[int] = []
    scope_index = indexes.get("citation scope")
    candidate_scopes = {"candidateonly", "candidate", "screened", "screening"}
    final_scopes = {"finalsource", "final", "selected", "cited"}
    for row_number, row in enumerate(rows, start=1):
        scope = normalize(row[scope_index]) if scope_index is not None and scope_index < len(row) else ""
        candidate_only = scope in candidate_scopes
        if scope not in candidate_scopes | final_scopes:
            invalid_scope_rows.append(row_number)
        weak = False
        for label, index in indexes.items():
            assert index is not None
            value = row[index] if index < len(row) else ""
            if candidate_only and label in {"support sentence", "why fits"}:
                continue
            if is_generic(value):
                weak = True
            if not candidate_only and label == "support sentence" and len(normalize(value)) < 20:
                weak = True
        if weak:
            weak_rows.append(row_number)
    if weak_rows:
        issues.append("citation bank has placeholder or weak claim-support rows: " + ", ".join(map(str, weak_rows[:10])))
    if invalid_scope_rows:
        issues.append(
            "citation bank rows must set Citation Scope to final-source or candidate-only: "
            + ", ".join(map(str, invalid_scope_rows[:10]))
        )

    if local_checker:
        candidate_index = indexes["candidate id"]
        source_index = indexes["source"]
        channel_index = indexes["source channel"]
        verified_index = indexes["verified"]
        scope_index = indexes["citation scope"]
        note_index = indexes["verification note"]
        assert None not in {
            candidate_index,
            source_index,
            channel_index,
            verified_index,
            scope_index,
            note_index,
        }
        registry_sources = registry.get("sources") if isinstance(registry, dict) else []
        registry_by_id = {
            str(source.get("source_id") or "").strip(): source
            for source in registry_sources
            if isinstance(source, dict) and str(source.get("source_id") or "").strip()
        } if isinstance(registry_sources, list) else {}
        bad_cnki_rows: list[int] = []
        verified_cnki_rows = 0
        verified_international_rows = 0
        cnki_rows = 0
        final_source_rows = 0
        invalid_verification_rows: list[int] = []
        for row_number, row in enumerate(rows, start=1):
            candidate_id = row[candidate_index].strip() if candidate_index < len(row) else ""
            source = row[source_index] if source_index < len(row) else ""
            channel = row[channel_index] if channel_index < len(row) else ""
            verified = row[verified_index] if verified_index < len(row) else ""
            scope = normalize(row[scope_index]) if scope_index < len(row) else ""
            note = row[note_index] if note_index < len(row) else ""
            is_verified = bool(re.search(r"\b(?:yes|true|verified)\b|已核验|已验证", verified, re.IGNORECASE))
            candidate_only = scope in candidate_scopes
            final_source = scope in final_scopes
            if final_source:
                final_source_rows += 1
                if not is_verified:
                    invalid_verification_rows.append(row_number)
            elif candidate_only and is_verified:
                invalid_verification_rows.append(row_number)
            if re.search(r"cnki|知网", " ".join((source, channel)), re.IGNORECASE):
                cnki_rows += 1
                has_channel = normalize(channel) == "cnki"
                stable_source = bool(re.search(r"https?://[^\s|]*cnki\.net", source, re.IGNORECASE))
                dated_note = bool(re.search(r"20\d{2}-\d{2}-\d{2}", note))
                traceable_note = bool(re.search(r"https?://|cnki|知网", note, re.IGNORECASE)) and bool(
                    re.search(r"abstract|detail|full[ -]?text|pdf|摘要|详情|全文|原文", note, re.IGNORECASE)
                )
                screening_note = bool(
                    re.search(r"screen|result|title|candidate|export|筛选|检索|题名|导出", note, re.IGNORECASE)
                )
                if not all((has_channel, stable_source, dated_note)):
                    bad_cnki_rows.append(row_number)
                elif final_source:
                    if is_verified and traceable_note:
                        verified_cnki_rows += 1
                    else:
                        bad_cnki_rows.append(row_number)
                elif candidate_only and (is_verified or not screening_note):
                    bad_cnki_rows.append(row_number)
            elif (
                final_source
                and is_verified
                and is_international_content_channel(channel)
                and (registered_source := registry_by_id.get(candidate_id)) is not None
                and is_international_content_channel(registered_source.get("channel"))
                and acquisition_content_verification_complete(registered_source)
            ):
                verified_international_rows += 1
        if invalid_verification_rows:
            issues.append(
                "final-source rows require Verified=yes; candidate-only screening rows require Verified=no: "
                + ", ".join(map(str, invalid_verification_rows[:10]))
            )
        if bad_cnki_rows:
            issues.append(
                "CNKI rows must set Source Channel=CNKI, retain a stable cnki.net Source URL, and record a dated "
                "Verification Note. final-source rows require an abstract/detail/full-text/PDF trace; candidate-only "
                "rows require an explicit screening/export note and cannot be marked Verified=yes: "
                + ", ".join(map(str, bad_cnki_rows[:10]))
            )
        # v5 uses this generated table for traceability only. The authoritative
        # numerical floor, deduplication, scholarly-source classification, and
        # coverage/saturation gates live in literature_analysis.json v2. An
        # explicit CLI minimum remains available for one-off diagnostics.
        if min_content_verified is not None and final_source_rows < min_content_verified:
            issues.append(
                f"citation bank has {final_source_rows} final-source rows; explicit diagnostic minimum is {min_content_verified}"
            )
    return issues


