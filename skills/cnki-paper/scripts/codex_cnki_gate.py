def _design_id_sets(base: Path) -> tuple[str, set[str], set[str]]:
    try:
        payload = json.loads(read_text(base / "research_design.json"))
    except json.JSONDecodeError:
        return "", set(), set()
    if not isinstance(payload, dict):
        return "", set(), set()
    design = payload.get("design") if isinstance(payload.get("design"), dict) else {}
    if not design and isinstance(payload.get("method_routes"), list):
        routes = [item for item in payload.get("method_routes") or [] if isinstance(item, dict)]
        design = next(
            (item for item in routes if str(item.get("role") or "").strip().lower() == "primary"),
            routes[0] if routes else {},
        )
    claims = {
        str(item.get("id") or "").strip()
        for item in payload.get("claims") or []
        if isinstance(item, dict)
        and str(item.get("status") or "").strip().lower() not in {"inactive", "superseded", "withdrawn"}
        and str(item.get("id") or "").strip()
    }
    evidence = {
        str(item.get("id") or "").strip()
        for item in payload.get("evidence") or []
        if isinstance(item, dict) and str(item.get("id") or "").strip()
    }
    return str(design.get("id") or "").strip(), claims, evidence


def _registered_tokens(value: str, known: set[str]) -> set[str]:
    return {
        identifier
        for identifier in known
        if re.search(
            rf"(?<![A-Za-z0-9_-]){re.escape(identifier)}(?![A-Za-z0-9_-])",
            value,
            re.IGNORECASE,
        )
    }


def check_execution_artifacts(base: Path, stage: str = "execution", *, write: bool = True) -> list[str]:
    """Validate the method-neutral evidence-and-inference execution ledger."""
    try:
        design_payload = json.loads(read_text(base / "research_design.json"))
    except json.JSONDecodeError:
        design_payload = {}
    if (
        isinstance(design_payload, dict)
        and design_payload.get("schema_version")
        in {"cnki-research-design/v3", "cnki-research-design/v4"}
    ):
        return check_method_execution(base, stage, write=write)
    text = read_text(base / "execution_record.md")
    required = {
        "execution": {"execution id", "执行编号", "分析编号"},
        "design": {"design id", "设计编号"},
        "claims": {"claim ids", "claim id", "主张编号"},
        "evidence": {"evidence ids", "evidence id", "证据编号"},
        "action": {"method action", "analysis action", "方法动作", "分析动作"},
        "result": {"result / inference", "result", "inference", "结果/推断", "结果与推断"},
        "negative": {
            "alternative / negative evidence",
            "alternative or negative evidence",
            "替代解释/负面证据",
            "替代解释与负面证据",
        },
        "status": {"status", "状态"},
    }
    table = find_table(text, list(required.values()))
    if table is None:
        return [
            "execution_record.md must contain Execution ID, Design ID, Claim IDs, Evidence IDs, "
            "Method Action, Result/Inference, Alternative/Negative Evidence, and Status"
        ]
    headers, rows = table
    indexes = {label: column_index(headers, names) for label, names in required.items()}
    usable = [row for row in rows if any(not is_generic(cell) for cell in row)]
    if not usable:
        return ["execution_record.md has no evidence-and-inference execution rows"]

    design_id, claim_ids, evidence_ids = _design_id_sets(base)
    issues: list[str] = []
    seen_execution: set[str] = set()
    covered_claims: set[str] = set()
    allowed_status = re.compile(
        r"^(?:supported|qualified|null|negative|not-supported|withdrawn|"
        r"支持|有限支持|受限|零结果|负面结果|不支持|撤回)$",
        re.IGNORECASE,
    )
    for number, row in enumerate(usable, start=1):
        values = {
            label: row[index] if index is not None and index < len(row) else ""
            for label, index in indexes.items()
        }
        empty = [label for label, value in values.items() if is_generic(value)]
        if empty:
            issues.append(f"execution row {number} has empty or generic fields: {', '.join(empty)}")
        execution_id = values["execution"].strip()
        if not re.fullmatch(r"EXE[-_]?\d{2,}", execution_id, re.IGNORECASE):
            issues.append(f"execution row {number} has invalid Execution ID {execution_id!r}")
        elif execution_id.lower() in seen_execution:
            issues.append(f"execution row {number} repeats Execution ID {execution_id}")
        seen_execution.add(execution_id.lower())
        if design_id and not re.search(
            rf"(?<![A-Za-z0-9_-]){re.escape(design_id)}(?![A-Za-z0-9_-])",
            values["design"],
            re.IGNORECASE,
        ):
            issues.append(f"execution row {number} does not resolve to active Design ID {design_id}")
        row_claims = _registered_tokens(values["claims"], claim_ids)
        row_evidence = _registered_tokens(values["evidence"], evidence_ids)
        if not row_claims:
            issues.append(f"execution row {number} has no registered Claim ID")
        if not row_evidence:
            issues.append(f"execution row {number} has no registered Evidence ID")
        covered_claims.update(row_claims)
        if not allowed_status.search(values["status"].strip()):
            issues.append(f"execution row {number} has unresolved or unsupported Status {values['status']!r}")
    missing_claims = sorted(claim_ids - covered_claims)
    if missing_claims:
        issues.append("execution_record.md does not evaluate active claims: " + ", ".join(missing_claims))
