def run_python_check(script: Path, arguments: list[str], label: str) -> list[str]:
    if not script.exists():
        return [f"required upstream checker is missing: {script}"]
    env = os.environ.copy()
    env.setdefault("PYTHONUTF8", "1")
    env.setdefault("PYTHONIOENCODING", "utf-8")
    result = subprocess.run(
        [sys.executable, str(script), *arguments],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        env=env,
        check=False,
    )
    if result.returncode == 0:
        return []
    detail = " ".join((result.stdout + "\n" + result.stderr).strip().split())[-500:]
    return [f"{label} failed live validation" + (f": {detail}" if detail else "")]


