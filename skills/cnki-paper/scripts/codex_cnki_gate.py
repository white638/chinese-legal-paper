def check_output(base: Path, outputs_dir: Path | None) -> list[str]:
    del outputs_dir  # Compatibility argument; workflow truth lives under final_paper/.
    config = workflow_config(base)
    final_paper = base / "final_paper"
    profile = task_profile_from_config(config) if isinstance(config, dict) else "full_paper"
    required = [base / "final_artifact_manifest.md"]
    word_requested = str(config.get("word_output") or "docx").strip().lower() != "none"
    if profile != "manuscript_revision":
        required.append(final_paper / "main.tex")
    output_language = str(config.get("output_language") or "").strip().lower()
    translation_zh = str(config.get("translation_package") or "none").strip().lower() == "zh"
    if word_requested:
        if output_language == "zh":
            required.extend([final_paper / "paper.zh.docx", base / "word_report.zh.md"])
        else:
            required.extend([final_paper / "paper.docx", base / "word_report.md"])
    if translation_zh:
        required.extend([final_paper / "paper.zh.docx", base / "word_report.zh.md"])
    def valid_artifact(path: Path) -> bool:
        if path.suffix.lower() in {".docx", ".pdf"}:
            return path.exists() and path.is_file() and path.stat().st_size > 0
        return is_meaningful_file(path)

    missing = [path.relative_to(base).as_posix() for path in dict.fromkeys(required) if not valid_artifact(path)]
    if profile == "manuscript_revision" and not word_requested and not any(
        valid_artifact(candidate)
        for candidate in (
            final_paper / "main.tex",
            final_paper / "manuscript.md",
            final_paper / "paper.md",
        )
    ):
        missing.append("final_paper/main.tex or final_paper/manuscript.md")
    return [] if not missing else ["missing or invalid configured final artifact: " + ", ".join(missing)]


