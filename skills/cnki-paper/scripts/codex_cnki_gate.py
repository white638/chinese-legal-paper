def check_literature_analysis(
    base: Path,
    stage: str,
    *,
    write: bool = True,
) -> list[str]:
    """Validate critical reading, claim permissions, and problem-led synthesis."""
    script = Path(__file__).with_name("literature_analysis.py")
    if not script.exists():
        return [f"required upstream checker is missing: {script}"]
    arguments = ["validate", str(base), "--stage", stage, "--json"]
    if write:
        arguments.append("--write")
    env = os.environ.copy()
    env.setdefault("PYTHONUTF8", "1")
    env.setdefault("PYTHONIOENCODING", "utf-8")
    process = subprocess.run(
        [sys.executable, str(script), *arguments],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        env=env,
        check=False,
    )
    if process.returncode == 0:
        return []
    try:
        payload = json.loads(process.stdout)
    except json.JSONDecodeError:
        detail = " ".join((process.stdout + "\n" + process.stderr).strip().split())[-500:]
        return [
            "CNKI-Paper literature-analysis contract failed live validation"
            + (f": {detail}" if detail else "")
        ]
    issues = payload.get("issues") if isinstance(payload, dict) else None
    if not isinstance(issues, list):
        return ["CNKI-Paper literature-analysis contract failed live validation"]
    rendered = []
    for issue in issues:
        if isinstance(issue, dict):
            rendered.append(
                f"{issue.get('code', 'LA.UNKNOWN')}: "
                f"{issue.get('message', 'literature-analysis validation failed')}"
            )
        elif issue:
            rendered.append(str(issue))
    return rendered or ["CNKI-Paper literature-analysis contract failed live validation"]


