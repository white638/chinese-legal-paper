@dataclass(frozen=True)
class Issue:
    code: str
    severity: str
    message: str
    path: str = ""

    def as_dict(self) -> dict[str, str]:
        return {
            "code": self.code,
            "severity": self.severity,
            "message": self.message,
            "path": self.path,
        }


@dataclass
class ValidationResult:
    issues: list[Issue] = field(default_factory=list)

    def add(self, code: str, message: str, path: str = "", severity: str = "ERROR") -> None:
        self.issues.append(Issue(code, severity, message, path))

    @property
    def errors(self) -> list[Issue]:
        return [item for item in self.issues if item.severity == "ERROR"]

    @property
    def status(self) -> str:
        return "FAIL" if self.errors else "PASS"


def _text(value: Any) -> str:
    return str(value or "").strip()


def _normalize(value: Any) -> str:
    return re.sub(r"[^a-z0-9\u4e00-\u9fff]+", "", _text(value).casefold())


def _substantive(value: Any, minimum: int = 4) -> bool:
    if isinstance(value, list):
        return bool(value) and all(_substantive(item, 1) for item in value)
    token = _normalize(value)
    return len(token) >= minimum and token not in {_normalize(item) for item in PLACEHOLDERS}


def canonical_digest(value: Any) -> str:
    encoded = json.dumps(
        value,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def _valid_timestamp(value: Any) -> bool:
    try:
        datetime.fromisoformat(_text(value).replace("Z", "+00:00"))
    except ValueError:
        return False
    return bool(_text(value))


def _valid_date(value: Any) -> bool:
    return bool(re.fullmatch(r"20\d{2}-\d{2}-\d{2}", _text(value)))


def _timestamp(value: Any) -> datetime | None:
    try:
        parsed = datetime.fromisoformat(_text(value).replace("Z", "+00:00"))
    except ValueError:
        return None
    if parsed.tzinfo is None:
        return parsed.replace(tzinfo=timezone.utc)
    return parsed.astimezone(timezone.utc)


def _utc_now_stamp() -> str:
    return (
        datetime.now(timezone.utc)
        .isoformat(timespec="seconds")
        .replace("+00:00", "Z")
    )


def _safe_relative_material(base: Path, value: Any) -> Path | None:
    raw = _text(value).replace("\\", "/")
    if not raw or raw.startswith("/") or re.match(r"^[A-Za-z]:", raw):
        return None
    root = base.resolve()
    candidate = (base / raw).resolve()
    try:
        candidate.relative_to(root)
    except ValueError:
        return None
    return candidate


def _direction_fit_issues(
    value: Any,
    *,
    path: str = "direction_fit",
    require_strong: bool = False,
) -> list[str]:
    issues: list[str] = []
    if not isinstance(value, Mapping):
        return [f"{path} must contain the four controlled direction-fit layers"]
    if set(value) != set(DIRECTION_FIT_LAYERS):
        issues.append(f"{path} must use the exact topic/problem/contribution/trajectory layers")
    for layer in DIRECTION_FIT_LAYERS:
        assessment = value.get(layer)
        layer_path = f"{path}.{layer}"
        if not isinstance(assessment, Mapping):
            issues.append(f"{layer_path} must be one assessment object")
            continue
        if set(assessment) != DIRECTION_FIT_LAYER_FIELDS:
            issues.append(f"{layer_path} must use exact verdict/basis/rationale fields")
        verdict = _text(assessment.get("verdict"))
        if verdict not in DIRECTION_FIT_VERDICTS:
            issues.append(f"{layer_path}.verdict is unsupported")
        elif verdict in {"weak", "uncertain"}:
            issues.append(f"{layer_path}.verdict cannot support a screened candidate")
        elif require_strong and verdict != "strong":
            issues.append(f"{layer_path}.verdict must be strong for material discovery")
        basis = assessment.get("basis")
        normalized_basis = (
            [_text(item) for item in basis if _text(item)]
            if isinstance(basis, list)
            else []
        )
        if (
            not normalized_basis
            or len(set(normalized_basis)) != len(normalized_basis)
            or not set(normalized_basis).issubset(DIRECTION_LAYER_BASIS[layer])
            or not set(normalized_basis).issubset(DIRECTION_CONTRACT_FIELD_SET)
        ):
            issues.append(
                f"{layer_path}.basis must cite unique direction-contract fields relevant to that layer"
            )
        if not _substantive(assessment.get("rationale"), 8):
            issues.append(f"{layer_path}.rationale is not substantive")
    return list(dict.fromkeys(issues))


