def screening_input_projection(
    packet: Mapping[str, Any],
    seed_seal: Mapping[str, Any],
    *,
    protocol_version: str = SCREENING_PROTOCOL_SCHEMA_VERSION,
) -> dict[str, Any]:
    return {
        "packet": deepcopy(dict(packet)),
        "seed_seal": {
            "packet_sha256": seed_seal.get("packet_sha256"),
            "sealed_at": seed_seal.get("sealed_at"),
            "seed_portfolio_sha256": seed_seal.get("seed_portfolio_sha256"),
            "seeds": deepcopy(seed_seal.get("seeds")),
        },
        "protocol": screening_protocol(packet, protocol_version=protocol_version),
    }


def screening_protocol(
    packet: Mapping[str, Any],
    *,
    protocol_version: str = SCREENING_PROTOCOL_SCHEMA_VERSION,
) -> dict[str, Any]:
    if protocol_version == SCREENING_PROTOCOL_SCHEMA_VERSION:
        direction_protocol = SCREENING_PROTOCOL
        material_protocol = MATERIAL_ORIGIN_SCREENING_PROTOCOL
    elif protocol_version == LEGACY_SCREENING_PROTOCOL_SCHEMA_VERSION:
        direction_protocol = LEGACY_SCREENING_PROTOCOL
        material_protocol = LEGACY_MATERIAL_ORIGIN_SCREENING_PROTOCOL
    else:
        raise ValueError("unsupported topic screening protocol version")
    return deepcopy(
        direction_protocol
        if _text(packet.get("origin_mode")) == "direction_first"
        else material_protocol
    )


def _screening_protocol_version(
    packet: Mapping[str, Any], protocol_sha256: Any
) -> str | None:
    for version in (
        SCREENING_PROTOCOL_SCHEMA_VERSION,
        LEGACY_SCREENING_PROTOCOL_SCHEMA_VERSION,
    ):
        if _text(protocol_sha256) == canonical_digest(
            screening_protocol(packet, protocol_version=version)
        ):
            return version
    return None


def screening_prompt(
    packet: Mapping[str, Any],
    seed_seal: Mapping[str, Any],
    *,
    protocol_version: str = SCREENING_PROTOCOL_SCHEMA_VERSION,
) -> str:
    bounded = json.dumps(
        screening_input_projection(
            packet, seed_seal, protocol_version=protocol_version
        ),
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    )
    focus_note = ""
    if protocol_version == SCREENING_PROTOCOL_SCHEMA_VERSION:
        focus_note = (
            "Make a non-compensatory judgment: first assess the support for the "
            "problem or important unknown, then the substantive judgment an answer "
            "could change, then the feasible evidence or reasoning that could "
            "support, revise, or withdraw it. Novelty, topical popularity, material "
            "convenience, and a memorable sentence cannot compensate for a failed "
            "load-bearing link; do not average scores or turn search absence into "
            "proof of originality. In each seed disposition rationale, give the "
            "decisive reason to retain, merge, or drop and preserve uncertainty "
            "instead of inventing missing support. In why_worth_deep_review, explain "
            "which consequential judgment remains open and why the next review "
            "could resolve it. In largest_uncertainty_or_failure_risk, identify "
            "the weakest load-bearing link and what finding or reasoning would "
            "require revision or withdrawal. A tractable but unresolved check can "
            "justify deeper review; do not treat it as completed verification. "
            "Preserve descriptive, historical, normative, and synthesis questions "
            "when their unknown or disagreement is consequential. Do not require "
            "a dramatic contradiction, a predetermined answer, or mutually "
            "exclusive mechanisms; compatible explanations may coexist. Merge "
            "seeds only when they address the same consequential question, retaining "
            "their distinct conditions and uncertainty in the existing fields.\n"
        )
    return (
        "Screen the sealed origin-bound seeds into substantive candidate cores. "
        "Account for every seed exactly once as retain, merge, or drop. Candidate "
        "cores and all four direction-fit layers must follow the bound protocol. "
        "Do not inspect any inputs outside the sealed seed portfolio. Return one strict JSON object.\n"
        + focus_note
        + f"Bound screening input: {bounded}"
    )


