class _AgentEmissionSemanticReviewCapability(_ControlledSemanticReviewCapability):
    def __init__(self, *, model_revision: str, request_dir: Path) -> None:
        self.model_revision = _text(model_revision)
        self.request_dir = Path(request_dir)
        super().__init__(self._emit, _token=_SEMANTIC_CAPABILITY_TOKEN)

    def _emit(self, bounded_input: Mapping[str, Any]) -> HostCapture:
        output_schema = bounded_input.get("output_schema")
        if not isinstance(output_schema, Mapping):
            raise ValueError("agent-declared semantic review lacks its controlled output schema")
        write_agent_capture_request(
            self.request_dir,
            step="semantic-review",
            prompt=_text(bounded_input.get("prompt")),
            output_schema=output_schema,
            model_revision=self.model_revision,
        )
        raise AgentResponsesPending(self.request_dir)


