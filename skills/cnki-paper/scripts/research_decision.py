def bind_command(path: Path, *, apply: bool) -> int:
    try:
        base, before = load_payload(path)
        declared_graph = before.get("selected_candidate_subgraph")
        live_graph, live_issues = selected_candidate_subgraph(base, before)
        if live_issues and _text(before.get("disposition")) != "withdrawn":
            raise ValueError("; ".join(live_issues))
        initialized = (
            isinstance(declared_graph, Mapping)
            and bool(declared_graph)
            and bool(_text(before.get("selected_candidate_subgraph_digest")))
        )
        if initialized and dict(declared_graph) != live_graph:
            raise ValueError(
                "bind refused: a non-empty selected-candidate subgraph differs from live semantics; "
                "do not erase staleness or reuse the old hard clearance. Use a controlled "
                "challenge/reopen and a new confirmation, or an explicit verified migration."
            )
        after = deepcopy(before)
        issues = bind_selected_candidate_subgraph(base, after)
        if issues:
            raise ValueError("; ".join(issues))
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(str(exc), file=sys.stderr)
        return 2
    output = _apply_mutation(base, before, after, "bind") if apply else _mutation_plan(base, before, after, "bind")
    output["status"] = "BOUND" if apply else "READY"
    print(json.dumps(output, ensure_ascii=False, indent=2))
    return 0


def migrate_command(path: Path, *, decision_file: Path, apply: bool) -> int:
    base, target = _resolve(path)
    try:
        prepared = json.loads(decision_file.read_text(encoding="utf-8-sig"))
        if not isinstance(prepared, dict):
            raise ValueError("prepared decision must be one JSON object")
        before = _read_json(target) if target.is_file() else {}
        issues = bind_selected_candidate_subgraph(base, prepared)
        if issues:
            raise ValueError("; ".join(issues))
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(str(exc), file=sys.stderr)
        return 2
    output = _apply_mutation(base, before, prepared, "migrate") if apply else _mutation_plan(base, before, prepared, "migrate")
    output["status"] = "MIGRATED" if apply else "READY"
    output["commitment_authority_rewritten"] = False
    print(json.dumps(output, ensure_ascii=False, indent=2))
    return 0


def _emit_receipt(receipt: Mapping[str, Any], output: Path | None) -> None:
    rendered = json.dumps(dict(receipt), ensure_ascii=False, indent=2) + "\n"
    if output is None:
        print(rendered, end="")
        return
    target = output.resolve()
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_suffix(target.suffix + ".tmp")
    temporary.write_text(rendered, encoding="utf-8")
    temporary.replace(target)
    print(f"Wrote {target}")


def screening_command(
    path: Path,
    *,
    model_revision: str,
    issued_at: str,
    timeout_seconds: int,
    output: Path | None,
    runner: str | None = None,
    request_dir: Path | None = None,
    responses_dir: Path | None = None,
) -> int:
    """Run the production seed-to-candidate screening adapter."""

    try:
        base, payload = load_payload(path)
        exploration = payload.get("exploration")
        if not isinstance(exploration, Mapping):
            raise ValueError("research decision lacks topic exploration")
        packet = exploration.get("topic_packet")
        seed_seal = exploration.get("seed_seal")
        if not isinstance(packet, Mapping) or not isinstance(seed_seal, Mapping):
            raise ValueError("topic exploration lacks a packet or seed seal")
        config_read = read_config(base)
        packet_issues = validate_topic_packet(
            packet,
            config_read.payload if isinstance(config_read.payload, Mapping) else None,
            for_generation=True,
        )
        if packet_issues:
            raise ValueError("topic packet is invalid: " + "; ".join(packet_issues))
        material_projection = declared_material_projection(packet, base)
        seal_issues = validate_seed_seal(
            packet,
            seed_seal,
            material_projection=material_projection,
        )
        if seal_issues:
            raise ValueError("seed seal is invalid: " + "; ".join(seal_issues))
        scheduler = TopicScreeningScheduler.from_runner(
            packet,
            seed_seal,
            runner=runner or default_host_runner(),
            model_revision=model_revision,
            workspace_root=base,
            timeout_seconds=timeout_seconds,
            request_dir=request_dir,
            responses_dir=responses_dir,
        )
        try:
            receipt = scheduler.run(issued_at=issued_at)
        except AgentResponsesPending as pending:
            print(str(pending))
            return 0
        _emit_receipt(receipt, output)
        return 0
    except (OSError, subprocess.SubprocessError, ValueError, json.JSONDecodeError) as exc:
        print(f"topic screening error: {exc}", file=sys.stderr)
        return 2


