class TopicScreeningScheduler:
    """Transform a verified seed seal into signed candidate cores."""

    def __init__(
        self,
        packet: Mapping[str, Any],
        seed_seal: Mapping[str, Any],
        *,
        capability: _ControlledScreeningCapability,
        key_store: TopicSchedulerKeyStore,
        material_projection: Sequence[Mapping[str, Any]],
        _token: object,
    ) -> None:
        if _token is not _SCREENING_SCHEDULER_TOKEN:
            raise ValueError("screening scheduler must be constructed by the orchestrator")
        packet_issues = validate_topic_packet(packet, for_generation=True)
        if packet_issues:
            raise ValueError("invalid topic packet: " + "; ".join(packet_issues))
        seal_issues = validate_seed_seal(
            packet,
            seed_seal,
            material_projection=material_projection,
        )
        if seal_issues:
            raise ValueError("invalid seed seal: " + "; ".join(seal_issues))
        self.packet = deepcopy(dict(packet))
        self.seed_seal = deepcopy(dict(seed_seal))
        self.material_projection = [dict(item) for item in material_projection]
        self._capability = capability
        self._key_store = key_store
        self.session_id = "TOPIC-SCHED-" + uuid.uuid4().hex
        self.key_id = "TOPIC-KEY-" + uuid.uuid4().hex
        self._signing_key = secrets.token_bytes(32)
        self._key_store.create_session(
            key_id=self.key_id,
            session_id=self.session_id,
            key=self._signing_key,
        )

    @classmethod
    def from_codex_exec(
        cls,
        packet: Mapping[str, Any],
        seed_seal: Mapping[str, Any],
        *,
        model_revision: str,
        key_store: TopicSchedulerKeyStore | None = None,
        workspace_root: Path | None = None,
        timeout_seconds: int = 180,
    ) -> "TopicScreeningScheduler":
        return cls(
            packet,
            seed_seal,
            capability=_CodexExecScreeningCapability(
                model_revision=model_revision,
                timeout_seconds=timeout_seconds,
            ),
            key_store=key_store
            or TopicSchedulerKeyStore(default_scheduler_key_store_path()),
            material_projection=declared_material_projection(packet, workspace_root),
            _token=_SCREENING_SCHEDULER_TOKEN,
        )

    @classmethod
    def from_claude_exec(
        cls,
        packet: Mapping[str, Any],
        seed_seal: Mapping[str, Any],
        *,
        model_revision: str,
        key_store: TopicSchedulerKeyStore | None = None,
        workspace_root: Path | None = None,
        timeout_seconds: int = 180,
    ) -> "TopicScreeningScheduler":
        return cls(
            packet,
            seed_seal,
            capability=_ClaudeExecScreeningCapability(
                model_revision=model_revision,
                timeout_seconds=timeout_seconds,
            ),
            key_store=key_store
            or TopicSchedulerKeyStore(default_scheduler_key_store_path()),
            material_projection=declared_material_projection(packet, workspace_root),
            _token=_SCREENING_SCHEDULER_TOKEN,
        )

    @classmethod
    def from_agent_declared(
        cls,
        packet: Mapping[str, Any],
        seed_seal: Mapping[str, Any],
        *,
        model_revision: str,
        request_dir: Path | None = None,
        responses_dir: Path | None = None,
        key_store: TopicSchedulerKeyStore | None = None,
        workspace_root: Path | None = None,
    ) -> "TopicScreeningScheduler":
        if bool(request_dir) == bool(responses_dir):
            raise ValueError(
                "agent-declared screening requires exactly one of request_dir or responses_dir"
            )
        capability: _ControlledScreeningCapability
        if request_dir is not None:
            capability = _AgentEmissionScreeningCapability(
                model_revision=model_revision,
                request_dir=request_dir,
            )
        else:
            capability = _AgentDeclaredScreeningCapability(
                model_revision=model_revision,
                responses_dir=responses_dir,
            )
        return cls(
            packet,
            seed_seal,
            capability=capability,
            key_store=key_store
            or TopicSchedulerKeyStore(default_scheduler_key_store_path()),
            material_projection=declared_material_projection(packet, workspace_root),
            _token=_SCREENING_SCHEDULER_TOKEN,
        )

    @classmethod
    def from_runner(
        cls,
        packet: Mapping[str, Any],
        seed_seal: Mapping[str, Any],
        *,
        runner: str,
        model_revision: str,
        key_store: TopicSchedulerKeyStore | None = None,
        workspace_root: Path | None = None,
        timeout_seconds: int = 180,
        request_dir: Path | None = None,
        responses_dir: Path | None = None,
    ) -> "TopicScreeningScheduler":
        normalized = ensure_runner_allowed(runner)
        if normalized == "agent-declared":
            return cls.from_agent_declared(
                packet,
                seed_seal,
                model_revision=model_revision,
                request_dir=request_dir,
                responses_dir=responses_dir,
                key_store=key_store,
                workspace_root=workspace_root,
            )
        if request_dir or responses_dir:
            raise ValueError("request/response directories require agent-declared")
        factory = cls.from_codex_exec if normalized == "codex-exec" else cls.from_claude_exec
        return factory(
            packet,
            seed_seal,
            model_revision=model_revision,
            key_store=key_store,
            workspace_root=workspace_root,
            timeout_seconds=timeout_seconds,
        )

    @classmethod
    def _for_test(
        cls,
        packet: Mapping[str, Any],
        seed_seal: Mapping[str, Any],
        *,
        test_capture: Any,
        key_store: TopicSchedulerKeyStore | None = None,
        workspace_root: Path | None = None,
        test_run_id: str = "test-screening-run",
        test_model_revision: str = "test-screening-model",
        test_context_id: str = "test-screening-context",
    ) -> "TopicScreeningScheduler":
        def capture(bounded_input: Mapping[str, Any]) -> HostCapture:
            raw_output = test_capture(bounded_input)
            if not isinstance(raw_output, (bytes, str)):
                raise ValueError("test screening capture must return raw bytes or text")
            return HostCapture(
                raw_output=(
                    raw_output.encode("utf-8")
                    if isinstance(raw_output, str)
                    else raw_output
                ),
                run_id=test_run_id,
                model_revision=test_model_revision,
                context_id=test_context_id,
            )

        return cls(
            packet,
            seed_seal,
            capability=_ControlledScreeningCapability(
                capture,
                _token=_SCREENING_CAPABILITY_TOKEN,
            ),
            key_store=key_store or TopicSchedulerKeyStore(),
            material_projection=declared_material_projection(packet, workspace_root),
            _token=_SCREENING_SCHEDULER_TOKEN,
        )

    def run(self, *, issued_at: str) -> dict[str, Any]:
        packet_issues = validate_topic_packet(self.packet, for_generation=True)
        if packet_issues:
            raise ValueError("invalid topic packet: " + "; ".join(packet_issues))
        input_projection = screening_input_projection(self.packet, self.seed_seal)
        prompt = screening_prompt(self.packet, self.seed_seal)
        seed_ids = [
            _text(item.get("seed_id"))
            for item in self.seed_seal.get("seeds") or []
            if isinstance(item, Mapping) and _text(item.get("seed_id"))
        ]
        bounded_input = {
            "packet": deepcopy(self.packet),
            "seed_seal": deepcopy(input_projection["seed_seal"]),
            "prompt": prompt,
            "protocol": screening_protocol(self.packet),
            "output_schema": screening_output_schema(
                seed_ids,
                _text(self.packet.get("origin_mode")),
            ),
        }
        capture = self._capability.capture(bounded_input)
        if not isinstance(capture, HostCapture):
            raise ValueError("screening capability returned no controlled HostCapture")
        try:
            output = json.loads(capture.raw_output.decode("utf-8-sig"))
        except (UnicodeDecodeError, json.JSONDecodeError) as exc:
            raise ValueError("screening output is not valid JSON") from exc
        output_issues = _screening_output_issues(
            output,
            seed_ids,
            _text(self.packet.get("origin_mode")),
        )
        if output_issues:
            raise ValueError("invalid screening output: " + "; ".join(output_issues))
        issued = _timestamp(issued_at)
        sealed = _timestamp(self.seed_seal.get("sealed_at"))
        if issued is None or sealed is None or issued <= sealed:
            raise ValueError("screening must be issued after direction-only seed sealing")
        generation_contexts = {
            _text(item.get("context_id"))
            for item in self.seed_seal.get("generation_receipts") or []
            if isinstance(item, Mapping)
        }
        if _text(capture.context_id) in generation_contexts:
            raise ValueError("screening must use a context distinct from generation")
        receipt_id = "TOPIC-RUN-" + uuid.uuid4().hex
        receipt: dict[str, Any] = {
            "schema_version": SCREENING_SCHEMA_VERSION,
            "issuer": SCREENING_ISSUER,
            "receipt_id": receipt_id,
            "scheduler_session_id": self.session_id,
            "scheduler_key_id": self.key_id,
            "issued_at": issued_at,
            "packet_sha256": _text(self.packet.get("packet_sha256")),
            "seed_seal_sha256": canonical_digest(self.seed_seal),
            "direction_contract_sha256": canonical_digest(
                self.packet.get("direction_contract")
            ),
            "input_sha256": canonical_digest(input_projection),
            "prompt_sha256": hashlib.sha256(prompt.encode("utf-8")).hexdigest(),
            "protocol_sha256": canonical_digest(screening_protocol(self.packet)),
            "run_id": _text(capture.run_id),
            "model_revision": _text(capture.model_revision),
            "context_id": _text(capture.context_id),
            "raw_output_sha256": hashlib.sha256(capture.raw_output).hexdigest(),
            "seed_dispositions": deepcopy(output["seed_dispositions"]),
            "candidate_cores": deepcopy(output["candidate_cores"]),
            "screening_output_digest": canonical_digest(output),
        }
        receipt["receipt_sha256"] = canonical_digest(
            screening_receipt_projection(receipt)
        )
        receipt["signature"] = hmac.new(
            self._signing_key,
            receipt["receipt_sha256"].encode("ascii"),
            hashlib.sha256,
        ).hexdigest()
        self._key_store.record_receipt(
            key_id=self.key_id,
            receipt_id=receipt_id,
            digest=receipt["receipt_sha256"],
        )
        self._key_store.consume_receipts(
            key_id=self.key_id,
            receipt_ids=[receipt_id],
        )
        return receipt


def validate_screening_receipt(
    packet: Mapping[str, Any],
    seed_seal: Mapping[str, Any],
    receipt: Any,
) -> tuple[list[str], dict[str, Mapping[str, Any]]]:
    issues: list[str] = []
    core_by_id: dict[str, Mapping[str, Any]] = {}
    if not isinstance(receipt, Mapping):
        return (["candidate portfolio requires one controlled screening receipt"], core_by_id)
    if set(receipt) != SCREENING_RECEIPT_FIELDS:
        issues.append("screening receipt must use the exact controlled receipt fields")
    if _text(receipt.get("schema_version")) != SCREENING_SCHEMA_VERSION:
        issues.append(f"screening schema_version must be {SCREENING_SCHEMA_VERSION}")
    if _text(receipt.get("issuer")) != SCREENING_ISSUER:
        issues.append("screening receipt issuer is invalid")
    for field, pattern in {
        "receipt_id": r"TOPIC-RUN-[a-f0-9]{32}",
        "scheduler_session_id": r"TOPIC-SCHED-[a-f0-9]{32}",
        "scheduler_key_id": r"TOPIC-KEY-[a-f0-9]{32}",
    }.items():
        if not re.fullmatch(pattern, _text(receipt.get(field))):
            issues.append(f"screening {field} is invalid")
    if _text(receipt.get("packet_sha256")) != _text(packet.get("packet_sha256")):
        issues.append("screening receipt is bound to a different topic packet")
    if _text(receipt.get("seed_seal_sha256")) != canonical_digest(seed_seal):
        issues.append("screening receipt is bound to a stale seed seal")
    if _text(receipt.get("direction_contract_sha256")) != canonical_digest(
        packet.get("direction_contract")
    ):
        issues.append("screening receipt direction contract is stale")
    protocol_version = _screening_protocol_version(packet, receipt.get("protocol_sha256"))
    if protocol_version is None:
        issues.append("screening protocol digest is stale")
        protocol_version = SCREENING_PROTOCOL_SCHEMA_VERSION
    input_projection = screening_input_projection(
        packet, seed_seal, protocol_version=protocol_version
    )
    prompt = screening_prompt(packet, seed_seal, protocol_version=protocol_version)
    if _text(receipt.get("input_sha256")) != canonical_digest(input_projection):
        issues.append("screening input digest is stale")
    if _text(receipt.get("prompt_sha256")) != hashlib.sha256(prompt.encode("utf-8")).hexdigest():
        issues.append("screening prompt digest is stale")
    if _text(receipt.get("protocol_sha256")) != canonical_digest(
        screening_protocol(packet, protocol_version=protocol_version)
    ):
        issues.append("screening protocol digest is stale")
    output = {
        "seed_dispositions": receipt.get("seed_dispositions"),
        "candidate_cores": receipt.get("candidate_cores"),
    }
    seed_ids = [
        _text(item.get("seed_id"))
        for item in seed_seal.get("seeds") or []
        if isinstance(item, Mapping) and _text(item.get("seed_id"))
    ]
    issues.extend(
        _screening_output_issues(
            output,
            seed_ids,
            _text(packet.get("origin_mode")),
        )
    )
    if isinstance(receipt.get("candidate_cores"), list):
        core_by_id = {
            _text(item.get("candidate_id")): item
            for item in receipt["candidate_cores"]
            if isinstance(item, Mapping) and _text(item.get("candidate_id"))
        }
    if _text(receipt.get("screening_output_digest")) != canonical_digest(output):
        issues.append("screening output digest is stale")
    if _text(receipt.get("receipt_sha256")) != canonical_digest(
        screening_receipt_projection(receipt)
    ):
        issues.append("screening receipt digest is stale")
    issued = _timestamp(receipt.get("issued_at"))
    sealed = _timestamp(seed_seal.get("sealed_at"))
    if issued is None or sealed is None or issued <= sealed:
        issues.append("screening must occur after direction-only seed sealing")
    generation_contexts = {
        _text(item.get("context_id"))
        for item in seed_seal.get("generation_receipts") or []
        if isinstance(item, Mapping)
    }
    if _text(receipt.get("context_id")) in generation_contexts:
        issues.append("screening must use a context distinct from generation")
    for field in ("run_id", "model_revision", "context_id"):
        if len(_text(receipt.get(field))) < 3:
            issues.append(f"screening {field} is missing")
    if not re.fullmatch(r"[a-f0-9]{64}", _text(receipt.get("raw_output_sha256"))):
        issues.append("screening raw output SHA-256 is invalid")
    key_id = _text(receipt.get("scheduler_key_id"))
    session_id = _text(receipt.get("scheduler_session_id"))
    key_store = resolve_scheduler_key_store(key_id)
    verification_key = (
        key_store.verification_key(key_id=key_id, session_id=session_id)
        if key_store is not None
        else None
    )
    if verification_key is None:
        issues.append("screening key is unavailable from the controlled key store")
    else:
        expected = hmac.new(
            verification_key,
            _text(receipt.get("receipt_sha256")).encode("ascii"),
            hashlib.sha256,
        ).hexdigest()
        if not hmac.compare_digest(_text(receipt.get("signature")), expected):
            issues.append("screening scheduler signature does not match")
    ledger_state = (
        key_store.receipt_state(
            key_id=key_id,
            receipt_id=_text(receipt.get("receipt_id")),
        )
        if key_store is not None
        else None
    )
    if ledger_state is None:
        issues.append("screening receipt is unknown to the controlled ledger")
    else:
        digest, consumed = ledger_state
        if digest != _text(receipt.get("receipt_sha256")):
            issues.append("screening receipt differs from the controlled ledger")
        if not consumed:
            issues.append("screening receipt was not finalized by its scheduler")
    return (list(dict.fromkeys(issues)), core_by_id)


def _material_discovery_input(
    packet: Mapping[str, Any],
    seed_seal: Mapping[str, Any],
    screening_receipt: Mapping[str, Any],
    workspace_root: Path,
    material_path: str,
) -> tuple[dict[str, Any], dict[str, str]]:
    resolved = _safe_relative_material(workspace_root, material_path)
    if resolved is None or not resolved.is_file():
        raise ValueError("material discovery path must resolve to one workspace file")
    raw = resolved.read_bytes()
    if len(raw) > 1_000_000:
        raise ValueError("material discovery file exceeds the one-megabyte bounded input limit")
    try:
        material_text = raw.decode("utf-8-sig")
    except UnicodeDecodeError as exc:
        raise ValueError("material discovery currently requires a UTF-8 text input") from exc
    relative = resolved.relative_to(workspace_root.resolve()).as_posix()
    material_ref = {
        "path": relative,
        "sha256": hashlib.sha256(raw).hexdigest(),
    }
    projection = {
        "direction_contract": deepcopy(packet.get("direction_contract")),
        "sealed_seeds": deepcopy(seed_seal.get("seeds")),
        "screened_candidate_cores": deepcopy(
            screening_receipt.get("candidate_cores")
        ),
        "material_ref": material_ref,
        "material_text": material_text,
        "protocol": deepcopy(MATERIAL_DISCOVERY_PROTOCOL),
    }
    return projection, material_ref


def material_discovery_prompt(projection: Mapping[str, Any]) -> str:
    return (
        "Determine whether the bound material exposes one genuine, previously unseen "
        "research anomaly relative to all sealed seeds and screened candidate cores. "
        "Return a candidate only when all four direction-fit layers are strong. Return "
        "one strict JSON object under the protocol.\nBound discovery input: "
        + json.dumps(
            dict(projection),
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
        )
    )


def material_discovery_output_schema() -> dict[str, Any]:
    core_schema = screening_output_schema(["SEED-00"])["properties"][
        "candidate_cores"
    ]["items"]
    core_schema = deepcopy(core_schema)
    core_schema["properties"]["seed_ids"] = {
        "type": "array",
        "maxItems": 0,
    }
    core_schema["properties"]["portfolio_bucket"] = {
        "const": "material-opportunity"
    }
    core_schema["properties"]["generation_lane"] = {
        "const": "material_discovery"
    }
    core_schema["properties"]["direction_fit"] = _direction_fit_schema(
        require_strong=True
    )
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "type": "object",
        "required": sorted(MATERIAL_DISCOVERY_OUTPUT_FIELDS),
        "properties": {
            "candidate_core": core_schema,
            "anomaly": {"type": "string", "minLength": 12},
            "previously_unseen": {"const": True},
            "comparison_rationale": {"type": "string", "minLength": 12},
        },
        "additionalProperties": False,
    }


def _material_discovery_output_issues(output: Any) -> list[str]:
    issues: list[str] = []
    if not isinstance(output, Mapping) or set(output) != MATERIAL_DISCOVERY_OUTPUT_FIELDS:
        return ["material discovery output must use the exact controlled fields"]
    core = output.get("candidate_core")
    if not isinstance(core, Mapping) or set(core) != SCREENED_CORE_FIELDS:
        issues.append("material discovery candidate_core must use exact screened-core fields")
        core = {}
    if not re.fullmatch(r"CAND-[0-9]{2,}", _text(core.get("candidate_id"))):
        issues.append("material discovery candidate_id is invalid")
    if core.get("seed_ids") != []:
        issues.append("previously unseen material discovery must not claim sealed-seed lineage")
    if _text(core.get("generation_lane")) != "material_discovery":
        issues.append("material discovery candidate must use generation_lane=material_discovery")
    if _text(core.get("portfolio_bucket")) != "material-opportunity":
        issues.append("material discovery candidate must remain in the material-opportunity bucket")
    for field in ("candidate_family", "research_question", *SCREENED_DECISION_SUMMARY_FIELDS):
        if not _substantive(core.get(field), 8 if field != "candidate_family" else 4):
            issues.append(f"material discovery {field} is not substantive")
    signature = core.get("semantic_signature")
    if (
        not isinstance(signature, Mapping)
        or set(signature) != set(SIGNATURE_DIMENSIONS)
        or any(not _substantive(signature.get(field), 4) for field in SIGNATURE_DIMENSIONS)
    ):
        issues.append("material discovery semantic_signature is incomplete")
    issues.extend(
        _direction_fit_issues(
            core.get("direction_fit"),
            path="candidate_core.direction_fit",
            require_strong=True,
        )
    )
    if not _substantive(output.get("anomaly"), 12):
        issues.append("material discovery anomaly is not substantive")
    if output.get("previously_unseen") is not True:
        issues.append("material discovery must be previously unseen relative to the seed portfolio")
    if not _substantive(output.get("comparison_rationale"), 12):
        issues.append("material discovery comparison rationale is not substantive")
    return list(dict.fromkeys(issues))


def material_discovery_receipt_projection(receipt: Mapping[str, Any]) -> dict[str, Any]:
    return {
        key: receipt.get(key)
        for key in sorted(
            MATERIAL_DISCOVERY_RECEIPT_FIELDS - {"receipt_sha256", "signature"}
        )
    }


_DISCOVERY_CAPABILITY_TOKEN = object()
