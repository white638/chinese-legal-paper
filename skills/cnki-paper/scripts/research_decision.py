class _ControlledMaterialDiscoveryCapability:
    def __init__(self, capture: Any, *, _token: object) -> None:
        if _token is not _DISCOVERY_CAPABILITY_TOKEN:
            raise ValueError("material discovery capability must be issued by the orchestrator")
        self._capture = capture

    def capture(self, bounded_input: Mapping[str, Any]) -> HostCapture:
        return self._capture(bounded_input)


class _CodexExecMaterialDiscoveryCapability(_ControlledMaterialDiscoveryCapability):
    def __init__(self, *, model_revision: str, timeout_seconds: int) -> None:
        self.model_revision = _text(model_revision)
        self.timeout_seconds = timeout_seconds
        super().__init__(self._capture_codex, _token=_DISCOVERY_CAPABILITY_TOKEN)

    def _capture_codex(self, bounded_input: Mapping[str, Any]) -> HostCapture:
        if set(bounded_input) != {"projection", "prompt", "protocol", "output_schema"}:
            raise ValueError("CodexExec material discovery received an unauthorized input scope")
        return run_codex_exec_isolated(
            prompt=_text(bounded_input.get("prompt")),
            output_schema=bounded_input["output_schema"],
            model_revision=self.model_revision,
            timeout_seconds=self.timeout_seconds,
        )


