"""Evidence-bound, optional knowledge-change records and their read-only view."""

from __future__ import annotations

import hashlib
import json
from copy import deepcopy
from pathlib import Path
from typing import Any, Mapping

from cnki_acquisition import content_verification_complete, safe_local_path


FACETS = (
    "research_question", "phenomenon_or_estimand", "unit_or_population",
    "existing_explanation", "mechanism_or_condition", "evidence_logic",
    "main_answer", "unresolved_responsibility",
)
RELEVANCE = {"direct": 0, "conditional": 1, "contextual": 2, "unknown": 3}
CONTRACT_VERSION = "cnki-knowledge-change/v1"
VIEW_VERSION = "cnki-novelty-delta-view/v1"
VIEW_REL = Path("novelty_delta_view.md")
VIEW_MARKER = "<!-- generated by research_decision.py novelty-delta; derived view only -->"
ASSUMPTION_FIELDS = (
    "dominant_assumption", "why_questionable_here", "alternative_account",
    "old_account_prediction", "alternative_prediction", "discriminating_evidence",
    "no_change_condition", "revision_condition", "affected_audience",
)


def _text(value: Any) -> str:
    return value.strip() if isinstance(value, str) else ""


def _digest(value: Any) -> str:
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                    separators=(",", ":")).encode("utf-8")).hexdigest()


def _mapping(value: Any) -> Mapping[str, Any]:
    return value if isinstance(value, Mapping) else {}


def _read(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {}
    value = json.loads(path.read_text(encoding="utf-8-sig"))
    if not isinstance(value, dict):
        raise ValueError(f"expected JSON object: {path.name}")
    return value


def _records(value: Mapping[str, Any], key: str, identity: str) -> dict[str, Mapping[str, Any]]:
    return {_text(row.get(identity)): row for row in value.get(key, [])
            if isinstance(row, Mapping) and _text(row.get(identity))}


def _current_question(candidate: Mapping[str, Any]) -> tuple[str | None, str | None]:
    active_id = _text(candidate.get("active_question_version_id"))
    versions = candidate.get("question_versions")
    for question in versions if isinstance(versions, list) else []:
        if isinstance(question, Mapping) and active_id and question.get("id") == active_id:
            return _text(question.get("text")) or None, f"question_versions[{active_id}].text"
    return _text(candidate.get("research_question")) or None, "research_question"


def _keys(value: Any, required: set[str], optional: set[str], path: str,
          issues: list[tuple[str, str, str]]) -> bool:
    if not isinstance(value, Mapping) or not required <= set(value) or set(value) - required - optional:
        issues.append(("RDEC.DELTA.SHAPE", "fields do not match the optional record contract", path))
        return False
    return True


def _facets(value: Any, path: str, issues: list[tuple[str, str, str]]) -> None:
    if _keys(value, set(FACETS), set(), path, issues):
        for key, item in value.items():
            if item is not None and not _text(item):
                issues.append(("RDEC.DELTA.FACET", "facet must be substantive text or null (unknown)", f"{path}.{key}"))


def _passage_issues(base: Path, passage: Any, source: Mapping[str, Any], path: str,
                    issues: list[tuple[str, str, str]]) -> None:
    required = {"path", "sha256", "start", "end", "exact_quote", "locator"}
    if not _keys(passage, required, set(), path, issues):
        return
    target = safe_local_path(base, passage.get("path"))
    registered = {safe_local_path(base, source.get("local_file")),
                  safe_local_path(base, _mapping(source.get("verification")).get("ocr_text_file"))}
    if target is None or target not in registered or not target.is_file():
        issues.append(("RDEC.DELTA.PASSAGE_SOURCE", "passage must resolve to a registered Source local_file or verification.ocr_text_file", path))
        return
    try:
        raw = target.read_bytes()
        text = raw.decode("utf-8-sig")
    except (OSError, UnicodeError):
        issues.append(("RDEC.DELTA.PASSAGE_READ", "passage requires a readable UTF-8 inspected text artifact", path))
        return
    if hashlib.sha256(raw).hexdigest() != passage.get("sha256"):
        issues.append(("RDEC.DELTA.PASSAGE_STALE", "inspected text artifact SHA-256 has changed", path))
    start, end, quote = passage.get("start"), passage.get("end"), passage.get("exact_quote")
    if (type(start) is not int or type(end) is not int or not 0 <= start < end <= len(text)
            or not isinstance(quote, str) or not quote.strip() or len(quote) > 2400
            or text[start:end] != quote):
        issues.append(("RDEC.DELTA.PASSAGE_EXACT", "exact_quote must match inspected character offsets and contain at most 2400 characters", path))
    if not _text(passage.get("locator")):
        issues.append(("RDEC.DELTA.PASSAGE_LOCATOR", "inspected passage requires its source locator", path))


def candidate_delta_issues(base: Path, candidate: Mapping[str, Any],
                           sources: Mapping[str, Mapping[str, Any]],
                           syntheses: Mapping[str, Mapping[str, Any]],
                           *, path: str = "candidate", finalist: bool = True
                           ) -> list[tuple[str, str, str]]:
    """Validate only additive records; absence preserves the legacy contract."""
    issues: list[tuple[str, str, str]] = []
    contract = candidate.get("knowledge_change_contract")
    if "knowledge_change_contract" in candidate:
        if _keys(contract, {"schema_version", "claim_level"}, set(), f"{path}.knowledge_change_contract", issues):
            if contract.get("schema_version") != CONTRACT_VERSION or _text(contract.get("claim_level")) not in {"incremental", "high"}:
                issues.append(("RDEC.DELTA.CONTRACT", "unsupported knowledge-change contract or claim level", path))
    challenge = candidate.get("assumption_challenge")
    if finalist and _mapping(contract).get("claim_level") == "high" and challenge is None:
        issues.append(("RDEC.ASSUMPTION.REQUIRED", "opted-in high-claim finalists require an assumption challenge", path))
    if "assumption_challenge" in candidate:
        challenge_path = f"{path}.assumption_challenge"
        if not finalist:
            issues.append(("RDEC.ASSUMPTION.SCOPE", "assumption challenge belongs only to finalist or selected candidates", challenge_path))
        fields = {"mode", "assumption_source_ids", "assumption_status", *ASSUMPTION_FIELDS}
        if _keys(challenge, fields, {"not_applicable_reason"}, challenge_path, issues):
            mode = _text(challenge.get("mode"))
            if mode not in {"problematization", "boundary-test", "not-applicable"}:
                issues.append(("RDEC.ASSUMPTION.MODE", "unsupported assumption challenge mode", challenge_path))
            if _text(challenge.get("assumption_status")) not in {"established", "contested", "unclear", "not-applicable"}:
                issues.append(("RDEC.ASSUMPTION.STATUS", "unsupported assumption status", challenge_path))
            source_ids = challenge.get("assumption_source_ids")
            if not isinstance(source_ids, list) or any(not _text(item) for item in source_ids) or len(set(map(str, source_ids))) != len(source_ids):
                issues.append(("RDEC.ASSUMPTION.SOURCES", "assumption_source_ids must be unique Source identities", challenge_path))
                source_ids = []
            if mode == "not-applicable":
                if len(_text(challenge.get("not_applicable_reason"))) < 8:
                    issues.append(("RDEC.ASSUMPTION.NA_REASON", "not-applicable requires a substantive bounded explanation", challenge_path))
            elif not source_ids:
                issues.append(("RDEC.ASSUMPTION.SOURCES", "a challenged assumption requires registered supporting sources", challenge_path))
            for identity in source_ids:
                if identity not in sources or not content_verification_complete(dict(sources[identity])):
                    issues.append(("RDEC.ASSUMPTION.SOURCE_UNVERIFIED", f"assumption source {identity} lacks complete content verification", challenge_path))
            for field in ASSUMPTION_FIELDS:
                value = challenge.get(field)
                if mode == "not-applicable" and value is None:
                    continue
                if len(_text(value)) < 8:
                    issues.append(("RDEC.ASSUMPTION.INCOMPLETE", f"substantive {field} is required", challenge_path))

    c1 = _mapping(candidate.get("c1_collision_evidence"))
    neighbors = c1.get("nearest_neighbors")
    if "nearest_neighbors" in c1:
        if not isinstance(neighbors, list):
            issues.append(("RDEC.DELTA.NEIGHBORS", "nearest_neighbors must be an array", path))
            neighbors = []
        elif len(neighbors) > 5:
            issues.append(("RDEC.DELTA.NEIGHBORS", "at most five collision neighbors may be recorded", f"{path}.c1_collision_evidence.nearest_neighbors"))
        seen: set[str] = set()
        for index, neighbor in enumerate(neighbors):
            row_path = f"{path}.c1_collision_evidence.nearest_neighbors[{index}]"
            fields = {"source_id", "collision_relevance", "relevance_rationale", "synthesis_ids", "facets", "refutation"}
            if not _keys(neighbor, fields, set(), row_path, issues):
                continue
            identity = _text(neighbor.get("source_id"))
            source = sources.get(identity, {})
            if not identity or identity in seen or identity not in c1.get("source_ids", []) or not source:
                issues.append(("RDEC.DELTA.SOURCE", "neighbor must be a unique registered C1 Source", row_path))
            seen.add(identity)
            if source and not content_verification_complete(dict(source)):
                issues.append(("RDEC.DELTA.SOURCE_UNVERIFIED", "neighbor Source lacks complete content verification", row_path))
            if _text(neighbor.get("collision_relevance")) not in RELEVANCE or len(_text(neighbor.get("relevance_rationale"))) < 8:
                issues.append(("RDEC.DELTA.RELEVANCE", "neighbor needs explicit collision relevance and substantive rationale", row_path))
            links = neighbor.get("synthesis_ids")
            if not isinstance(links, list) or not links or any(not isinstance(item, str) for item in links) or len(set(map(str, links))) != len(links):
                issues.append(("RDEC.DELTA.SYNTHESIS", "neighbor requires registered candidate-bound synthesis identities", row_path))
                links = []
            for synthesis_id in links:
                synthesis = syntheses.get(synthesis_id, {})
                raw_links = synthesis.get("source_links", synthesis.get("links", []))
                raw_links = raw_links if isinstance(raw_links, list) else []
                source_links = {_text(item.get("source_id")) for item in raw_links if isinstance(item, Mapping)}
                markers = [item for key in ("candidate_ids", "research_candidate_ids", "topic_option_ids")
                           for item in (synthesis.get(key) if isinstance(synthesis.get(key), list) else [])
                           if isinstance(item, str)]
                markers.extend(_text(synthesis.get(key)) for key in ("candidate_id", "topic_option_id") if _text(synthesis.get(key)))
                if (synthesis_id not in c1.get("synthesis_ids", []) or identity not in source_links
                        or not {candidate.get("id"), candidate.get("topic_option_id")}.intersection(markers)):
                    issues.append(("RDEC.DELTA.SYNTHESIS", "neighbor SYN must link this C1 candidate and source", row_path))
            _facets(neighbor.get("facets"), f"{row_path}.facets", issues)
            refutation = neighbor.get("refutation")
            if not _keys(refutation, {"status", "prior_claim", "candidate_claim", "rationale", "passage"}, set(), f"{row_path}.refutation", issues):
                continue
            status = _text(refutation.get("status"))
            if status not in {"can_refute", "cannot_refute", "unclear"}:
                issues.append(("RDEC.DELTA.REFUTATION_STATUS", "unsupported refutation status", row_path))
            strong = status in {"can_refute", "cannot_refute"}
            for field in ("prior_claim", "candidate_claim", "rationale"):
                value = refutation.get(field)
                if (value is not None or strong) and len(_text(value)) < 8:
                    issues.append(("RDEC.DELTA.REFUTATION_BASIS", f"strong refutation adjudication requires substantive {field}", row_path))
            passage = refutation.get("passage")
            has_facets = any(value is not None for value in _mapping(neighbor.get("facets")).values())
            if passage is not None or strong or has_facets:
                _passage_issues(base, passage, source, f"{row_path}.refutation.passage", issues)

    c2 = _mapping(candidate.get("c2_overlap_adjudication"))
    if "knowledge_delta" in c2:
        delta = c2.get("knowledge_delta")
        delta_path = f"{path}.c2_overlap_adjudication.knowledge_delta"
        if _keys(delta, {"current_facets", "delta_statement"}, set(), delta_path, issues):
            _facets(delta.get("current_facets"), f"{delta_path}.current_facets", issues)
            question, _ = _current_question(candidate)
            facet_question = _mapping(delta.get("current_facets")).get("research_question")
            if question and facet_question is not None and " ".join(_text(facet_question).split()) != " ".join(question.split()):
                issues.append(("RDEC.DELTA.QUESTION_DRIFT", "current research_question facet differs from the canonical candidate question", delta_path))
            statement = delta.get("delta_statement")
            if statement is not None and len(_text(statement)) < 8:
                issues.append(("RDEC.DELTA.STATEMENT", "single delta_statement must be substantive text or null", delta_path))
    return issues


def delta_dependency_projection(base: Path, candidate: Mapping[str, Any],
                                sources: Mapping[str, Mapping[str, Any]]) -> dict[str, Any] | None:
    """Bind new source and inspected-file dependencies inside the existing hash."""
    challenge = _mapping(candidate.get("assumption_challenge"))
    neighbors = _mapping(candidate.get("c1_collision_evidence")).get("nearest_neighbors")
    if not challenge and neighbors is None:
        return None
    source_ids = {_text(item) for item in challenge.get("assumption_source_ids", []) if _text(item)}
    files: dict[str, Any] = {}
    for neighbor in neighbors if isinstance(neighbors, list) else []:
        if not isinstance(neighbor, Mapping):
            continue
        source_ids.add(_text(neighbor.get("source_id")))
        passage = _mapping(_mapping(neighbor.get("refutation")).get("passage"))
        raw_path = _text(passage.get("path"))
        if raw_path:
            target = safe_local_path(base, raw_path)
            try:
                files[raw_path] = hashlib.sha256(target.read_bytes()).hexdigest() if target else None
            except OSError:
                files[raw_path] = None
    return {"source_records": {identity: _digest(sources[identity]) if identity in sources else None
                               for identity in sorted(source_ids)},
            "inspected_files": dict(sorted(files.items()))}


def build_novelty_delta_view(base: Path, payload: Mapping[str, Any], candidate_id: str | None = None,
                             limit: int = 5) -> dict[str, Any]:
    if type(limit) is not int or not 3 <= limit <= 5:
        raise ValueError("neighbor display limit must be between 3 and 5; fewer available matches remain fewer")
    candidate_id = candidate_id or _text(payload.get("selected_candidate_id"))
    candidate = next((row for row in payload.get("candidates", [])
                      if isinstance(row, Mapping) and row.get("id") == candidate_id), None)
    if candidate is None:
        raise ValueError("select an existing candidate with --candidate-id or selected_candidate_id")
    registry = _read(base / "reference_materials" / "literature_registry.json")
    analysis = _read(base / "literature_analysis.json")
    sources = _records(registry, "sources", "source_id")
    syntheses = _records(analysis, "syntheses", "synthesis_id")
    maturity = candidate.get("maturity")
    finalist = maturity in {"finalist", "selected"} or maturity is None and bool(candidate.get("question_versions"))
    issues = candidate_delta_issues(base, candidate, sources, syntheses, finalist=finalist)
    c1 = _mapping(candidate.get("c1_collision_evidence"))
    c2 = _mapping(candidate.get("c2_overlap_adjudication"))
    delta = _mapping(c2.get("knowledge_delta"))
    current_facets = {key: _mapping(delta.get("current_facets")).get(key) for key in FACETS}
    current_origins = {key: "c2_overlap_adjudication.knowledge_delta.current_facets." + key
                       if current_facets[key] is not None else None for key in FACETS}
    signature = _mapping(candidate.get("semantic_signature"))
    for facet, field in (("phenomenon_or_estimand", "phenomenon"), ("unit_or_population", "unit_of_analysis"), ("evidence_logic", "evidence_logic")):
        if current_facets[facet] is None and _text(signature.get(field)):
            current_facets[facet] = signature[field]
            current_origins[facet] = f"semantic_signature.{field}"
    if current_facets["unresolved_responsibility"] is None and _text(c2.get("unresolved_claim")):
        current_facets["unresolved_responsibility"] = c2["unresolved_claim"]
        current_origins["unresolved_responsibility"] = "c2_overlap_adjudication.unresolved_claim"
    question, origin = _current_question(candidate)
    if question:
        current_facets["research_question"] = question
        current_origins["research_question"] = origin
    raw_rows = c1.get("nearest_neighbors", [])
    raw_rows = raw_rows if isinstance(raw_rows, list) else []
    rows = []
    for index, raw in enumerate(raw_rows):
        row = _mapping(raw)
        row_path = f"candidate.c1_collision_evidence.nearest_neighbors[{index}]"
        problems = [f"{code}: {message}" for code, message, issue_path in issues
                    if issue_path.startswith(row_path)]
        refutation = _mapping(row.get("refutation"))
        declared_status = _text(refutation.get("status")) or "unknown"
        effective_status = declared_status if not problems and declared_status in {"can_refute", "cannot_refute", "unclear"} else "unclear"
        rows.append({"source_id": _text(row.get("source_id")) or f"unknown-{index + 1}",
                     "collision_relevance": _text(row.get("collision_relevance")) if _text(row.get("collision_relevance")) in RELEVANCE else "unknown",
                     "relevance_rationale": row.get("relevance_rationale"),
                     "synthesis_ids": [item for item in row.get("synthesis_ids", []) if isinstance(item, str)] if isinstance(row.get("synthesis_ids"), list) else [],
                     "facets": {key: _mapping(row.get("facets")).get(key) if not problems else None for key in FACETS},
                     "refutation": {"status": effective_status, "declared_status": declared_status,
                                    "prior_claim": refutation.get("prior_claim"), "candidate_claim": refutation.get("candidate_claim"),
                                    "rationale": refutation.get("rationale"), "passage": refutation.get("passage"),
                                    "evidence_problem": problems}})
    declared_ids = {row["source_id"] for row in rows}
    strongest = _text(c1.get("strongest_collision_source_id"))
    # The strongest C1 identity is a legacy priority, not an inferred facet or verdict.
    for identity in c1.get("source_ids", []):
        if identity not in declared_ids:
            rows.append({"source_id": identity, "collision_relevance": "unknown",
                         "relevance_rationale": None, "synthesis_ids": [], "facets": {key: None for key in FACETS},
                         "refutation": {"status": "unclear", "declared_status": "unknown", "prior_claim": None, "candidate_claim": None,
                                        "rationale": None, "passage": None, "evidence_problem": ["No recorded neighbor comparison"]}})
    rows.sort(key=lambda row: (RELEVANCE[row["collision_relevance"]], row["source_id"] != strongest, row["source_id"]))
    view_rows = []
    for row in rows[:limit]:
        source = sources.get(row["source_id"], {})
        item = deepcopy(row)
        item["source_title"] = _text(source.get("title")) or None
        item["source_content_verified"] = content_verification_complete(dict(source))
        passage = _mapping(item["refutation"].get("passage"))
        item["refutation"]["passage"] = {"locator": passage.get("locator"), "sha256": passage.get("sha256")} if passage else None
        view_rows.append(item)
    return {"schema_version": VIEW_VERSION, "authority": "derived-only", "candidate_id": candidate_id,
            "input_digest": _digest({"candidate": candidate, "c1_sources": {key: sources.get(key) for key in c1.get("source_ids", [])},
                                     "c1_syntheses": {key: syntheses.get(key) for key in c1.get("synthesis_ids", [])},
                                     "dependencies": delta_dependency_projection(base, candidate, sources)}),
            "current_facets": current_facets, "current_facet_origins": current_origins,
            "neighbors": view_rows, "omitted_neighbor_count": max(0, len(rows) - limit),
            "delta_statement": delta.get("delta_statement"), "assumption_challenge": deepcopy(candidate.get("assumption_challenge")),
            "validation_issues": [{"code": code, "message": message, "path": path} for code, message, path in issues],
            "c2_overlap_vector": deepcopy(c2.get("overlap_vector"))}


def render_novelty_delta_view(view: Mapping[str, Any]) -> str:
    def md(value: Any) -> str:
        if value is None or value == "":
            return "unknown"
        return str(value).replace("|", "\\|").replace("\r", " ").replace("\n", " ")

    rows = view["neighbors"]
    lines = [VIEW_MARKER, "# Novelty delta view", "",
             f"Candidate: `{md(view['candidate_id'])}`. Authority: derived-only.",
             f"Input digest: `{view['input_digest']}`.", "",
             "Canonical records: research_decision.json, registered Source records, SYN records, and C2 adjudication.",
             "Unrecorded facets remain unknown; collision relevance is recorded judgment, not a novelty score.", "",
             "A cannot_refute judgment does not establish novelty or close the remaining C1–C3 responsibilities.", "",
             "| Facet | Current candidate | " + " | ".join(md(row["source_id"]) for row in rows) + (" |" if rows else ""),
             "|---|---|" + "---|" * len(rows)]
    for facet in FACETS:
        lines.append("| " + " | ".join([facet, md(view["current_facets"][facet]),
                                         *(md(row["facets"][facet]) for row in rows)]) + " |")
    lines.extend(["", "## Collision evidence", ""])
    for row in rows:
        refutation = row["refutation"]
        passage = _mapping(refutation.get("passage"))
        lines.extend([f"### {md(row['source_id'])}: {md(row['source_title'])}", "",
                      f"- Collision relevance: {md(row['collision_relevance'])}. {md(row['relevance_rationale'])}",
                      f"- Content verification: {'verified' if row['source_content_verified'] else 'unknown'}.",
                      f"- SYN: {', '.join(row['synthesis_ids']) or 'unknown'}.",
                      f"- Declared refutation: {md(refutation['declared_status'])}. Effective refutation: {md(refutation['status'])}.",
                      f"- Evidence problem: {'; '.join(refutation['evidence_problem']) or 'none detected'}.",
                      f"- Prior claim: {md(refutation['prior_claim'])}",
                      f"- Candidate claim: {md(refutation['candidate_claim'])}",
                      f"- Rationale: {md(refutation['rationale'])}",
                      f"- Inspected locator: {md(passage.get('locator'))}", ""])
    if not rows:
        lines.extend(["No registered collision neighbors; unknown.", ""])
    if view["omitted_neighbor_count"]:
        lines.extend([f"Additional registered neighbors outside display limit: {view['omitted_neighbor_count']}.", ""])
    if view["validation_issues"]:
        lines.extend(["## Record validation", ""])
        lines.extend(f"- {md(item['code'])}: {md(item['path'])}: {md(item['message'])}" for item in view["validation_issues"])
        lines.append("")
    lines.extend(["## Single delta statement", "", md(view["delta_statement"]), ""])
    challenge = view.get("assumption_challenge")
    lines.extend(["## Assumption challenge", ""])
    if isinstance(challenge, Mapping):
        lines.extend(f"- {key}: {md(', '.join(value) if isinstance(value, list) else value)}" for key, value in challenge.items())
    else:
        lines.append("unknown")
    return "\n".join(lines) + "\n"
