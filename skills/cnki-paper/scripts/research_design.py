def migrate_contract(path: Path, *, apply: bool, to: str = "v2") -> tuple[int, str]:
    if to == "v4":
        return _migrate_contract_to_v4(path, apply=apply)
    if to == "v3":
        return _migrate_contract_to_v3(path, apply=apply)
    if to != "v2":
        return 2, "Supported migration targets are v2, v3, and v4.\n"
    base, contract_path = resolve_contract_path(path)
    existing: Mapping[str, Any] | None = None
    if contract_path.exists():
        try:
            existing = _load_json(contract_path)
        except ContractError as exc:
            return 2, f"{exc}\n"
        schema = _text(existing.get("schema_version"))
        if schema == SCHEMA_VERSION_V2:
            return 0, f"Migration is already complete; current contract exists: {contract_path}\n"
        if schema != SCHEMA_VERSION_V1:
            qualifier = "future " if schema.startswith("cnki-research-design/v") else ""
            return 2, (
                f"Refusing migration because an unsupported or {qualifier}contract already exists "
                f"({schema or 'missing schema'}): {contract_path}\n"
            )

    matrix_path = base / VIEW_RELS[0]
    matrix_text = ""
    source_kind = "v1-contract" if existing is not None else "legacy-matrix"
    if existing is not None:
        source_text = json.dumps(existing, ensure_ascii=False, indent=2) + "\n"
        digest = hashlib.sha256(source_text.encode("utf-8")).hexdigest()
        backup_rel = MIGRATION_V31_REL / f"research_design.{digest[:12]}.v1.json"
        payload = _v2_module().migrate_v1_payload(existing)
    else:
        matrix_text = matrix_path.read_text(encoding="utf-8-sig") if matrix_path.exists() else ""
        legacy_v1 = migrate_payload(matrix_text)
        payload = _v2_module().migrate_v1_payload(legacy_v1)
        digest = hashlib.sha256(matrix_text.encode("utf-8")).hexdigest()
        # Preserve the v3.0 recovery location for v2-era hand-maintained matrices.
        backup_rel = MIGRATION_REL / f"knowledge_design_matrix.{digest[:12]}.v2.md"
    preview = {
        "mode": "apply" if apply else "dry-run",
        "source_kind": source_kind,
        "contract": str(contract_path),
        "legacy_matrix": str(matrix_path) if existing is None and matrix_path.exists() else None,
        "backup": str(base / backup_rel),
        "schema_version": SCHEMA_VERSION_V2,
        "status": "needs-review",
        "payload": payload,
    }
    if not apply:
        return 0, json.dumps(preview, ensure_ascii=False, indent=2) + "\n"

    if existing is not None:
        backup_path = base / backup_rel
        if not backup_path.exists():
            _atomic_write_text(backup_path, source_text)
    elif matrix_path.exists():
        backup_path = base / backup_rel
        if not backup_path.exists():
            _atomic_write_text(backup_path, matrix_text)
    _atomic_write_json(contract_path, payload)
    render_views(base, payload, allow_unmanaged_replace=True)
    return 0, (
        f"Migrated {source_kind} to {SCHEMA_VERSION_V2} at {contract_path}\n"
        f"Status remains needs-review; validate and confirm every unresolved field before execution.\n"
    )


def validate_command(
    path: Path,
    *,
    write: bool,
    json_stdout: bool,
    stage: str = "design",
) -> int:
    base, payload, result = validate_contract(path, stage=stage)
    design_schema = _text(payload.get("schema_version")) if payload is not None else ""
    unsafe_schema = bool(
        payload is not None
        and design_schema
        not in {SCHEMA_VERSION_V1, SCHEMA_VERSION_V2, SCHEMA_VERSION_V3, SCHEMA_VERSION_V4}
    )
    if write and payload is not None and not unsafe_schema:
        try:
            render_views(base, payload)
        except ContractError as exc:
            result.add("RD.VIEW.UNMANAGED", "ERROR", str(exc), "")
    report_json = validation_payload(result, design_schema)
    report_md = validation_markdown(result, design_schema)
    if write and not unsafe_schema:
        _atomic_write_json(base / CHECK_JSON_REL, report_json)
        _atomic_write_text(base / CHECK_MD_REL, report_md)
    if json_stdout:
        print(json.dumps(report_json, ensure_ascii=False, indent=2))
    else:
        print(report_md, end="")
    return 1 if result.errors else 0


def render_command(path: Path) -> int:
    base, contract_path = resolve_contract_path(path)
    try:
        payload = _load_json(contract_path)
        schema = _text(payload.get("schema_version"))
        if schema not in {
            SCHEMA_VERSION_V1,
            SCHEMA_VERSION_V2,
            SCHEMA_VERSION_V3,
            SCHEMA_VERSION_V4,
        }:
            raise ContractError(
                f"Cannot render schema {schema!r}; supported readers are "
                f"{SCHEMA_VERSION_V1}, {SCHEMA_VERSION_V2}, {SCHEMA_VERSION_V3}, "
                f"and {SCHEMA_VERSION_V4}"
            )
        written = render_views(base, payload)
    except ContractError as exc:
        print(exc, file=sys.stderr)
        return 2
    for output in written:
        print(f"Rendered generated view: {output}")
    return 0


def schema_command(version: str = "v1") -> int:
    versions = {
        "v1": (SCHEMA_ASSET_PATH_V1, SCHEMA_VERSION_V1),
        "v2": (SCHEMA_ASSET_PATH_V2, SCHEMA_VERSION_V2),
        "v3": (SCHEMA_ASSET_PATH_V3, SCHEMA_VERSION_V3),
        "v4": (SCHEMA_ASSET_PATH_V4, SCHEMA_VERSION_V4),
    }
    if version not in versions:
        print(f"Unsupported schema version: {version}", file=sys.stderr)
        return 2
    schema_path, expected = versions[version]
    try:
        schema = _load_json(schema_path)
    except ContractError as exc:
        print(exc, file=sys.stderr)
        return 2
    if _text(_at(schema, "properties.schema_version.const")) != expected:
        print("Schema asset version does not match the validator", file=sys.stderr)
        return 2
    print(json.dumps(schema, ensure_ascii=False, indent=2))
    return 0


def template_command(family: str, output: Path | None = None) -> int:
    try:
        payload = _v4_module().template_payload(family, _v2_module(), _v3_module())
    except (ContractError, OSError, ValueError) as exc:
        print(exc, file=sys.stderr)
        return 2
    content = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
    if output is None:
        print(content, end="")
        return 0
    target = output / DESIGN_REL if output.exists() and output.is_dir() else output
    if target.exists():
        print(f"Refusing to overwrite existing template target: {target}", file=sys.stderr)
        return 2
    try:
        _atomic_write_text(target, content)
    except OSError as exc:
        print(f"Could not write template: {exc}", file=sys.stderr)
        return 2
    print(f"Wrote {SCHEMA_VERSION_V4} template: {target}")
    return 0


