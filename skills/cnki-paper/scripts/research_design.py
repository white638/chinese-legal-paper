@dataclass(frozen=True)
class Issue:
    code: str
    severity: str
    message: str
    path: str = ""


@dataclass
class ValidationResult:
    issues: list[Issue] = field(default_factory=list)

    def add(self, code: str, severity: str, message: str, path: str = "") -> None:
        issue = Issue(code=code, severity=severity, message=message, path=path)
        if issue not in self.issues:
            self.issues.append(issue)

    @property
    def errors(self) -> list[Issue]:
        return [issue for issue in self.issues if issue.severity == "ERROR"]

    @property
    def status(self) -> str:
        return "FAIL" if self.errors else "PASS"


class ContractError(ValueError):
    """Raised for a malformed contract or unsafe view operation."""


def canonical_stage(value: str) -> str:
    return LEGACY_STAGE_ALIASES.get(value, value)


def _is_mapping(value: Any) -> bool:
    return isinstance(value, Mapping)


def _is_sequence(value: Any) -> bool:
    return isinstance(value, Sequence) and not isinstance(value, (str, bytes, bytearray))


def _text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value.strip()
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, Mapping):
        return "; ".join(f"{key}={_text(item)}" for key, item in value.items() if _text(item))
    if _is_sequence(value):
        return "; ".join(_text(item) for item in value if _text(item))
    return str(value).strip()


def _substantive(value: Any) -> bool:
    text = _text(value)
    return bool(text and text not in {"-", "--", "n/a", "N/A", "none", "null"})


def _contains_review(value: Any) -> bool:
    return bool(NEEDS_REVIEW.search(_text(value)))


def _at(payload: Mapping[str, Any], dotted: str, default: Any = None) -> Any:
    current: Any = payload
    for part in dotted.split("."):
        if not isinstance(current, Mapping) or part not in current:
            return default
        current = current[part]
    return current


def _require_text(
    result: ValidationResult,
    payload: Mapping[str, Any],
    dotted: str,
    *,
    code: str = "RD.FIELD.MISSING",
    severity: str = "ERROR",
) -> str:
    value = _at(payload, dotted)
    if not _substantive(value):
        result.add(code, severity, f"Required field is missing or empty: {dotted}", dotted)
        return ""
    if _contains_review(value):
        result.add("RD.REVIEW.FIELD", "REVIEW", f"Field still requires explicit evidence-backed review: {dotted}", dotted)
    return _text(value)


def _require_member(
    result: ValidationResult,
    payload: Mapping[str, Any],
    dotted: str,
    allowed: set[str],
) -> str:
    value = _require_text(result, payload, dotted)
    if value and value not in allowed:
        if _contains_review(value):
            return value
        result.add(
            "RD.TYPE.UNSUPPORTED",
            "ERROR",
            f"Unsupported value {value!r}; expected one of: {', '.join(sorted(allowed))}",
            dotted,
        )
    return value


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _safe_workspace_path(base: Path, raw: Any) -> Path | None:
    text = _text(raw)
    if not text:
        return None
    candidate = Path(text)
    if candidate.is_absolute():
        return None
    resolved_base = base.resolve()
    resolved = (resolved_base / candidate).resolve()
    try:
        resolved.relative_to(resolved_base)
    except ValueError:
        return None
    return resolved


def _atomic_write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            delete=False,
            dir=path.parent,
            prefix=f".{path.name}.",
            suffix=".tmp",
        ) as handle:
            handle.write(content)
            temporary = Path(handle.name)
        os.replace(temporary, path)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()


def _atomic_write_json(path: Path, payload: Mapping[str, Any]) -> None:
    _atomic_write_text(path, json.dumps(payload, ensure_ascii=False, indent=2) + "\n")


def _load_json(path: Path) -> Mapping[str, Any]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8-sig"))
    except FileNotFoundError as exc:
        raise ContractError(f"Missing JSON file: {path}") from exc
    except (OSError, json.JSONDecodeError) as exc:
        raise ContractError(f"Cannot parse JSON file {path}: {exc}") from exc
    if not isinstance(payload, Mapping):
        raise ContractError(f"JSON root must be one object: {path}")
    return payload


def resolve_contract_path(path: Path) -> tuple[Path, Path]:
    resolved = path.resolve()
    if resolved.suffix.lower() == ".json":
        return resolved.parent, resolved
    return resolved, resolved / DESIGN_REL


def _registry_sources(base: Path, result: ValidationResult) -> dict[str, Mapping[str, Any]]:
    registry_path = base / REGISTRY_REL
    if not registry_path.exists():
        result.add(
            "RD.REGISTRY.MISSING",
            "ERROR",
            f"Literature registry is missing: {REGISTRY_REL.as_posix()}",
            REGISTRY_REL.as_posix(),
        )
        return {}
    try:
        registry = _load_json(registry_path)
    except ContractError as exc:
        result.add("RD.REGISTRY.INVALID", "ERROR", str(exc), REGISTRY_REL.as_posix())
        return {}
    sources = registry.get("sources")
    if not isinstance(sources, list):
        result.add(
            "RD.REGISTRY.INVALID",
            "ERROR",
            "literature_registry.json must contain a sources array",
            f"{REGISTRY_REL.as_posix()}.sources",
        )
        return {}
    known: dict[str, Mapping[str, Any]] = {}
    for index, source in enumerate(sources):
        if not isinstance(source, Mapping) or not _substantive(source.get("source_id")):
            result.add(
                "RD.REGISTRY.INVALID",
                "ERROR",
                "Every registry source must contain source_id",
                f"{REGISTRY_REL.as_posix()}.sources[{index}]",
            )
            continue
        known[_text(source["source_id"])] = source
    return known


def _walk(value: Any, path: str = "") -> Iterable[tuple[str, Any]]:
    yield path, value
    if isinstance(value, Mapping):
        for key, item in value.items():
            child = f"{path}.{key}" if path else str(key)
            yield from _walk(item, child)
    elif _is_sequence(value):
        for index, item in enumerate(value):
            yield from _walk(item, f"{path}[{index}]")


def _validate_source_ids(
    payload: Mapping[str, Any],
    known: set[str],
    result: ValidationResult,
) -> None:
    references: list[tuple[str, str]] = []
    for path, value in _walk(payload):
        if path.endswith(".source_ids") or path == "source_ids":
            if not isinstance(value, list):
                result.add("RD.FIELD.INVALID", "ERROR", "source_ids must be an array", path)
            else:
                for index, source_id in enumerate(value):
                    token = _text(source_id)
                    if token:
                        references.append((f"{path}[{index}]", token))
        elif path.endswith(".source_id") or path == "source_id":
            token = _text(value)
            if token:
                references.append((path, token))
        if isinstance(value, str):
            for match in SOURCE_TOKEN.finditer(value):
                references.append((path, match.group(0)))
    for path, source_id in references:
        if source_id not in known:
            result.add(
                "RD.SOURCE.UNKNOWN",
                "ERROR",
                f"Source ID {source_id!r} is absent from literature_registry.json",
                path,
            )


def _source_ids(item: Mapping[str, Any]) -> list[str]:
    values = item.get("source_ids")
    if isinstance(values, list):
        return [_text(value) for value in values if _text(value)]
    singular = _text(item.get("source_id"))
    return [singular] if singular else []


def _registry_record_is_content_verified(record: Mapping[str, Any]) -> bool:
    state = _text(record.get("state")).lower()
    scope = _text(record.get("citation_scope")).lower()
    verification = record.get("verification")
    if not isinstance(verification, Mapping):
        verification = {}
    method = _text(verification.get("method")).lower()
    support_claim = _text(verification.get("support_claim"))
    explicit = record.get("content_verified") is True or _text(record.get("verification_status")).lower() in {
        "content-verified",
        "verified",
    }
    return (
        scope == "final-source"
        and (state in {"content-verified", "pdf-downloaded"} or explicit)
        and (method in {"abstract", "detail", "full-text", "pdf"} or explicit)
        and bool(support_claim or explicit)
    )


def _validate_source_verification(
    payload: Mapping[str, Any],
    registry: Mapping[str, Mapping[str, Any]],
    stage: str,
    result: ValidationResult,
) -> None:
    if stage not in {"execution", "build", "audit", "output"}:
        return
    for index, evidence in enumerate(payload.get("evidence") or []):
        if not isinstance(evidence, Mapping):
            continue
        load_bearing = bool(evidence.get("supports_claim_ids")) or evidence.get("load_bearing") is True
        represented_verified = (
            load_bearing
            or evidence.get("verified") is True
            or _text(evidence.get("verification_status")).lower() in {"verified", "content-verified"}
        )
        if not represented_verified:
            continue
        for source_id in _source_ids(evidence):
            record = registry.get(source_id)
            if record is None:
                continue
            if not _registry_record_is_content_verified(record):
                result.add(
                    "RD.SOURCE.UNVERIFIED_AS_VERIFIED",
                    "ERROR",
                    f"Load-bearing evidence represents unverified or candidate-only source {source_id} as verified",
                    f"evidence[{index}]",
                )


def _validate_ids(payload: Mapping[str, Any], result: ValidationResult) -> dict[str, set[str]]:
    collections = {
        "concepts": payload.get("concepts"),
        "claims": payload.get("claims"),
        "evidence": payload.get("evidence"),
        "hypotheses": payload.get("hypotheses", []),
        "propositions": payload.get("propositions", []),
        "alternatives": payload.get("alternatives"),
        "falsification_conditions": payload.get("falsification_conditions"),
    }
    known_by_collection: dict[str, set[str]] = {}
    globally_known: set[str] = set()

    singleton_ids = (
        ("research_question", _at(payload, "research_question.id")),
        ("design", _at(payload, "design.id")),
        ("framework", _at(payload, "framework.id")),
    )
    for name, raw_identifier in singleton_ids:
        identifier = _text(raw_identifier)
        path = f"{name}.id"
        if not identifier or not ID_PATTERN.fullmatch(identifier):
            result.add(
                "RD.ID.INVALID",
                "ERROR",
                f"Invalid or missing stable ID: {identifier!r}",
                path,
            )
            continue
        if identifier in globally_known:
            result.add("RD.ID.DUPLICATE", "ERROR", f"Duplicate global ID {identifier!r}", path)
        globally_known.add(identifier)

    for name, values in collections.items():
        if not isinstance(values, list):
            result.add("RD.FIELD.MISSING", "ERROR", f"{name} must be an array", name)
            known_by_collection[name] = set()
            continue
        known: set[str] = set()
        for index, item in enumerate(values):
            item_path = f"{name}[{index}]"
            if not isinstance(item, Mapping):
                result.add("RD.FIELD.INVALID", "ERROR", f"{name} entries must be objects", item_path)
                continue
            identifier = _text(item.get("id"))
            if not identifier or not ID_PATTERN.fullmatch(identifier):
                result.add(
                    "RD.ID.INVALID",
                    "ERROR",
                    f"Invalid or missing stable ID: {identifier!r}",
                    f"{item_path}.id",
                )
                continue
            if identifier in globally_known:
                result.add(
                    "RD.ID.DUPLICATE",
                    "ERROR",
                    f"Duplicate global ID {identifier!r}",
                    f"{item_path}.id",
                )
            known.add(identifier)
            globally_known.add(identifier)
        known_by_collection[name] = known

    concepts = known_by_collection["concepts"]
    claims = known_by_collection["claims"]
    evidence = known_by_collection["evidence"]
    reference_specs = (
        ("claims", "concept_ids", concepts),
        ("claims", "evidence_ids", evidence),
        ("evidence", "supports_claim_ids", claims),
        ("hypotheses", "concept_ids", concepts),
        ("hypotheses", "evidence_ids", evidence),
    )
    for collection, key, known in reference_specs:
        values = payload.get(collection)
        if not isinstance(values, list):
            continue
        for index, item in enumerate(values):
            if not isinstance(item, Mapping) or key not in item:
                continue
            references = item.get(key)
            path = f"{collection}[{index}].{key}"
            if not isinstance(references, list):
                result.add("RD.FIELD.INVALID", "ERROR", f"{key} must be an array", path)
                continue
            for ref_index, identifier in enumerate(references):
                token = _text(identifier)
                if token and token not in known:
                    result.add(
                        "RD.ID.UNRESOLVED",
                        "ERROR",
                        f"Unknown internal reference {token!r}",
                        f"{path}[{ref_index}]",
                    )
    known_by_collection["all"] = globally_known
    return known_by_collection


def _validate_research_question(payload: Mapping[str, Any], result: ValidationResult) -> None:
    _require_text(result, payload, "research_question.id")
    _require_text(result, payload, "research_question.text")
    question_type = _require_member(result, payload, "research_question.primary_type", QUESTION_TYPES)
    for key in ("object", "time", "issue", "perspective"):
        _require_text(result, payload, f"research_question.otipr.{key}")
    _require_member(result, payload, "research_question.otipr.relation.strength", {"strong", "weak"})
    _require_text(result, payload, "research_question.otipr.relation.statement")

    fields = _at(payload, "research_question.task_fields", {})
    if not isinstance(fields, Mapping):
        result.add(
            "RD.FIELD.INVALID",
            "ERROR",
            "research_question.task_fields must be an object",
            "research_question.task_fields",
        )
        return
    required = {
        "descriptive": {"descriptive_increment", "reconstruction_boundary"},
        "explanatory": {"relation", "discriminating_expectations"},
        "predictive": {
            "forecast_target",
            "horizon",
            "baseline",
            "uncertainty",
            "validation",
            "updating",
        },
        "operational": {"actor", "goal", "constraints", "levers", "feasibility", "evaluation"},
        "normative": {"normative_premises", "strongest_objection", "institutional_constraints"},
    }
    for key in required.get(question_type, set()):
        value = fields.get(key)
        path = f"research_question.task_fields.{key}"
        if not _substantive(value):
            result.add("RD.FIELD.MISSING", "ERROR", f"Question route field is missing: {key}", path)
        elif _contains_review(value):
            result.add("RD.REVIEW.QUESTION", "REVIEW", f"Question route field needs review: {key}", path)


def _validate_core(payload: Mapping[str, Any], result: ValidationResult) -> tuple[str, str]:
    schema = _text(payload.get("schema_version"))
    if not schema:
        result.add("RD.SCHEMA.MISSING", "ERROR", "schema_version is required", "schema_version")
    elif schema != SCHEMA_VERSION:
        code = "RD.SCHEMA.FUTURE" if schema.startswith("cnki-research-design/v") else "RD.SCHEMA.UNSUPPORTED"
        result.add(code, "ERROR", f"Unsupported schema_version {schema!r}; expected {SCHEMA_VERSION}", "schema_version")

    status = _require_member(result, payload, "status", {"confirmed", "draft", "needs-review"})
    if status != "confirmed":
        result.add(
            "RD.CONFIRMATION.MISSING",
            "ERROR",
            "Research design must be explicitly confirmed before the design gate can pass",
            "status",
        )
        if status == "needs-review":
            result.add("RD.REVIEW.MIGRATION", "REVIEW", "Migrated design still needs independent evidence-backed review", "status")

    _validate_research_question(payload, result)
    for dotted in (
        "knowledge_state.known",
        "knowledge_state.unknown",
        "knowledge_state.gap_authenticity",
        "knowledge_state.maturity",
        "knowledge_state.expected_contribution",
        "epistemic_position.paradigm",
        "epistemic_position.method_rationale",
        "design.id",
        "design.method",
        "design.method_rationale",
        "design.units",
        "design.time_scope",
        "design.inference_ceiling",
        "design.evidence_boundary",
        "design.limitations",
        "framework.description",
    ):
        code = "RD.BOUNDARY.MISSING" if dotted in {"design.inference_ceiling", "design.evidence_boundary"} else "RD.FIELD.MISSING"
        _require_text(result, payload, dotted, code=code)
    _require_member(result, payload, "epistemic_position.research_logic", RESEARCH_LOGICS)
    family = _require_member(result, payload, "design.family", FAMILIES)
    claim_type = _require_member(result, payload, "design.claim_type", CLAIM_TYPES)

    for collection in ("concepts", "claims", "evidence", "alternatives", "falsification_conditions"):
        values = payload.get(collection)
        if not isinstance(values, list) or not values:
            result.add("RD.FIELD.MISSING", "ERROR", f"{collection} must contain at least one entry", collection)

    for index, concept in enumerate(payload.get("concepts") or []):
        if not isinstance(concept, Mapping):
            continue
        for key in ("name", "definition", "boundary"):
            if not _substantive(concept.get(key)):
                result.add(
                    "RD.BOUNDARY.MISSING" if key == "boundary" else "RD.FIELD.MISSING",
                    "ERROR",
                    f"Concept {key} is missing",
                    f"concepts[{index}].{key}",
                )
        if _contains_review(concept):
            result.add(
                "RD.REVIEW.CONCEPT",
                "REVIEW",
                "Concept definition or boundary needs independent evidence-backed review",
                f"concepts[{index}]",
            )

    for index, claim in enumerate(payload.get("claims") or []):
        if not isinstance(claim, Mapping):
            continue
        for key in ("text", "type", "allowed_scope", "prohibited_scope"):
            if not _substantive(claim.get(key)):
                result.add(
                    "RD.BOUNDARY.MISSING" if key.endswith("scope") else "RD.FIELD.MISSING",
                    "ERROR",
                    f"Claim {key} is missing",
                    f"claims[{index}].{key}",
                )
        claim_kind = _text(claim.get("type"))
        if claim_kind and claim_kind not in CLAIM_TYPES:
            result.add(
                "RD.TYPE.UNSUPPORTED",
                "ERROR",
                f"Unsupported claim type {claim_kind!r}",
                f"claims[{index}].type",
            )

    return family, claim_type


def _validate_governance(
    payload: Mapping[str, Any],
    family: str,
    claim_type: str,
    stage: str,
    result: ValidationResult,
) -> None:
    permissions = _text(_at(payload, "design.permissions.status"))
    if permissions not in {
        "confirmed",
        "not-required",
        "not-applicable",
        "public",
        "open",
        "licensed",
        "licensed-restricted",
        "authorized",
    }:
        severity = "REVIEW" if _contains_review(permissions) else "ERROR"
        code = "RD.REVIEW.PERMISSION" if severity == "REVIEW" else "RD.PERMISSION.MISSING"
        result.add(code, severity, "Data/material permissions are unresolved", "design.permissions.status")

    ethics = _text(_at(payload, "design.ethics.status"))
    if ethics not in {"approved", "exempt", "not-required", "not-applicable"}:
        severity = "REVIEW" if _contains_review(ethics) else "ERROR"
        code = "RD.REVIEW.ETHICS" if severity == "REVIEW" else "RD.ETHICS.MISSING"
        result.add(code, severity, "Ethics status is missing or unresolved", "design.ethics.status")

    reproducibility = _text(_at(payload, "design.reproducibility.status"))
    accepted_repro = {"ready", "not-required"}
    if stage == "design":
        accepted_repro.add("planned")
    if reproducibility not in accepted_repro:
        severity = "REVIEW" if _contains_review(reproducibility) else "ERROR"
        code = "RD.REVIEW.REPRO" if severity == "REVIEW" else "RD.REPRO.MISSING"
        result.add(
            code,
            severity,
            f"Reproducibility status is missing or unresolved for stage {stage}",
            "design.reproducibility.status",
        )

    separation = _text(_at(payload, "design.evidence_separation.status"))
    if not separation:
        result.add(
            "RD.BOUNDARY.MISSING",
            "ERROR",
            "Framework-development and validation evidence separation is not declared",
            "design.evidence_separation.status",
        )
    elif separation == "same-material-claimed-validation":
        result.add(
            "RD.VALIDATION.LEAKAGE",
            "ERROR",
            "The same material cannot both construct a framework and independently validate it",
            "design.evidence_separation.status",
        )
    elif separation == "same-material-no-independent-test":
        if claim_type not in {"descriptive", "interpretive", "theory_generation", "review_synthesis"}:
            result.add(
                "RD.VALIDATION.LEAKAGE",
                "ERROR",
                "Same-material theory development cannot support the declared confirmatory claim",
                "design.evidence_separation.status",
            )
        else:
            result.add(
                "RD.RISK.CONSTRUCTION_REUSE",
                "WARNING",
                "Same-material theory development is allowed only without an independent-validation claim",
                "design.evidence_separation.status",
            )
    elif separation not in {"separated", "not-applicable"}:
        result.add(
            "RD.REVIEW.SEPARATION",
            "REVIEW",
            "Evidence-separation status needs independent evidence-backed review",
            "design.evidence_separation.status",
        )

    claim_text = " ".join(
        _text(item.get("text"))
        for item in payload.get("claims") or []
        if isinstance(item, Mapping)
    )
    causal_family = family in {"quantitative_causal", "case_process"}
    if (claim_type in {"causal_effect", "causal_mechanism"} or CAUSAL_TEXT.search(claim_text)) and not causal_family:
        result.add(
            "RD.CAUSAL.ROUTE_UNDECLARED",
            "ERROR",
            "A causal claim is active but no causal design route is declared",
            "design.family",
        )
        result.add(
            "RD.CAUSAL.OVERCLAIM",
            "ERROR",
            "Causal language exceeds the declared research-design family",
            "design.family",
        )
    if claim_type == "causal_effect" and family != "quantitative_causal":
        result.add(
            "RD.CAUSAL.OVERCLAIM",
            "ERROR",
            "A causal-effect claim requires a quantitative/causal identification route",
            "design.claim_type",
        )
    if UNIVERSAL_TEXT.search(claim_text):
        result.add(
            "RD.REVIEW.EXTRAPOLATION",
            "REVIEW",
            "Universal language requires an independent evidence-backed check against the inference ceiling",
            "claims",
        )


def _validate_empirical(
    base: Path,
    payload: Mapping[str, Any],
    family: str,
    claim_type: str,
    stage: str,
    result: ValidationResult,
) -> None:
    empirical = _at(payload, "design.empirical")
    if family in EMPIRICAL_FAMILIES and empirical is not True:
        result.add(
            "RD.FIELD.INVALID",
            "ERROR",
            f"Design family {family!r} must declare design.empirical=true",
            "design.empirical",
        )
    if empirical is not True:
        return

    route = _at(payload, f"routes.{family}", {})
    if not isinstance(route, Mapping):
        result.add("RD.ROUTE.MISSING", "ERROR", f"Missing route object for {family}", f"routes.{family}")
        route = {}
    for key in BRANCH_FIELDS.get(family, set()):
        value = route.get(key)
        path = f"routes.{family}.{key}"
        if not _substantive(value):
            code = "RD.CAUSAL.NO_COUNTERFACTUAL" if key == "comparison_or_counterfactual" else "RD.ROUTE.MISSING"
            result.add(code, "ERROR", f"Required {family} route field is missing: {key}", path)
        elif _contains_review(value):
            result.add("RD.REVIEW.METHOD", "REVIEW", f"Method route field needs review: {key}", path)

    if claim_type == "causal_effect" and not _substantive(route.get("comparison_or_counterfactual")):
        result.add(
            "RD.CAUSAL.NO_COUNTERFACTUAL",
            "ERROR",
            "Causal-effect design lacks comparison or counterfactual construction",
            f"routes.{family}.comparison_or_counterfactual",
        )

    reporting = _at(payload, "design.reporting_plan", {})
    if not isinstance(reporting, Mapping):
        reporting = {}
    for key in ("negative_findings", "deviations"):
        if not _substantive(reporting.get(key)):
            result.add(
                "RD.REPORT.SELECTIVE",
                "ERROR",
                f"Selective-reporting control is missing: {key}",
                f"design.reporting_plan.{key}",
            )

    if stage in {"execution", "build", "audit", "output"}:
        registered_results = _at(payload, "reporting.results", {})
        if isinstance(registered_results, Mapping):
            for result_id, record in registered_results.items():
                if not isinstance(record, Mapping):
                    continue
                status = _text(record.get("status"))
                included = record.get("included")
                if included is False and status in {"main", "null", "adverse", "negative", "confirmatory"}:
                    result.add(
                        "RD.REPORT.SELECTIVE",
                        "ERROR",
                        f"Registered {status} result {result_id} is marked omitted",
                        f"reporting.results.{result_id}.included",
                    )

    if family == "quantitative_causal":
        sampling = payload.get("sampling")
        if not isinstance(sampling, Mapping):
            sampling = {}
        for key in ("population", "frame", "unit", "strategy", "rationale", "limitations"):
            if not _substantive(sampling.get(key)):
                result.add(
                    "RD.SAMPLING.MISSING",
                    "ERROR",
                    f"Sampling field is missing: {key}",
                    f"sampling.{key}",
                )
        operationalized = False
        for index, concept in enumerate(payload.get("concepts") or []):
            if not isinstance(concept, Mapping):
                continue
            operations = concept.get("operationalization")
            if isinstance(operations, list) and operations:
                operationalized = True
                for op_index, operation in enumerate(operations):
                    if not isinstance(operation, Mapping):
                        result.add(
                            "RD.MEASUREMENT.MISSING",
                            "ERROR",
                            "Operationalization entries must be objects",
                            f"concepts[{index}].operationalization[{op_index}]",
                        )
                        continue
                    for key in ("indicator", "measurement", "data_source_ids"):
                        if not _substantive(operation.get(key)):
                            result.add(
                                "RD.MEASUREMENT.MISSING",
                                "ERROR",
                                f"Operationalization field is missing: {key}",
                                f"concepts[{index}].operationalization[{op_index}].{key}",
                            )
            measurement = concept.get("measurement")
            if not isinstance(measurement, Mapping):
                measurement = {}
            for key in ("reliability", "validity"):
                if not _substantive(measurement.get(key)):
                    result.add(
                        "RD.MEASUREMENT.MISSING",
                        "ERROR",
                        f"Measurement {key} plan is missing",
                        f"concepts[{index}].measurement.{key}",
                    )
        if not operationalized:
            result.add(
                "RD.MEASUREMENT.MISSING",
                "ERROR",
                "Quantitative/causal design requires at least one operationalized concept",
                "concepts",
            )

    artifact_paths = _at(payload, "design.artifact_paths", {})
    if not isinstance(artifact_paths, Mapping):
        result.add(
            "RD.ARTIFACT.MISSING",
            "ERROR",
            "design.artifact_paths must map artifact roles to workspace-relative files",
            "design.artifact_paths",
        )
        artifact_paths = {}
    required_artifacts = (
        DESIGN_EMPIRICAL_ARTIFACTS
        | DESIGN_BRANCH_ARTIFACTS.get(family, set())
    )
    if stage in {"execution", "build", "audit", "output"}:
        required_artifacts |= (
            EXECUTION_EMPIRICAL_ARTIFACTS
            | EXECUTION_BRANCH_ARTIFACTS.get(family, set())
        )
    for key in sorted(required_artifacts):
        raw = artifact_paths.get(key)
        dotted = f"design.artifact_paths.{key}"
        resolved = _safe_workspace_path(base, raw)
        if resolved is None:
            result.add(
                "RD.ARTIFACT.MISSING",
                "ERROR",
                f"Missing or unsafe registered artifact path: {key}",
                dotted,
            )
        elif not resolved.is_file():
            result.add(
                "RD.ARTIFACT.MISSING",
                "ERROR",
                f"Registered empirical artifact does not exist: {_text(raw)}",
                dotted,
            )


def _validate_fingerprints(base: Path, payload: Mapping[str, Any], result: ValidationResult) -> None:
    fingerprints = payload.get("artifact_fingerprints", [])
    if fingerprints is None:
        return
    if not isinstance(fingerprints, list):
        result.add(
            "RD.FIELD.INVALID",
            "ERROR",
            "artifact_fingerprints must be an array",
            "artifact_fingerprints",
        )
        return
    for index, record in enumerate(fingerprints):
        path = f"artifact_fingerprints[{index}]"
        if not isinstance(record, Mapping):
            result.add("RD.FIELD.INVALID", "ERROR", "Fingerprint entries must be objects", path)
            continue
        resolved = _safe_workspace_path(base, record.get("path"))
        expected = _text(record.get("sha256")).lower()
        if resolved is None or not resolved.is_file() or not re.fullmatch(r"[0-9a-f]{64}", expected):
            result.add(
                "RD.CONSISTENCY.DRIFT",
                "ERROR",
                "Fingerprint path or SHA-256 is invalid, or the artifact is missing",
                path,
            )
            continue
        if _sha256(resolved) != expected:
            result.add(
                "RD.CONSISTENCY.DRIFT",
                "ERROR",
                f"Artifact content has changed since design confirmation: {_text(record.get('path'))}",
                path,
            )


def _normalized_lock_text(value: Any) -> str:
    normalized = unicodedata.normalize("NFKC", _text(value)).casefold()
    return "".join(character for character in normalized if character.isalnum())


def _artifact_internal_ids(text: str) -> set[str]:
    return set(
        re.findall(
            r"(?<![A-Za-z0-9_-])"
            r"(?:"
            r"(?:CUN|CAS|SCP|CMP|WCA)-[A-Z0-9][A-Z0-9_-]*"
            r"|(?:RQ|CON|CLM|DSN|EVD|EV|HYP|PRP|AF|ALT|FAL|CL|T|D|C|E|H)[-_]?\d+"
            r")"
            r"(?![A-Za-z0-9_-])",
            text,
            flags=re.IGNORECASE,
        )
    )


def _has_assertive_causal_text(text: str) -> bool:
    """Return true only for positive causal assertions, not explicit prohibitions."""
    for match in CAUSAL_TEXT.finditer(text):
        prefix = text[max(0, match.start() - 32) : match.start()]
        if CAUSAL_NEGATION.search(prefix):
            continue
        return True
    return False


def _validate_cross_artifacts(
    base: Path,
    payload: Mapping[str, Any],
    identifiers: Mapping[str, set[str]],
    stage: str,
    result: ValidationResult,
) -> None:
    motivation = base / "confirmed_motivation.md"
    if motivation.is_file():
        text = motivation.read_text(encoding="utf-8-sig", errors="ignore")
        normalized = _normalized_lock_text(text)
        question = _normalized_lock_text(_at(payload, "research_question.text"))
        question_type = _text(_at(payload, "research_question.primary_type"))
        type_labels = {
            question_type,
            QUESTION_TYPE_CN.get(question_type, ""),
        }
        if question and question not in normalized:
            result.add(
                "RD.CONSISTENCY.DRIFT",
                "ERROR",
                "confirmed_motivation.md no longer contains the locked research question",
                "confirmed_motivation.md",
            )
        if not any(
            _normalized_lock_text(label) in normalized
            for label in type_labels
            if _normalized_lock_text(label)
        ):
            result.add(
                "RD.CONSISTENCY.DRIFT",
                "ERROR",
                "confirmed_motivation.md no longer contains the locked primary question type",
                "confirmed_motivation.md",
            )
        if _text(payload.get("schema_version")) in {
            SCHEMA_VERSION_V2,
            SCHEMA_VERSION_V3,
            SCHEMA_VERSION_V4,
        }:
            confirmed_gap_text = extract_markdown_gap_field(text)
            design_gap_text = _text(_at(payload, "knowledge_state.gap_authenticity"))
            if not confirmed_gap_text:
                result.add(
                    "RD.CONSISTENCY.DRIFT",
                    "ERROR",
                    "confirmed_motivation.md no longer contains the locked Gap Diagnosis",
                    "confirmed_motivation.md",
                )
            else:
                confirmed_gap, confirmed_gap_issues = validate_gap_diagnosis(
                    confirmed_gap_text,
                    context="confirmed gap diagnosis",
                )
                design_gap, design_gap_issues = validate_gap_diagnosis(
                    design_gap_text,
                    context="design gap diagnosis",
                )
                if (
                    not confirmed_gap_issues
                    and not design_gap_issues
                    and confirmed_gap is not None
                    and design_gap is not None
                    and not gap_core_matches(confirmed_gap, design_gap)
                ):
                    result.add(
                        "RD.CONSISTENCY.DRIFT",
                        "ERROR",
                        "research_design.json changes the confirmed gap locus, obstruction, claim, or SYN-* basis",
                        "knowledge_state.gap_authenticity",
                    )

    contribution = base / "confirmed_contribution.md"
    if contribution.is_file():
        text = contribution.read_text(encoding="utf-8-sig", errors="ignore")
        for claim in payload.get("claims") or []:
            if not isinstance(claim, Mapping):
                continue
            if _text(claim.get("status")) in {"inactive", "superseded", "withdrawn"}:
                continue
            claim_id = _text(claim.get("id"))
            if claim_id and not re.search(
                rf"(?<![A-Za-z0-9_-]){re.escape(claim_id)}(?![A-Za-z0-9_-])",
                text,
            ):
                result.add(
                    "RD.CONSISTENCY.DRIFT",
                    "ERROR",
                    f"confirmed_contribution.md does not reference active claim {claim_id}",
                    "confirmed_contribution.md",
                )

    all_known = identifiers.get("all", set())
    cross_paths: dict[str, Path] = {
        filename: base / filename
        for filename in (
            "confirmed_motivation.md",
            "confirmed_contribution.md",
            "execution_record.md",
            "results_validation.md",
            "evidence_bank.md",
            "writing_rationale_matrix.md",
        )
    }
    result_register = _safe_workspace_path(base, _at(payload, "design.artifact_paths.result_register"))
    if result_register is not None:
        cross_paths[result_register.relative_to(base.resolve()).as_posix()] = result_register
    bearing_files = {
        "execution_record.md",
        "results_validation.md",
        "evidence_bank.md",
        "writing_rationale_matrix.md",
    }
    if result_register is not None:
        bearing_files.add(result_register.relative_to(base.resolve()).as_posix())
    bearing_header = re.compile(
        r"claim|contribution|evidence|design|主张|贡献|证据|设计",
        re.IGNORECASE,
    )
    prohibited_header = re.compile(
        r"not\s+allowed|prohibited|forbidden|禁止|不得|不允许|禁止解释",
        re.IGNORECASE,
    )
    claim_to_evidence = {
        _text(claim.get("id")): set(_text(item) for item in claim.get("evidence_ids") or [])
        for claim in payload.get("claims") or []
        if isinstance(claim, Mapping)
    }
    claim_types = {
        _text(claim.get("id")): _text(claim.get("type"))
        for claim in payload.get("claims") or []
        if isinstance(claim, Mapping)
    }
    evidence_to_claim = {
        _text(evidence.get("id")): set(_text(item) for item in evidence.get("supports_claim_ids") or [])
        for evidence in payload.get("evidence") or []
        if isinstance(evidence, Mapping)
    }
    number_pattern = re.compile(
        r"(?:\d+(?:\.\d+)?\s*(?:%|％|个百分点|倍))|(?:[pP]\s*[<=>]\s*0?\.\d+)|(?:[nN]\s*=\s*\d+)"
    )
    for filename, path in cross_paths.items():
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8-sig", errors="ignore")
        for token in _artifact_internal_ids(text):
            canonical = token.upper()
            if canonical not in all_known:
                result.add(
                    "RD.ID.UNRESOLVED",
                    "ERROR",
                    f"{filename} references unknown internal ID {canonical}",
                    filename,
                )
        if filename not in bearing_files:
            continue
        for table_index, (headers, rows) in enumerate(_markdown_tables(text), start=1):
            if not bearing_header.search(" ".join(headers)):
                continue
            for row_index, row in enumerate(rows, start=1):
                row_text = " | ".join(row)
                if not _substantive(row_text):
                    continue
                row_ids = _artifact_internal_ids(row_text)
                if not row_ids:
                    result.add(
                        "RD.ID.UNRESOLVED",
                        "ERROR",
                        "Bearing row has no resolvable Claim, Evidence, or Design ID",
                        f"{filename}:table[{table_index}].row[{row_index}]",
                    )
                canonical_row_ids = {identifier.upper() for identifier in row_ids}
                row_claims = canonical_row_ids & identifiers.get("claims", set())
                row_evidence = canonical_row_ids & identifiers.get("evidence", set())
                assertive_row_text = " | ".join(
                    cell
                    for header, cell in zip(headers, row)
                    if not prohibited_header.search(header)
                )
                linked_pairs = {
                    (claim_id, evidence_id)
                    for claim_id in row_claims
                    for evidence_id in row_evidence
                    if (
                        evidence_id in claim_to_evidence.get(claim_id, set())
                        and claim_id in evidence_to_claim.get(evidence_id, set())
                    )
                }
                if len(row_claims) == 1 and len(row_evidence) == 1:
                    claim_id = next(iter(row_claims))
                    evidence_id = next(iter(row_evidence))
                    if (claim_id, evidence_id) not in linked_pairs:
                        result.add(
                            "RD.CONSISTENCY.CONTRADICTION",
                            "ERROR",
                            f"Bearing row pairs {claim_id} with {evidence_id}, but the contract does not register that bidirectional link",
                            f"{filename}:table[{table_index}].row[{row_index}]",
                        )
                elif row_claims and row_evidence:
                    isolated_claims = sorted(
                        claim_id
                        for claim_id in row_claims
                        if not any(pair[0] == claim_id for pair in linked_pairs)
                    )
                    isolated_evidence = sorted(
                        evidence_id
                        for evidence_id in row_evidence
                        if not any(pair[1] == evidence_id for pair in linked_pairs)
                    )
                    if isolated_claims or isolated_evidence:
                        details = []
                        if isolated_claims:
                            details.append("claims " + ", ".join(isolated_claims))
                        if isolated_evidence:
                            details.append("evidence " + ", ".join(isolated_evidence))
                        result.add(
                            "RD.CONSISTENCY.CONTRADICTION",
                            "ERROR",
                            "Bearing row contains IDs with no bidirectional contract link: "
                            + "; ".join(details),
                            f"{filename}:table[{table_index}].row[{row_index}]",
                        )
                for claim_id in row_claims:
                    if (
                        _has_assertive_causal_text(assertive_row_text)
                        and claim_types.get(claim_id) not in {"causal_effect", "causal_mechanism"}
                    ):
                        result.add(
                            "RD.CAUSAL.OVERCLAIM",
                            "ERROR",
                            f"Bearing row uses causal wording for noncausal claim {claim_id}",
                            f"{filename}:table[{table_index}].row[{row_index}]",
                        )
                if stage in {"execution", "build", "audit", "output"} and number_pattern.search(row_text):
                    evidence_ids = identifiers.get("evidence", set())
                    if not canonical_row_ids & evidence_ids:
                        result.add(
                            "RD.NUMBER.UNREGISTERED",
                            "ERROR",
                            "Load-bearing numeric result has no registered Evidence ID",
                            f"{filename}:table[{table_index}].row[{row_index}]",
                        )

    numbers_raw = _at(payload, "design.artifact_paths.numbers_registry")
    numbers_path = _safe_workspace_path(base, numbers_raw)
    if numbers_path is None and (base / "numbers.jsonl").is_file():
        numbers_path = base / "numbers.jsonl"
    if stage in {"execution", "build", "audit", "output"} and numbers_path is not None and numbers_path.is_file():
        for line_number, line in enumerate(
            numbers_path.read_text(encoding="utf-8-sig", errors="ignore").splitlines(),
            start=1,
        ):
            if not line.strip():
                continue
            try:
                record = json.loads(line)
            except json.JSONDecodeError:
                result.add(
                    "RD.NUMBER.UNREGISTERED",
                    "ERROR",
                    "numbers.jsonl contains invalid JSON",
                    f"{numbers_path.name}:{line_number}",
                )
                continue
            if not isinstance(record, Mapping) or not _substantive(record.get("value")):
                result.add(
                    "RD.NUMBER.UNREGISTERED",
                    "ERROR",
                    "Every number record must declare value and evidence_id",
                    f"{numbers_path.name}:{line_number}",
                )
                continue
            evidence_id = _text(record.get("evidence_id"))
            if evidence_id not in identifiers.get("evidence", set()):
                result.add(
                    "RD.NUMBER.UNREGISTERED",
                    "ERROR",
                    f"Number record points to unknown evidence ID {evidence_id!r}",
                    f"{numbers_path.name}:{line_number}",
                )


def validate_payload(
    base: Path,
    payload: Mapping[str, Any],
    *,
    stage: str = "design",
) -> ValidationResult:
    """Validate one parsed v1-v4 contract against its workspace and registry."""
    stage = canonical_stage(stage)
    result = ValidationResult()
    schema = _text(payload.get("schema_version"))
    if schema == SCHEMA_VERSION_V4:
        try:
            v2 = _v2_module()
            v3 = _v3_module()
            v4 = _v4_module()
            identifiers = v4.validate_payload(
                base,
                payload,
                stage=stage,
                result=result,
                v2=v2,
                v3=v3,
            )
        except (ContractError, OSError, ValueError) as exc:
            result.add(
                "RD.ADAPTER.REGISTRY_INVALID",
                "ERROR",
                str(exc),
                "method_routes",
            )
            return result
        registry = _registry_sources(base, result)
        _validate_source_ids(payload, set(registry), result)
        _validate_source_verification(payload, registry, stage, result)
        _validate_fingerprints(base, payload, result)
        projected = v4.cross_artifact_projection(payload, v2, v3)
        _validate_cross_artifacts(base, projected, identifiers, stage, result)
        return result
    if schema == SCHEMA_VERSION_V3:
        try:
            v2 = _v2_module()
            v3 = _v3_module()
            identifiers = v3.validate_payload(
                base,
                payload,
                stage=stage,
                result=result,
                v2=v2,
            )
        except (ContractError, OSError, ValueError) as exc:
            result.add(
                "RD.ADAPTER.REGISTRY_INVALID",
                "ERROR",
                str(exc),
                "method_routes",
            )
            return result
        registry = _registry_sources(base, result)
        _validate_source_ids(payload, set(registry), result)
        _validate_source_verification(payload, registry, stage, result)
        _validate_fingerprints(base, payload, result)
        projected = v3.cross_artifact_projection(payload, v2)
        _validate_cross_artifacts(base, projected, identifiers, stage, result)
        return result
    if schema == SCHEMA_VERSION_V2:
        try:
            v2 = _v2_module()
            identifiers = v2.validate_payload(
                base,
                payload,
                stage=stage,
                result=result,
            )
        except (ContractError, OSError, ValueError) as exc:
            result.add(
                "RD.ADAPTER.REGISTRY_INVALID",
                "ERROR",
                str(exc),
                "method_routes",
            )
            return result
        registry = _registry_sources(base, result)
        _validate_source_ids(payload, set(registry), result)
        _validate_source_verification(payload, registry, stage, result)
        _validate_fingerprints(base, payload, result)
        projected = v2.cross_artifact_projection(payload)
        _validate_cross_artifacts(base, projected, identifiers, stage, result)
        return result
    if schema != SCHEMA_VERSION_V1:
        if not schema:
            result.add("RD.SCHEMA.MISSING", "ERROR", "schema_version is required", "schema_version")
        else:
            code = (
                "RD.SCHEMA.FUTURE"
                if schema.startswith("cnki-research-design/v")
                else "RD.SCHEMA.UNSUPPORTED"
            )
            result.add(
                code,
                "ERROR",
                (
                    f"Unsupported schema_version {schema!r}; supported readers are "
                    f"{SCHEMA_VERSION_V1}, {SCHEMA_VERSION_V2}, {SCHEMA_VERSION_V3}, "
                    f"and {SCHEMA_VERSION_V4}"
                ),
                "schema_version",
            )
        return result
    family, claim_type = _validate_core(payload, result)
    identifiers = _validate_ids(payload, result)
    registry = _registry_sources(base, result)
    _validate_source_ids(payload, set(registry), result)
    _validate_source_verification(payload, registry, stage, result)
    _validate_governance(payload, family, claim_type, stage, result)
    _validate_empirical(base, payload, family, claim_type, stage, result)
    _validate_fingerprints(base, payload, result)
    _validate_cross_artifacts(base, payload, identifiers, stage, result)
    return result


def validate_contract(
    path: Path,
    *,
    stage: str = "design",
) -> tuple[Path, Mapping[str, Any] | None, ValidationResult]:
    base, contract_path = resolve_contract_path(path)
    result = ValidationResult()
    if not contract_path.exists():
        result.add(
            "RD.FILE.MISSING",
            "ERROR",
            f"Research-design contract is missing: {contract_path}",
            DESIGN_REL.as_posix(),
        )
        return base, None, result
    try:
        payload = _load_json(contract_path)
    except ContractError as exc:
        result.add("RD.JSON.INVALID", "ERROR", str(exc), DESIGN_REL.as_posix())
        return base, None, result
    return base, payload, validate_payload(base, payload, stage=stage)


def validation_payload(result: ValidationResult, design_schema: str = "") -> dict[str, Any]:
    counts = {
        severity: sum(1 for issue in result.issues if issue.severity == severity)
        for severity in ("ERROR", "WARNING", "REVIEW")
    }
    return {
        "schema_version": CHECK_SCHEMA_VERSION,
        "design_schema_version": design_schema,
        "status": result.status,
        "counts": counts,
        "issues": [asdict(issue) for issue in result.issues],
    }


def validation_markdown(result: ValidationResult, design_schema: str = "") -> str:
    report = validation_payload(result, design_schema)
    lines = [
        "# Research Design Check",
        "",
        f"- Status: **{report['status']}**",
        f"- Design schema: `{design_schema or 'unknown'}`",
        f"- ERROR: {report['counts']['ERROR']}",
        f"- WARNING: {report['counts']['WARNING']}",
        f"- REVIEW: {report['counts']['REVIEW']}",
    ]
    for severity in ("ERROR", "WARNING", "REVIEW"):
        issues = [issue for issue in result.issues if issue.severity == severity]
        if not issues:
            continue
        lines.extend(["", f"## {severity}", ""])
        for issue in issues:
            location = f" (`{issue.path}`)" if issue.path else ""
            lines.append(f"- `{issue.code}`{location}: {issue.message}")
    lines.append("")
    return "\n".join(lines)


def _md_cell(value: Any) -> str:
    text = _text(value).replace("\r", " ").replace("\n", " ").replace("|", r"\|")
    return re.sub(r"\s+", " ", text).strip()


def _ids(items: Any) -> str:
    if not isinstance(items, list):
        return ""
    return ", ".join(_text(item) for item in items if _text(item))


def _evidence_for(payload: Mapping[str, Any], *values: Any) -> str:
    source_ids: list[str] = []
    for value in values:
        for token in SOURCE_TOKEN.findall(_text(value)):
            if token not in source_ids:
                source_ids.append(token)
    if not source_ids:
        for evidence in payload.get("evidence") or []:
            if isinstance(evidence, Mapping):
                for token in evidence.get("source_ids") or []:
                    text = _text(token)
                    if text and text not in source_ids:
                        source_ids.append(text)
    return ", ".join(source_ids) or "research_design.json"


def _otipr_text(payload: Mapping[str, Any]) -> str:
    otipr = _at(payload, "research_question.otipr", {})
    if not isinstance(otipr, Mapping):
        return ""
    relation = otipr.get("relation")
    if isinstance(relation, Mapping):
        strength = {"strong": "强关系", "weak": "弱关系"}.get(
            _text(relation.get("strength")),
            _text(relation.get("strength")),
        )
        relation_text = f"{strength}: {_text(relation.get('statement'))}"
    else:
        relation_text = _text(relation)
    return (
        f"O={_text(otipr.get('object'))}; T={_text(otipr.get('time'))}; "
        f"I={_text(otipr.get('issue'))}; P={_text(otipr.get('perspective'))}; "
        f"R={relation_text}"
    )


