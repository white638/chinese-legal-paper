def _migrate_contract_to_v4(path: Path, *, apply: bool) -> tuple[int, str]:
    base, contract_path = resolve_contract_path(path)
    if not contract_path.exists():
        return 2, (
            "Research-design v4 migration requires an existing v1, v2, or v3 "
            f"research_design.json: {contract_path}\n"
        )
    try:
        existing = _load_json(contract_path)
        source_text = contract_path.read_text(encoding="utf-8-sig")
    except (ContractError, OSError) as exc:
        return 2, f"{exc}\n"
    schema = _text(existing.get("schema_version"))
    if schema == SCHEMA_VERSION_V4:
        return 0, f"Migration is already complete; current contract exists: {contract_path}\n"
    if schema not in {SCHEMA_VERSION_V1, SCHEMA_VERSION_V2, SCHEMA_VERSION_V3}:
        qualifier = "future " if schema.startswith("cnki-research-design/v") else ""
        return 2, (
            f"Refusing migration because an unsupported or {qualifier}contract already exists "
            f"({schema or 'missing schema'}): {contract_path}\n"
        )
    try:
        payload = _v4_module().migrate_payload(
            existing,
            v2=_v2_module(),
            v3=_v3_module(),
        )
    except (OSError, ValueError) as exc:
        return 2, f"Could not create a safe v4 migration: {exc}\n"
    digest = hashlib.sha256(source_text.encode("utf-8")).hexdigest()
    source_kind = f"{schema.rsplit('/', 1)[-1]}-contract"
    backup_rel = MIGRATION_V4_REL / (
        f"research_design.{digest[:12]}.{schema.rsplit('/', 1)[-1]}.json"
    )
    preview = {
        "mode": "apply" if apply else "dry-run",
        "source_kind": source_kind,
        "contract": str(contract_path),
        "backup": str(base / backup_rel),
        "schema_version": SCHEMA_VERSION_V4,
        "status": "needs-review",
        "payload": payload,
    }
    if not apply:
        return 0, json.dumps(preview, ensure_ascii=False, indent=2) + "\n"
    backup_path = base / backup_rel
    if not backup_path.exists():
        _atomic_write_text(backup_path, source_text)
    _atomic_write_json(contract_path, payload)
    render_views(base, payload, allow_unmanaged_replace=True)
    return 0, (
        f"Migrated {source_kind} to {SCHEMA_VERSION_V4} at {contract_path}\n"
        "Status remains needs-review; OPR and STEP shells are not accepted research actions.\n"
    )


