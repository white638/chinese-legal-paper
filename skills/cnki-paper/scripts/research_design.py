def render_views(
    base: Path,
    payload: Mapping[str, Any],
    *,
    allow_unmanaged_replace: bool = False,
) -> list[Path]:
    if _text(payload.get("schema_version")) == SCHEMA_VERSION_V4:
        try:
            return _v4_module().render_views(
                base,
                payload,
                allow_unmanaged_replace=allow_unmanaged_replace,
                v2=_v2_module(),
                v3=_v3_module(),
            )
        except (OSError, ValueError) as exc:
            raise ContractError(str(exc)) from exc
    if _text(payload.get("schema_version")) == SCHEMA_VERSION_V3:
        try:
            return _v3_module().render_views(
                base,
                payload,
                allow_unmanaged_replace=allow_unmanaged_replace,
                v2=_v2_module(),
            )
        except (OSError, ValueError) as exc:
            raise ContractError(str(exc)) from exc
    if _text(payload.get("schema_version")) == SCHEMA_VERSION_V2:
        try:
            return _v2_module().render_views(
                base,
                payload,
                allow_unmanaged_replace=allow_unmanaged_replace,
            )
        except (OSError, ValueError) as exc:
            raise ContractError(str(exc)) from exc
    rendered = {
        VIEW_RELS[0]: render_knowledge_matrix(payload),
        VIEW_RELS[1]: render_concept_register(payload),
        VIEW_RELS[2]: render_claim_matrix(payload),
    }
    for relative in rendered:
        path = base / relative
        if path.exists() and GENERATED_MARKER not in path.read_text(
            encoding="utf-8-sig", errors="ignore"
        ):
            if not allow_unmanaged_replace:
                raise ContractError(
                    f"Refusing to overwrite hand-maintained view {path}; run migrate --apply first"
                )
    for relative, content in rendered.items():
        _atomic_write_text(base / relative, content)
    return [base / relative for relative in rendered]


def _normal(value: str) -> str:
    return re.sub(r"[\s`*_：:、，,（）()\-/]+", "", value).lower()


def _markdown_tables(text: str) -> list[tuple[list[str], list[list[str]]]]:
    lines = text.splitlines()
    tables: list[tuple[list[str], list[list[str]]]] = []
    index = 0
    while index + 1 < len(lines):
        if "|" not in lines[index] or "|" not in lines[index + 1]:
            index += 1
            continue
        separator = [cell.strip() for cell in lines[index + 1].strip().strip("|").split("|")]
        if not separator or not all(re.fullmatch(r":?-{3,}:?", cell.replace(" ", "")) for cell in separator):
            index += 1
            continue
        headers = [cell.strip() for cell in lines[index].strip().strip("|").split("|")]
        rows: list[list[str]] = []
        cursor = index + 2
        while cursor < len(lines) and "|" in lines[cursor] and lines[cursor].strip():
            rows.append([cell.strip() for cell in lines[cursor].strip().strip("|").split("|")])
            cursor += 1
        tables.append((headers, rows))
        index = cursor
    return tables


