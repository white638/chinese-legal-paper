def _research_design_authority() -> Any:
    """Load the canonical design validator without copying its rules."""

    global _RESEARCH_DESIGN_AUTHORITY
    if _RESEARCH_DESIGN_AUTHORITY is not None:
        return _RESEARCH_DESIGN_AUTHORITY
    if not RESEARCH_DESIGN_AUTHORITY_PATH.is_file():
        raise ExecutionContractError(
            f"Canonical research-design validator is missing: {RESEARCH_DESIGN_AUTHORITY_PATH}"
        )
    module_name = "_method_execution_research_design_authority"
    spec = importlib.util.spec_from_file_location(
        module_name,
        RESEARCH_DESIGN_AUTHORITY_PATH,
    )
    if spec is None or spec.loader is None:
        raise ExecutionContractError(
            f"Cannot load canonical research-design validator: {RESEARCH_DESIGN_AUTHORITY_PATH}"
        )
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    try:
        spec.loader.exec_module(module)
    except Exception:
        sys.modules.pop(module_name, None)
        raise
    _RESEARCH_DESIGN_AUTHORITY = module
    return module


