def scaffold_command(path: Path, *, dry_run: bool = False) -> int:
    base, contract_path = resolve_path(path)
    if contract_path.exists():
        print(f"Refusing to overwrite existing method execution contract: {contract_path}", file=sys.stderr)
        return 2
    try:
        design = _load_json(base / DESIGN_REL)
        if _text(design.get("schema_version")) != DESIGN_SCHEMA_VERSION_V4:
            raise ExecutionContractError(
                f"New execution scaffolds require {DESIGN_SCHEMA_VERSION_V4}; migrate research_design.json first"
            )
        payload = scaffold_payload(design)
    except ExecutionContractError as exc:
        print(exc, file=sys.stderr)
        return 2
    if dry_run:
        print(json.dumps(payload, ensure_ascii=False, indent=2))
        return 0
    _atomic_write_json(contract_path, payload)
    print(f"Scaffolded {SCHEMA_VERSION_V3}: {contract_path}")
    print("Status remains needs-review until actual execution, artifacts, results, and reporting are registered.")
    return 0


def _split_row(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def _legacy_table(text: str) -> tuple[list[str], list[list[str]]] | None:
    lines = text.splitlines()
    for index in range(len(lines) - 1):
        if "|" not in lines[index] or "|" not in lines[index + 1]:
            continue
        separator = _split_row(lines[index + 1])
        if not separator or not all(re.fullmatch(r":?-{3,}:?", cell.replace(" ", "")) for cell in separator):
            continue
        headers = _split_row(lines[index])
        rows: list[list[str]] = []
        cursor = index + 2
        while cursor < len(lines) and "|" in lines[cursor] and lines[cursor].strip():
            rows.append(_split_row(lines[cursor]))
            cursor += 1
        if any(re.search(r"execution|执行编号|分析编号", header, re.IGNORECASE) for header in headers):
            return headers, rows
    return None


def migrate_legacy_payload(
    design: Mapping[str, Any],
    legacy_text: str,
) -> Mapping[str, Any]:
    # Migration must preserve a legacy execution record even when the v1 design
    # could not safely distinguish merged routes such as case/process. New
    # execution scaffolds still block unresolved routes.
    payload = dict(scaffold_payload(design, allow_unresolved=True))
    table = _legacy_table(legacy_text)
    routes = {
        _text(route.get("id")).upper(): route
        for route in design.get("method_routes") or []
        if isinstance(route, Mapping)
    }
    if table is not None:
        headers, rows = table
        normalized = [re.sub(r"[\s/_-]+", "", header).casefold() for header in headers]
        execution_index = next(
            (index for index, header in enumerate(normalized) if "executionid" in header or "执行编号" in header or "分析编号" in header),
            None,
        )
        design_index = next(
            (index for index, header in enumerate(normalized) if "designid" in header or "设计编号" in header),
            None,
        )
        action_index = next(
            (index for index, header in enumerate(normalized) if "methodaction" in header or "analysisaction" in header or "方法动作" in header or "分析动作" in header),
            None,
        )
        result_index = next(
            (index for index, header in enumerate(normalized) if "result" in header or "inference" in header or "结果" in header or "推断" in header),
            None,
        )
        for row_number, row in enumerate(rows, start=1):
            design_id = row[design_index].strip().upper() if design_index is not None and design_index < len(row) else ""
            if design_id not in routes:
                continue
            run = next(
                (
                    item
                    for item in payload["runs"]
                    if _text(item.get("design_id")).upper() == design_id
                ),
                None,
            )
            if not isinstance(run, dict):
                continue
            if execution_index is not None and execution_index < len(row):
                candidate = row[execution_index].strip().upper()
                if ID_PATTERN.fullmatch(candidate):
                    run["id"] = candidate
            action = row[action_index].strip() if action_index is not None and action_index < len(row) else ""
            old_result = row[result_index].strip() if result_index is not None and result_index < len(row) else ""
            run["actions"] = [
                action or f"needs-review: recover method action from legacy row {row_number}"
            ]
            run["migration_note"] = (
                f"needs-review: legacy result was not promoted to a registered result: {old_result}"
                if old_result
                else f"needs-review: legacy row {row_number} had no recoverable result"
            )
    payload["migration"] = {
        "from": "legacy execution_record.md",
        "status": "needs-review",
        "note": "Long text and keywords were not converted into PASS, results, or artifact hashes.",
    }
    return payload


def migrate_v1_payload(
    design: Mapping[str, Any],
    legacy: Mapping[str, Any],
) -> Mapping[str, Any]:
    """Preserve v1 identities while refusing to invent case-level execution facts."""
    payload = deepcopy(dict(scaffold_payload(design, allow_unresolved=True)))
    legacy_runs = {
        _text(run.get("design_id")).upper(): run
        for run in legacy.get("runs") or []
        if isinstance(run, Mapping) and _text(run.get("design_id"))
    }
    case_sensitive = False
    for run in payload.get("runs") or []:
        if not isinstance(run, dict):
            continue
        old = legacy_runs.get(_text(run.get("design_id")).upper())
        if not isinstance(old, Mapping):
            continue
        for field_name in (
            "id",
            "design_id",
            "route_family",
            "adapter_version",
            "design_route_sha256",
            "question_ids",
            "claim_ids",
            "evidence_ids",
            "status",
            "actions",
            "method_fields",
            "artifacts",
            "results",
            "deviations",
            "negative_findings",
            "ethics_events",
            "software_environment_ids",
            "inference_ceiling_observed",
            "prohibited_inferences_observed",
            "not_applicable_reason",
        ):
            if field_name in old:
                run[field_name] = deepcopy(old.get(field_name))
        for item in run.get("results") or []:
            if isinstance(item, dict):
                item.setdefault("case_ids", [])
                item.setdefault("scope_condition_ids", [])
                item.setdefault("comparison_ids", [])
                item.setdefault("within_case_analysis_ids", [])
        if _text(run.get("route_family")) in CASE_FAMILIES:
            case_sensitive = True
            run["case_ids"] = []
            run["scope_condition_ids"] = []
            run["comparison_ids"] = []
            run["within_case_analysis_ids"] = []
            run["case_execution"] = {
                "applicability": "needs-review",
                "actual_case_ids": [],
                "case_changes": [],
                "theory_prediction_observation_matrix": [],
                "mechanism_traces": [],
                "negative_cases": [],
                "scope_revisions": [],
                "handoff_results": [],
                "negative_case_review_status": "needs-review",
                "contradictory_result_status": "needs-review",
                "scope_review_status": "needs-review",
            }
    if isinstance(legacy.get("software_environments"), list):
        payload["software_environments"] = deepcopy(legacy.get("software_environments"))
    if isinstance(legacy.get("reporting"), Mapping):
        payload["reporting"] = deepcopy(legacy.get("reporting"))
    payload["status"] = "needs-review"
    if case_sensitive:
        payload["design_sha256"] = (
            "needs-review: case-oriented execution must be manually rebound to the v3 design"
        )
    payload["migration"] = {
        "from": SCHEMA_VERSION_V1,
        "to": SCHEMA_VERSION_V2,
        "status": "needs-review",
        "case_sensitive": case_sensitive,
        "note": (
            "Stable run, result, artifact, and hash identities were preserved. "
            "No case role, actual inclusion, mechanism trace, congruence result, "
            "scope revision, or PASS state was inferred from legacy text."
        ),
    }
    return payload


def migrate_v2_payload(
    design: Mapping[str, Any],
    legacy: Mapping[str, Any],
) -> Mapping[str, Any]:
    """Lift v2 into a reviewable v3 shell without fabricating accepted actions."""

    if _text(design.get("schema_version")) != DESIGN_SCHEMA_VERSION_V4:
        raise ExecutionContractError(
            f"v2 to v3 migration requires {DESIGN_SCHEMA_VERSION_V4}"
        )
    if _text(legacy.get("schema_version")) != SCHEMA_VERSION_V2:
        raise ExecutionContractError("v2 to v3 migration requires a v2 execution contract")
    payload = deepcopy(dict(scaffold_payload(design, allow_unresolved=True)))
    old_runs = {
        _text(item.get("design_id")).upper(): item
        for item in legacy.get("runs") or []
        if isinstance(item, Mapping) and _text(item.get("design_id"))
    }
    preserved_fields = (
        "id",
        "design_id",
        "route_family",
        "adapter_version",
        "design_route_sha256",
        "question_ids",
        "claim_ids",
        "evidence_ids",
        "status",
        "not_applicable_reason",
        "method_fields",
        "method_contract_schema",
        "method_contract_revision",
        "method_profile",
        "design_method_contract_sha256",
        "method_contract",
        "supplemental_profile_id",
        "design_supplemental_contract_sha256",
        "supplemental_contract",
        "artifact_refs",
        "case_ids",
        "scope_condition_ids",
        "comparison_ids",
        "within_case_analysis_ids",
        "case_execution",
        "artifacts",
        "results",
        "deviations",
        "negative_findings",
        "ethics_events",
        "software_environment_ids",
        "inference_ceiling_observed",
        "prohibited_inferences_observed",
        "inference_disposition",
    )
    legacy_action_inventory: list[dict[str, Any]] = []
    for run in payload.get("runs") or []:
        if not isinstance(run, dict):
            continue
        old = old_runs.get(_text(run.get("design_id")).upper())
        if not isinstance(old, Mapping):
            continue
        for field_name in preserved_fields:
            if field_name in old:
                run[field_name] = deepcopy(old.get(field_name))
        old_actions = deepcopy(old.get("actions")) if isinstance(old.get("actions"), list) else []
        if old_actions:
            legacy_action_inventory.append(
                {
                    "execution_id": _text(run.get("id")),
                    "design_id": _text(run.get("design_id")),
                    "actions": old_actions,
                }
            )
        # v2 strings contain no immutable attempt, environment, diagnostic, or
        # result provenance.  They are evidence for review, never accepted v3 actions.
        run["actions"] = []
        run["claim_dispositions"] = []
        run["minimum_viable_run"] = {
            "status": "unchecked",
            "material_id": "",
            "analysis_unit": {
                "id": "",
                "material_id": "",
                "unit_type": "",
                "locator": "",
            },
            "extraction_or_coding": {
                "kind": "",
                "rule": "",
                "artifact_id": "",
            },
            "action_ids": [],
            "artifact_ids": [],
            "check_result_ids": [],
            "result_ids": [],
            "claim_disposition_ids": [],
        }
        for item in run.get("results") or []:
            if isinstance(item, dict):
                item["action_ids"] = []
        for item in run.get("deviations") or []:
            if isinstance(item, dict):
                item.setdefault("action_id", "")
                item.setdefault("failure_code", _text(item.get("classification")).upper())
                item.setdefault("disposition_route", _text(item.get("disposition")))
        run["migration_status"] = "needs-review"
    if isinstance(legacy.get("software_environments"), list):
        payload["software_environments"] = deepcopy(legacy.get("software_environments"))
    if isinstance(legacy.get("reporting"), Mapping):
        payload["reporting"] = deepcopy(legacy.get("reporting"))
    for field_name in ("feasibility_basis_digest", "material_realizations"):
        if field_name in legacy:
            payload[field_name] = deepcopy(legacy.get(field_name))
    payload["status"] = "needs-review"
    payload["migration"] = {
        "from": SCHEMA_VERSION_V2,
        "to": SCHEMA_VERSION_V3,
        "status": "needs-review",
        "legacy_actions": legacy_action_inventory,
        "note": (
            "Stable run, result, artifact, environment, and SHA identities were preserved. "
            "Legacy string actions were not promoted to accepted attempts or MVMR evidence; "
            "all results require explicit binding to a newly reviewed accepted action."
        ),
    }
    return payload


def migrate_command(
    path: Path,
    *,
    apply: bool,
    to: str = "v2",
) -> tuple[int, str]:
    if to == "v3":
        base, contract_path = resolve_path(path)
        if not contract_path.is_file():
            return 2, f"v2 execution contract is missing: {contract_path}\n"
        try:
            existing = _load_json(contract_path)
            schema = _text(existing.get("schema_version"))
            if schema == SCHEMA_VERSION_V3:
                return 0, f"Migration is already complete; current contract exists: {contract_path}\n"
            if schema != SCHEMA_VERSION_V2:
                return 2, f"Migration to v3 requires {SCHEMA_VERSION_V2}; found {schema or 'missing schema'}\n"
            design = _load_json(base / DESIGN_REL)
            if _text(design.get("schema_version")) != DESIGN_SCHEMA_VERSION_V4:
                raise ExecutionContractError(
                    f"Migrate research_design.json to {DESIGN_SCHEMA_VERSION_V4} before migrating execution"
                )
            payload = migrate_v2_payload(design, existing)
            source_text = contract_path.read_text(encoding="utf-8-sig")
        except (ExecutionContractError, OSError) as exc:
            return 2, f"{exc}\n"
        digest = hashlib.sha256(source_text.encode("utf-8")).hexdigest()
        backup_rel = MIGRATION_V3_REL / f"method_execution.{digest[:12]}.v2.json"
        preview = {
            "mode": "apply" if apply else "dry-run",
            "source_kind": "v2-contract",
            "contract": str(contract_path),
            "backup": str(base / backup_rel),
            "schema_version": SCHEMA_VERSION_V3,
            "status": "needs-review",
            "payload": payload,
        }
        if not apply:
            return 0, json.dumps(preview, ensure_ascii=False, indent=2) + "\n"
        backup = base / backup_rel
        if not backup.exists():
            _atomic_write_text(backup, source_text)
        _atomic_write_json(contract_path, payload)
        render_record(base, payload, allow_unmanaged_replace=True)
        return 0, (
            f"Migrated v2 contract to {SCHEMA_VERSION_V3} at {contract_path}\n"
            "Status remains needs-review; typed attempts, MVMR evidence, diagnostics, result links, and claim dispositions must be reviewed.\n"
        )
    if to != "v2":
        return 2, "Only migration to cnki-method-execution/v2 or v3 is supported.\n"
    base, contract_path = resolve_path(path)
    existing: Mapping[str, Any] | None = None
    source_text = ""
    source_kind = "legacy-record"
    if contract_path.exists():
        try:
            existing = _load_json(contract_path)
            source_text = contract_path.read_text(encoding="utf-8-sig")
        except ExecutionContractError as exc:
            return 2, f"{exc}\n"
        schema = _text(existing.get("schema_version"))
        if schema == SCHEMA_VERSION_V2:
            return 0, f"Migration is already complete; current contract exists: {contract_path}\n"
        if schema != SCHEMA_VERSION_V1:
            qualifier = "future " if schema.startswith("cnki-method-execution/v") else ""
            return 2, (
                f"Refusing migration because an unsupported or {qualifier}execution contract exists "
                f"({schema or 'missing schema'}): {contract_path}\n"
            )
        source_kind = "v1-contract"
    try:
        design = _load_json(base / DESIGN_REL)
        if _text(design.get("schema_version")) != DESIGN_SCHEMA_VERSION_V3:
            raise ExecutionContractError(
                f"Migrate research_design.json to {DESIGN_SCHEMA_VERSION_V3} before migrating execution"
            )
        legacy_path = base / VIEW_REL
        legacy_text = (
            legacy_path.read_text(encoding="utf-8-sig")
            if existing is None and legacy_path.is_file()
            else ""
        )
        payload = (
            migrate_v1_payload(design, existing)
            if existing is not None
            else migrate_legacy_payload(design, legacy_text)
        )
    except (ExecutionContractError, OSError) as exc:
        return 2, f"{exc}\n"
    backup_source = source_text if existing is not None else legacy_text
    digest = hashlib.sha256(backup_source.encode("utf-8")).hexdigest()
    backup_rel = (
        MIGRATION_V2_REL / f"method_execution.{digest[:12]}.v1.json"
        if existing is not None
        else MIGRATION_V2_REL / f"execution_record.{digest[:12]}.legacy.md"
    )
    preview = {
        "mode": "apply" if apply else "dry-run",
        "source_kind": source_kind,
        "contract": str(contract_path),
        "legacy_record": (
            str(base / VIEW_REL)
            if existing is None and (base / VIEW_REL).is_file()
            else None
        ),
        "backup": str(base / backup_rel),
        "schema_version": SCHEMA_VERSION_V2,
        "status": "needs-review",
        "payload": payload,
    }
    if not apply:
        return 0, json.dumps(preview, ensure_ascii=False, indent=2) + "\n"
    backup = base / backup_rel
    if not backup.exists():
        _atomic_write_text(backup, backup_source)
    _atomic_write_json(contract_path, payload)
    render_record(base, payload, allow_unmanaged_replace=True)
    return 0, (
        f"Migrated {source_kind} to {SCHEMA_VERSION_V2} at {contract_path}\n"
        "Status remains needs-review; case facts, actions, results, negative findings, environments, and hashes must be confirmed.\n"
    )


def validate_command(
    path: Path,
    *,
    write: bool,
    json_stdout: bool,
    stage: str,
) -> int:
    base, payload, result = validate_contract(path, stage=stage)
    schema = _text(payload.get("schema_version")) if payload is not None else ""
    # v2 remains a supported reader and may refresh only its derived views;
    # authoritative scaffolds/migrations still write v3.
    unsafe = bool(payload is not None and schema not in {SCHEMA_VERSION_V2, SCHEMA_VERSION_V3})
    if write and payload is not None and not unsafe:
        try:
            render_record(base, payload)
        except ExecutionContractError as exc:
            result.add("ME.VIEW.UNMANAGED", "ERROR", str(exc), VIEW_REL.as_posix())
    report_json = validation_payload(result, schema)
    report_md = validation_markdown(result, schema)
    if write and not unsafe:
        _atomic_write_json(base / CHECK_JSON_REL, report_json)
        _atomic_write_text(base / CHECK_MD_REL, report_md)
    if json_stdout:
        print(json.dumps(report_json, ensure_ascii=False, indent=2))
    else:
        print(report_md, end="")
    return 1 if result.errors else 0


def render_command(path: Path) -> int:
    base, contract_path = resolve_path(path)
    try:
        payload = _load_json(contract_path)
        schema = _text(payload.get("schema_version"))
        if schema not in {SCHEMA_VERSION_V1, SCHEMA_VERSION_V2, SCHEMA_VERSION_V3}:
            raise ExecutionContractError(
                f"Cannot render execution schema {schema!r}; supported readers are "
                f"{SCHEMA_VERSION_V1}, {SCHEMA_VERSION_V2}, and {SCHEMA_VERSION_V3}"
            )
        output = render_record(base, payload)
    except ExecutionContractError as exc:
        print(exc, file=sys.stderr)
        return 2
    print(f"Rendered generated view: {output}")
    return 0


def schema_command(version: str = "v3") -> int:
    versions = {
        "v1": (SCHEMA_ASSET_PATH_V1, SCHEMA_VERSION_V1),
        "v2": (SCHEMA_ASSET_PATH_V2, SCHEMA_VERSION_V2),
        "v3": (SCHEMA_ASSET_PATH_V3, SCHEMA_VERSION_V3),
    }
    if version not in versions:
        print(f"Unsupported schema version: {version}", file=sys.stderr)
        return 2
    schema_path, expected = versions[version]
    try:
        schema = _load_json(schema_path)
    except ExecutionContractError as exc:
        print(exc, file=sys.stderr)
        return 2
    if _text(((schema.get("properties") or {}).get("schema_version") or {}).get("const")) != expected:
        print("Schema asset version does not match the validator", file=sys.stderr)
        return 2
    print(json.dumps(schema, ensure_ascii=False, indent=2))
    return 0


