def _validate_v3_material_realizations(
    base: Path,
    payload: Mapping[str, Any],
    result: ValidationResult,
) -> dict[str, Mapping[str, Any]]:
    """Validate real, hash-bound acquisition materials for v3 MVMR lineage."""

    raw = payload.get("material_realizations")
    if not isinstance(raw, list) or not raw:
        result.add(
            "ME.MATERIAL.REALIZATIONS_MISSING",
            "ERROR",
            "v3 execution requires at least one hash-bound material realization",
            "material_realizations",
        )
        return {}
    records: dict[str, Mapping[str, Any]] = {}
    for index, item in enumerate(raw):
        path = f"material_realizations[{index}]"
        if not isinstance(item, Mapping):
            result.add(
                "ME.MATERIAL.REALIZATION_INVALID",
                "ERROR",
                "Material realization must be an object",
                path,
            )
            continue
        material_id = _text(item.get("material_id")).upper()
        if not ID_PATTERN.fullmatch(material_id):
            result.add(
                "ME.MATERIAL.REALIZATION_INVALID",
                "ERROR",
                "Material realization requires a stable material_id",
                f"{path}.material_id",
            )
            continue
        if material_id in records:
            result.add(
                "ME.MATERIAL.REALIZATION_DUPLICATE",
                "ERROR",
                f"Material {material_id} has more than one realization",
                f"{path}.material_id",
            )
        records[material_id] = item
        status = _text(item.get("status")).upper()
        if status not in {"REALIZED", "PARTIAL", "BLOCKED", "FAILED"}:
            result.add(
                "ME.MATERIAL.STATUS",
                "ERROR",
                f"Unsupported material realization status {status!r}",
                f"{path}.status",
            )
        artifact_ids = item.get("artifact_ids")
        if not isinstance(artifact_ids, list):
            result.add(
                "ME.MATERIAL.ARTIFACT_INVALID",
                "ERROR",
                "material realization artifact_ids must be an array",
                f"{path}.artifact_ids",
            )
        else:
            _string_id_list(result, artifact_ids, f"{path}.artifact_ids")
        raw_path = _text(item.get("path"))
        declared_sha256 = _text(item.get("sha256"))
        if status == "REALIZED" or raw_path or declared_sha256:
            source_path = _safe_workspace_path(base, raw_path)
            if source_path is None:
                result.add(
                    "ME.MATERIAL.PATH_UNSAFE",
                    "ERROR",
                    "Realized material path must resolve inside the workspace",
                    f"{path}.path",
                )
            elif not source_path.is_file():
                result.add(
                    "ME.MATERIAL.FILE_MISSING",
                    "ERROR",
                    f"Realized material file is missing: {raw_path}",
                    f"{path}.path",
                )
            if not SHA256_PATTERN.fullmatch(declared_sha256):
                result.add(
                    "ME.MATERIAL.HASH_MISSING",
                    "ERROR",
                    "Realized material requires a SHA-256 digest",
                    f"{path}.sha256",
                )
            elif source_path is not None and source_path.is_file():
                if _sha256(source_path).casefold() != declared_sha256.casefold():
                    result.add(
                        "ME.MATERIAL.HASH_CHANGED",
                        "ERROR",
                        f"Realized material content changed: {raw_path}",
                        f"{path}.sha256",
                    )
    return records


def _design_state(
    base: Path,
    result: ValidationResult,
    *,
    expected_schema: str,
) -> tuple[Mapping[str, Any] | None, dict[str, Any]]:
    try:
        design = _load_json(base / DESIGN_REL)
    except ExecutionContractError as exc:
        result.add("ME.DESIGN.MISSING", "ERROR", str(exc), DESIGN_REL.as_posix())
        return None, {}
    schema = _text(design.get("schema_version"))
    if schema != expected_schema:
        code = (
            "ME.DESIGN.FUTURE"
            if schema.startswith("cnki-research-design/v")
            and schema not in {
                "cnki-research-design/v1",
                DESIGN_SCHEMA_VERSION_V2,
                DESIGN_SCHEMA_VERSION_V3,
                DESIGN_SCHEMA_VERSION_V4,
            }
            else "ME.DESIGN.MIGRATION_REQUIRED"
        )
        result.add(
            code,
            "ERROR",
            f"Method execution requires {expected_schema}; found {schema or 'missing schema'}",
            DESIGN_REL.as_posix(),
        )
        return design, {}
    questions = {
        _text(item.get("id")).upper(): item
        for item in design.get("research_questions") or []
        if isinstance(item, Mapping) and _text(item.get("id"))
    }
    claims = {
        _text(item.get("id")).upper(): item
        for item in design.get("claims") or []
        if isinstance(item, Mapping) and _text(item.get("id"))
    }
    evidence = {
        _text(item.get("id")).upper(): item
        for item in design.get("evidence") or []
        if isinstance(item, Mapping) and _text(item.get("id"))
    }
    routes = {
        _text(item.get("id")).upper(): item
        for item in design.get("method_routes") or []
        if isinstance(item, Mapping) and _text(item.get("id"))
    }
    case_design = (
        design.get("case_design")
        if isinstance(design.get("case_design"), Mapping)
        else {}
    )
    cases = {
        _text(item.get("id")).upper(): item
        for item in case_design.get("cases") or []
        if isinstance(item, Mapping) and _text(item.get("id"))
    }
    scopes = {
        _text(item.get("id")).upper(): item
        for item in case_design.get("scope_conditions") or []
        if isinstance(item, Mapping) and _text(item.get("id"))
    }
    comparisons = {
        _text(item.get("id")).upper(): item
        for item in case_design.get("comparisons") or []
        if isinstance(item, Mapping) and _text(item.get("id"))
    }
