@dataclass(frozen=True)
class Issue:
    code: str
    severity: str
    message: str
    path: str = ""


@dataclass
class ValidationResult:
    issues: list[Issue] = field(default_factory=list)

    def add(self, code: str, severity: str, message: str, path: str = "") -> None:
        issue = Issue(code=code, severity=severity, message=message, path=path)
        if issue not in self.issues:
            self.issues.append(issue)

    @property
    def errors(self) -> list[Issue]:
        return [issue for issue in self.issues if issue.severity == "ERROR"]

    @property
    def status(self) -> str:
        return "FAIL" if self.errors else "PASS"


class ExecutionContractError(ValueError):
    """Raised for malformed or unsafe execution-contract operations."""


def _text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value.strip()
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, Mapping):
        return "; ".join(f"{key}={_text(item)}" for key, item in value.items() if _text(item))
    if isinstance(value, Sequence) and not isinstance(value, (str, bytes, bytearray)):
        return "; ".join(_text(item) for item in value if _text(item))
    return str(value).strip()


def _substantive(value: Any) -> bool:
    return bool(_text(value) and _text(value).casefold() not in {"-", "--", "n/a", "na", "none", "null"})


def _contains_review(value: Any) -> bool:
    return bool(NEEDS_REVIEW.search(_text(value)))


def _looks_repetitive(value: Any) -> bool:
    text = _text(value)
    compact = re.sub(r"[\W_]+", "", text, flags=re.UNICODE).casefold()
    if len(compact) < 12:
        return False
    for unit_length in range(1, min(24, len(compact) // 3) + 1):
        if len(compact) % unit_length:
            continue
        unit = compact[:unit_length]
        if unit and unit * (len(compact) // unit_length) == compact:
            return True
    tokens = re.findall(r"[A-Za-z][A-Za-z0-9_-]*|[\u3400-\u9fff]{2,}", text.casefold())
    return len(tokens) >= 5 and len(set(tokens)) <= 1


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _canonical_digest(value: Mapping[str, Any]) -> str:
    canonical = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _is_json_value(value: Any) -> bool:
    """Return whether a value has one portable, finite JSON representation."""

    if value is None or isinstance(value, (str, bool, int)):
        return True
    if isinstance(value, float):
        return math.isfinite(value)
    if isinstance(value, list):
        return all(_is_json_value(item) for item in value)
    if isinstance(value, Mapping):
        return all(
            isinstance(key, str) and _is_json_value(item)
            for key, item in value.items()
        )
    return False


def _numeric_values_equal(declared: Any, observed: Any) -> bool:
    try:
        left = float(declared)
        right = float(observed)
    except (TypeError, ValueError):
        return _text(declared) == _text(observed)
    tolerance = max(1e-12, 1e-9 * max(abs(left), abs(right), 1.0))
    return abs(left - right) <= tolerance


def _resolve_numeric_locator(
    base: Path,
    artifact: Mapping[str, Any],
    locator: str,
) -> tuple[Any | None, str]:
    candidate = _safe_workspace_path(base, artifact.get("path"))
    if candidate is None or not candidate.is_file():
        return None, "artifact is missing or outside the workspace"
    if locator.startswith("json:"):
        pointer = locator[5:]
        if pointer and not pointer.startswith("/"):
            return None, "JSON locator must use RFC 6901 pointer syntax"
        try:
            value: Any = json.loads(candidate.read_text(encoding="utf-8-sig"))
        except (OSError, json.JSONDecodeError) as exc:
            return None, f"cannot parse JSON artifact: {exc}"
        if not pointer:
            return value, ""
        for raw in pointer.split("/")[1:]:
            token = raw.replace("~1", "/").replace("~0", "~")
            if isinstance(value, Mapping) and token in value:
                value = value[token]
            elif isinstance(value, list) and token.isdigit() and int(token) < len(value):
                value = value[int(token)]
            else:
                return None, f"JSON pointer token {token!r} is unresolved"
        return value, ""
    match = re.fullmatch(r"csv:row=(\d+),column=([^,]+)", locator)
    if match:
        row_number = int(match.group(1))
        column = match.group(2).strip()
        if row_number < 1 or not column:
            return None, "CSV locator requires a 1-based data row and column name"
        try:
            with candidate.open("r", encoding="utf-8-sig", newline="") as handle:
                rows = list(csv.DictReader(handle))
        except (OSError, UnicodeError) as exc:
            return None, f"cannot parse CSV artifact: {exc}"
        if row_number > len(rows) or column not in (rows[0] if rows else {}):
            return None, "CSV row or column is unresolved"
        return rows[row_number - 1].get(column), ""
    match = re.fullmatch(r"text:line=(\d+)", locator)
    if match:
        line_number = int(match.group(1))
        try:
            lines = candidate.read_text(encoding="utf-8-sig").splitlines()
        except (OSError, UnicodeError) as exc:
            return None, f"cannot parse text artifact: {exc}"
        if line_number < 1 or line_number > len(lines):
            return None, "text line is unresolved"
        return lines[line_number - 1].strip(), ""
    return None, "unsupported locator; use json:/pointer, csv:row=N,column=NAME, or text:line=N"


def _resolve_analysis_unit_locator(
    base: Path,
    artifacts: Mapping[str, Mapping[str, Any]],
    locator: str,
) -> tuple[str, Any | None, str]:
    """Resolve ``artifact:ART-ID#<typed locator>`` to a non-empty unit."""

    match = re.fullmatch(
        r"artifact:([A-Z][A-Z0-9_-]{1,31})#(.+)",
        locator,
        re.IGNORECASE,
    )
    if not match:
        return "", None, (
            "analysis-unit locator must use artifact:ART-ID#json:/pointer, "
            "#csv:row=N,column=NAME, or #text:line=N"
        )
    artifact_id = match.group(1).upper()
    artifact = artifacts.get(artifact_id)
    if artifact is None:
        return artifact_id, None, f"analysis-unit artifact {artifact_id!r} is unresolved"
    value, error = _resolve_numeric_locator(base, artifact, match.group(2))
    if error:
        return artifact_id, None, error
    if value is None or value == "" or value == [] or value == {}:
        return artifact_id, value, "analysis-unit locator resolves to an empty value"
    return artifact_id, value, ""


def _atomic_write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(
        prefix=f".{path.name}.",
        suffix=".tmp",
        dir=str(path.parent),
    )
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content.rstrip() + "\n")
        os.replace(temporary, path)
    except Exception:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def _atomic_write_json(path: Path, payload: Mapping[str, Any]) -> None:
    _atomic_write_text(path, json.dumps(payload, ensure_ascii=False, indent=2) + "\n")


def _load_json(path: Path) -> Mapping[str, Any]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8-sig"))
    except FileNotFoundError as exc:
        raise ExecutionContractError(f"JSON file is missing: {path}") from exc
    except (OSError, json.JSONDecodeError) as exc:
        raise ExecutionContractError(f"Cannot read JSON file {path}: {exc}") from exc
    if not isinstance(payload, Mapping):
        raise ExecutionContractError(f"JSON root must be an object: {path}")
    return payload


def resolve_path(path: Path) -> tuple[Path, Path]:
    resolved = path.resolve()
    if resolved.name == EXECUTION_REL.name:
        return resolved.parent, resolved
    return resolved, resolved / EXECUTION_REL


def _safe_workspace_path(base: Path, raw: Any) -> Path | None:
    token = _text(raw)
    if not token:
        return None
    candidate = Path(token)
    resolved = candidate.resolve() if candidate.is_absolute() else (base / candidate).resolve()
    try:
        resolved.relative_to(base.resolve())
    except ValueError:
        return None
    return resolved


